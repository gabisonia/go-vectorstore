package vectordata_test

import (
	"errors"
	"strings"
	"testing"

	"github.com/gabisonia/go-vectorstore/stores/memory"
	"github.com/gabisonia/go-vectorstore/vectordata"
)

// A decoder alone can receive a generated key but cannot send it back to Get,
// Delete or a filter. Reject that binding before a collection can be created.
type decodeOnlyUUID struct{ text string }

func (u *decodeOnlyUUID) UnmarshalText(text []byte) error { u.text = string(text); return nil }

type encodeOnlyUUID struct{ text string }

func (u encodeOnlyUUID) MarshalText() ([]byte, error) { return []byte(u.text), nil }

type stringerUUID struct{ text string }

func (u stringerUUID) String() string                   { return u.text }
func (u *stringerUUID) UnmarshalText(text []byte) error { u.text = string(text); return nil }

type mappedUUID struct{ text string }

func (u mappedUUID) MarshalText() ([]byte, error)     { return []byte(u.text), nil }
func (u *mappedUUID) UnmarshalText(text []byte) error { u.text = string(text); return nil }

func TestUUIDKeyBindingsRequireBothTextDirections(t *testing.T) {
	type explicit struct {
		ID decodeOnlyUUID `vectordata:"key,type=uuid"`
	}
	type generated struct {
		ID decodeOnlyUUID `vectordata:"key,type=uuid,generated"`
	}
	t.Run("explicit", func(t *testing.T) {
		if _, err := vectordata.NewStructCodec[explicit](nil); !errors.Is(err, vectordata.ErrSchemaMismatch) {
			t.Fatalf("decode-only model key accepted: %v", err)
		}
	})
	t.Run("generated", func(t *testing.T) {
		if _, err := vectordata.NewStructCodec[generated](nil); !errors.Is(err, vectordata.ErrSchemaMismatch) {
			t.Fatalf("decode-only generated key accepted: %v", err)
		}
	})
	store := memory.New()
	definition := vectordata.CollectionDefinition{Key: vectordata.KeyProperty{Name: "ID", Type: vectordata.KeyUUID, AutoGenerated: true}}
	base, err := store.GetModelCollection("keys", definition, vectordata.ModelCollectionOptions{})
	if err != nil {
		t.Fatal(err)
	}
	if _, err := vectordata.NewTypedModelCollection[decodeOnlyUUID, vectordata.ModelRecord](base, recordPassthroughCodec{}); !errors.Is(err, vectordata.ErrSchemaMismatch) {
		t.Fatalf("decode-only typed key accepted: %v", err)
	}
	if _, err := vectordata.NewTypedModelCollection[encodeOnlyUUID, vectordata.ModelRecord](base, recordPassthroughCodec{}); !errors.Is(err, vectordata.ErrSchemaMismatch) {
		t.Fatalf("encode-only typed key accepted: %v", err)
	}
	// An explicit definition must enforce the same model-field rule as tags.
	if _, err := vectordata.NewStructCodec[struct{ ID decodeOnlyUUID }](&definition); !errors.Is(err, vectordata.ErrSchemaMismatch) {
		t.Fatalf("explicit definition bypassed UUID binding validation: %v", err)
	}
	for _, kind := range []string{"field", "parameter"} {
		t.Run("ensure/"+kind, func(t *testing.T) {
			name := "invalid_" + kind
			var err error
			if kind == "field" {
				_, err = vectordata.EnsureTypedModelCollection[string, generated](t.Context(), store, name, nil, vectordata.ModelCollectionOptions{})
			} else {
				_, err = vectordata.EnsureTypedModelCollection[decodeOnlyUUID, struct{ ID string }](t.Context(), store, name, &definition, vectordata.ModelCollectionOptions{})
			}
			if !errors.Is(err, vectordata.ErrSchemaMismatch) {
				t.Fatalf("invalid UUID binding created storage: %v", err)
			}
			if exists, err := store.CollectionExists(t.Context(), name); err != nil || exists {
				t.Fatalf("invalid UUID binding touched storage: %v, %v", exists, err)
			}
		})
	}
}

func TestUUIDKeyBindingsPreserveSupportedMappings(t *testing.T) {
	t.Run("text", func(t *testing.T) {
		testUUIDKeyMapping[mappedUUID](t, mappedUUID{text: strings.ToUpper("8f516db6-38ca-4e8f-ad79-d71b015f5419")})
	})
	t.Run("stringer", func(t *testing.T) {
		testUUIDKeyMapping[stringerUUID](t, stringerUUID{text: strings.ToUpper("8f516db6-38ca-4e8f-ad79-d71b015f5419")})
	})
	t.Run("string", func(t *testing.T) { testUUIDKeyMapping[string](t, "8F516DB6-38CA-4E8F-AD79-D71B015F5419") })
	t.Run("named_string", func(t *testing.T) {
		type UUID string
		testUUIDKeyMapping[UUID](t, "8F516DB6-38CA-4E8F-AD79-D71B015F5419")
	})
}

func testUUIDKeyMapping[K comparable](t *testing.T, input K) {
	t.Helper()
	type model struct{ ID K }
	d := vectordata.CollectionDefinition{Key: vectordata.KeyProperty{Name: "ID", Type: vectordata.KeyUUID, AutoGenerated: true}}
	c, err := vectordata.EnsureTypedModelCollection[K, model](t.Context(), memory.New(), "valid_keys", &d, vectordata.ModelCollectionOptions{})
	if err != nil {
		t.Fatal(err)
	}
	key, err := c.InsertOne(t.Context(), model{ID: input})
	if err != nil {
		t.Fatal(err)
	}
	canonical, err := d.NormalizeKey(key)
	if err != nil || canonical != "8f516db6-38ca-4e8f-ad79-d71b015f5419" {
		t.Fatalf("explicit key: %v, %v", canonical, err)
	}
	generated, err := c.InsertOne(t.Context(), model{})
	if err != nil || generated == key {
		t.Fatalf("generated key: %v, %v", generated, err)
	}
	for _, key := range []K{key, generated} {
		got, err := c.Get(t.Context(), key, vectordata.RetrievalOptions{})
		if err != nil || got.ID != key {
			t.Fatalf("round-trip: %+v, %v", got, err)
		}
		if count, err := c.Count(t.Context(), vectordata.Eq(vectordata.Column("ID"), key)); err != nil || count != 1 {
			t.Fatalf("key filter: %d, %v", count, err)
		}
		if deleted, err := c.DeleteOne(t.Context(), key); err != nil || !deleted {
			t.Fatalf("key delete: %v, %v", deleted, err)
		}
	}
}
