func (d CollectionDefinition) NormalizeKey(key any) (any, error) {
	if isNilValue(key) {
		return nil, fmt.Errorf("%w: missing key", ErrInvalidRecord)
	}
	switch d.Key.Type {
	case KeyString:
		v := reflect.ValueOf(key)
		if v.Kind() == reflect.String && v.String() != "" {
			return v.String(), nil
		}
	case KeyInt64:
		v := reflect.ValueOf(key)
		switch v.Kind() {
		case reflect.Int, reflect.Int8, reflect.Int16, reflect.Int32, reflect.Int64:
			return v.Int(), nil
		case reflect.Uint, reflect.Uint8, reflect.Uint16, reflect.Uint32, reflect.Uint64:
			if v.Uint() <= math.MaxInt64 {
				return int64(v.Uint()), nil
			}
		}
	case KeyUUID:
		s, ok := key.(string)
		if !ok && reflect.ValueOf(key).Kind() == reflect.String {
			s = reflect.ValueOf(key).String()
		}
		if text, yes := key.(encoding.TextMarshaler); yes {
			raw, err := text.MarshalText()
			if err != nil {
				return nil, fmt.Errorf("%w: %v", ErrInvalidRecord, err)
			}
			s = string(raw)
		}
		if s == "" {
			if v, yes := key.(fmt.Stringer); yes {
				s = v.String()
			}
		}
		if len(s) == 36 {
			valid := true
			for i, c := range s {
				if i == 8 || i == 13 || i == 18 || i == 23 {
					valid = valid && c == '-'
				} else {
					valid = valid && (c >= '0' && c <= '9' || c >= 'a' && c <= 'f' || c >= 'A' && c <= 'F')
				}
			}
			if valid {
				return strings.ToLower(s), nil
			}
		}
	}
	return nil, fmt.Errorf("%w: invalid %s key", ErrInvalidRecord, d.Key.Type)
}
func normalizeData(value any, p DataProperty) (any, error) {
	if value == nil {
		if p.Optional {
			return nil, nil
		}
		return nil, fmt.Errorf("%w: missing data property %q", ErrInvalidRecord, p.Name)
	}
	invalid := func() (any, error) {
		return nil, fmt.Errorf("%w: invalid %s data property %q", ErrInvalidRecord, p.Type, p.Name)
	}
	switch p.Type {
	case TypeInt64Array, TypeFloat64Array, TypeBoolArray, TypeUUIDArray, TypeTimeArray, TypeDateOnlyArray, TypeTimeOnlyArray, TypeDecimalArray:
		return normalizeNativeArray(value, p)
	case TypeDecimal:
		if isNilValue(value) {
			if p.Optional {
				return nil, nil
			}
			return invalid()
		}
		return normalizeDecimal(value)
	case TypeDateOnly, TypeTimeOnly:
		if isNilValue(value) {
			if p.Optional {
				return nil, nil
			}
			return invalid()
		}
		return normalizeCalendar(value, p.Type)
	case TypeUUID:
		if isNilValue(value) {
			if p.Optional {
				return nil, nil
			}
			return invalid()
		}
		return (CollectionDefinition{Key: KeyProperty{Type: KeyUUID}}).NormalizeKey(value)
	case TypeBytes:
		v := reflect.ValueOf(value)
		if v.Kind() == reflect.Slice && v.Type().Elem().Kind() == reflect.Uint8 {
			if v.IsNil() {
				if p.Optional {
					return nil, nil
				}
				return invalid()
			}
			return append([]byte{}, v.Bytes()...), nil
		}
	case TypeString:
		if v := reflect.ValueOf(value); v.Kind() == reflect.String {
			return v.String(), nil
		}
	case TypeInt64:
		return (CollectionDefinition{Key: KeyProperty{Type: KeyInt64}}).NormalizeKey(value)
	case TypeFloat64:
		v := reflect.ValueOf(value)
		var x float64
		switch v.Kind() {
		case reflect.Float32, reflect.Float64:
			x = v.Float()
		case reflect.Int, reflect.Int8, reflect.Int16, reflect.Int32, reflect.Int64:
			x = float64(v.Int())
		default:
			return invalid()
		}
		if !math.IsNaN(x) && !math.IsInf(x, 0) {
			return x, nil
		}
	case TypeBool:
		if v := reflect.ValueOf(value); v.Kind() == reflect.Bool {
			return v.Bool(), nil
		}
	case TypeTime:
		if x, ok := value.(time.Time); ok {
			return x, nil
		}
	case TypeStringArray:
		if x, ok := value.([]string); ok {
			if x == nil {
				x = []string{}
			}
			return append([]string{}, x...), nil
		}
	case TypeJSON:
		raw, err := json.Marshal(value)
		if err != nil {
			return nil, fmt.Errorf("%w: property %q: %v", ErrInvalidRecord, p.Name, err)
		}
		dec := json.NewDecoder(strings.NewReader(string(raw)))
		dec.UseNumber()
		var out any
		if err := dec.Decode(&out); err != nil {
			return nil, err
		}
		if out == nil {
			return JSONNull{}, nil
		}
		return out, nil
	}
	return invalid()
}

// NormalizeModelData validates a native property value and copies mutable values.
// UUID values become canonical strings; timestamp arrays use UTC microseconds.
// Nil byte slices and explicit native arrays (except legacy string_array) become
// SQL NULL only for optional properties; non-nil empty slices stay empty values.
func NormalizeModelData(value any, p DataProperty) (any, error) {
	return normalizeData(value, p)
}

// PrepareModelRecords copies and validates inputs and batches automatic embedding
// generation per property. Providers call this before opening a write transaction.
func PrepareModelRecords(ctx context.Context, d CollectionDefinition, opts ModelCollectionOptions, records []ModelRecord) ([]ModelRecord, error) {
	if err := ctx.Err(); err != nil {
		return nil, err
	}
	if _, err := opts.WithDefaults(ModelCollectionOptions{}); err != nil {
		return nil, err
	}
	out := make([]ModelRecord, len(records))
	for i, r := range records {
		if err := ctx.Err(); err != nil {
			return nil, err
		}
		out[i] = ModelRecord{Data: map[string]any{}, Vectors: map[string][]float32{}}
		if r.Key != nil || !d.Key.AutoGenerated {
			key, err := d.NormalizeKey(r.Key)
			if err != nil {
				return nil, err
			}
			out[i].Key = key
		}
		for name := range r.Data {
			found := false
			for _, p := range d.Data {
				found = found || p.Name == name
			}
			if !found {
				return nil, fmt.Errorf("%w: unknown data property %q", ErrInvalidRecord, name)
			}
		}
		for _, p := range d.Data {
			value, err := normalizeData(r.Data[p.Name], p)
			if err != nil {
				return nil, err
			}
			out[i].Data[p.Name] = value
		}
		for name, vector := range r.Vectors {
			found := false
			for _, p := range d.Vectors {
				found = found || p.Name == name && p.Kind != VectorBinary && p.Kind != VectorSparse
			}
			if !found {
				return nil, fmt.Errorf("%w: unknown vector property %q", ErrInvalidRecord, name)
			}
			if vector != nil {
				out[i].Vectors[name] = append([]float32{}, vector...)
			}
		}
		for name := range r.BinaryVectors {
			found := false
			for _, p := range d.Vectors {
				found = found || p.Name == name && p.Kind == VectorBinary
			}
			if !found {
				return nil, fmt.Errorf("%w: unknown/non-binary property %q", ErrInvalidRecord, name)
			}
		}
		for _, p := range d.Vectors {
			if p.Kind == VectorSparse {
				raw, present := r.SparseVectors[p.Name]
				if !present && p.Optional {
					continue
				}
				v, err := NormalizeSparseVector(raw, p)
				if err != nil {
					return nil, fmt.Errorf("%w: record %d: %w", ErrInvalidRecord, i, err)
				}
				if out[i].SparseVectors == nil {
					out[i].SparseVectors = map[string]SparseVector{}
				}
				out[i].SparseVectors[p.Name] = v
			}
			if p.Kind == VectorBinary {
				raw, present := r.BinaryVectors[p.Name]
				if !present && p.Optional {
					continue
				}
				v, err := NormalizeBinaryVector(raw, p)
				if err != nil {
					return nil, fmt.Errorf("%w: record %d: %w", ErrInvalidRecord, i, err)
				}
				if out[i].BinaryVectors == nil {
					out[i].BinaryVectors = map[string]BinaryVector{}
				}
				out[i].BinaryVectors[p.Name] = v
			}
		}
		for name := range r.SparseVectors {
			found := false
			for _, p := range d.Vectors {
				found = found || p.Name == name && p.Kind == VectorSparse
			}
			if !found {
				return nil, fmt.Errorf("%w: unknown/non-sparse property %q", ErrInvalidRecord, name)
			}
		}
	}
	for _, p := range d.Vectors {
		if p.Kind == VectorBinary || p.Kind == VectorSparse {
			continue
		}
		var positions []int
		var inputs []string
		for i := range out {
			if out[i].Vectors[p.Name] == nil && p.Optional && (p.SourceProperty == "" || out[i].Data[p.SourceProperty] == nil) {
				delete(out[i].Vectors, p.Name)
				continue
			}
			if len(out[i].Vectors[p.Name]) == 0 && p.SourceProperty != "" && (!p.Optional || out[i].Vectors[p.Name] == nil) {
				value, ok := out[i].Data[p.SourceProperty].(string)
				if !ok {
					return nil, fmt.Errorf("%w: missing embedding source %q", ErrInvalidRecord, p.SourceProperty)
				}
				positions = append(positions, i)
				inputs = append(inputs, value)
			} else {
				vector, err := NormalizeModelVector(out[i].Vectors[p.Name], p)
				if err != nil {
					return nil, fmt.Errorf("%w: record %d: %w", ErrInvalidRecord, i, err)
				}
				out[i].Vectors[p.Name] = vector
			}
		}
		if len(inputs) > 0 {
			embedder := p.Embedder
			if isNilValue(embedder) {
				embedder = opts.Embedder
			}
			if isNilValue(embedder) {
				return nil, fmt.Errorf("%w: no embedder for %q", ErrUnsupported, p.Name)
			}
			batchSize := opts.EmbeddingBatchSize
			if batchSize == 0 {
				batchSize = len(inputs)
			}
			for start := 0; start < len(inputs); {
				if err := ctx.Err(); err != nil {
					return nil, err
				}
				end := start + min(batchSize, len(inputs)-start)
				vectors, err := embedder.Embed(ctx, inputs[start:end:end])
				if err != nil {
					return nil, err
				}
				if err := ctx.Err(); err != nil {
					return nil, err
				}
				if len(vectors) != end-start {
					return nil, fmt.Errorf("%w: embedder returned %d vectors for %d inputs", ErrInvalidVector, len(vectors), end-start)
				}
				for j, vector := range vectors {
					i := positions[start+j]
					vector, err := NormalizeModelVector(vector, p)
					if err != nil {
						return nil, fmt.Errorf("%w: record %d: %w", ErrInvalidRecord, i, err)
					}
					// Embedders may reuse their output buffers on the next call.
					if p.Precision != VectorFloat16 {
						vector = append([]float32(nil), vector...)
					}
					out[i].Vectors[p.Name] = vector
				}
				start = end
			}
		}
	}
	return out, nil
}
func EmbedQuery(ctx context.Context, text string, p VectorProperty, opts ModelCollectionOptions) ([]float32, error) {
	if err := ctx.Err(); err != nil {
		return nil, err
	}
	if p.Kind == VectorBinary || p.Kind == VectorSparse {
		return nil, fmt.Errorf("%w: binary/sparse queries require explicit vector values", ErrUnsupported)
	}
	if _, err := opts.WithDefaults(ModelCollectionOptions{}); err != nil {
		return nil, err
	}
	embedder := p.Embedder
	if isNilValue(embedder) {
		embedder = opts.Embedder
	}
	if isNilValue(embedder) {
		return nil, fmt.Errorf("%w: text search requires an embedder", ErrUnsupported)
	}
	vectors, err := embedder.Embed(ctx, []string{text})
	if err != nil {
		return nil, err
	}
	if err := ctx.Err(); err != nil {
		return nil, err
	}
	if len(vectors) != 1 {
		return nil, fmt.Errorf("%w: expected one query embedding", ErrInvalidVector)
	}
	return NormalizeModelVector(vectors[0], p)
}
func ValidateModelSearchOptions(top int, opts ModelSearchOptions) error {
	if top <= 0 || opts.Skip < 0 || top > int(^uint(0)>>1)-opts.Skip {
		return fmt.Errorf("%w: top must be positive and skip nonnegative", ErrInvalidSearchOptions)
	}
	for _, threshold := range []*float64{opts.DistanceThreshold, opts.ScoreThreshold} {
		if threshold != nil && (math.IsNaN(*threshold) || math.IsInf(*threshold, 0)) {
			return fmt.Errorf("%w: thresholds must be finite", ErrInvalidSearchOptions)
		}
	}
	return nil
}
func ValidateModelSearch(vector []float32, top int, opts ModelSearchOptions, p VectorProperty) error {
	if err := ValidateModelSearchOptions(top, opts); err != nil {
		return err
	}
	return ValidateModelVector(vector, p)
}

// ValidateModelQuery restricts portable ordering to keys and scalar data properties.
func ValidateModelQuery(d CollectionDefinition, top int, opts QueryOptions) error {
	if top <= 0 || opts.Skip < 0 {
		return fmt.Errorf("%w: positive top and nonnegative skip required", ErrInvalidSearchOptions)
	}
	for _, sort := range opts.OrderBy {
		if sort.Property == d.Key.Name {
			continue
		}
		found := false
		for _, p := range d.Data {
			if p.Name == sort.Property {
				found = true
				_, array := p.Type.ArrayElementType()
				if p.Type == TypeJSON || array {
					return fmt.Errorf("%w: ordering JSON or array properties is provider-specific", ErrUnsupported)
				}
			}
		}
		if !found {
			return fmt.Errorf("%w: unknown sort property %q", ErrInvalidFilter, sort.Property)
		}
	}
	return nil
}

// HasModelVector reports presence without interpreting zero-valued vector components.
func HasModelVector(r ModelRecord, p VectorProperty) bool {
	switch p.Kind {
	case VectorBinary:
		_, ok := r.BinaryVectors[p.Name]
		return ok
	case VectorSparse:
		_, ok := r.SparseVectors[p.Name]
		return ok
	default:
		return r.Vectors[p.Name] != nil
	}
}
