// KeyType describes the native storage type of a model key.
type KeyType string

const (
	KeyString KeyType = "string"
	KeyInt64  KeyType = "int64"
	KeyUUID   KeyType = "uuid"
)

// DataType describes portable data properties supported by model collections.
type DataType string

const (
	TypeString      DataType = "string"
	TypeInt64       DataType = "int64"
	TypeFloat64     DataType = "float64"
	TypeBool        DataType = "bool"
	TypeJSON        DataType = "json"
	TypeTime        DataType = "time"
	TypeStringArray DataType = "string_array"
)

type KeyProperty struct {
	Name, StorageName string
	Type              KeyType
	AutoGenerated     bool
}
type DataProperty struct {
	Name, StorageName                      string
	Type                                   DataType
	Optional, IsIndexed, IsFullTextIndexed bool
}
type VectorProperty struct {
	Name, StorageName string
	Dimensions        int
	Metric            DistanceMetric
	Index             *VectorIndexOptions
	// SourceProperty names a string data property used for automatic embedding.
	SourceProperty string
	Embedder       Embedder `json:"-"`
}

// CollectionDefinition is shared by mapping, schema creation, validation and search.
type CollectionDefinition struct {
	Key     KeyProperty
	Data    []DataProperty
	Vectors []VectorProperty
}

// JSONNull distinguishes a JSON null value from a native SQL NULL in dynamic records.
type JSONNull struct{}

func (JSONNull) MarshalJSON() ([]byte, error) { return []byte("null"), nil }

// ModelRecord is the dynamic counterpart of a typed application model. Maps use logical property names.
type ModelRecord struct {
	Key     any
	Data    map[string]any
	Vectors map[string][]float32
}

// Embedder generates one vector for each input, preserving input order. Implementations must honor ctx.
type Embedder interface {
	Embed(context.Context, []string) ([][]float32, error)
}
type EmbeddingFunc func(context.Context, []string) ([][]float32, error)

func (f EmbeddingFunc) Embed(ctx context.Context, inputs []string) ([][]float32, error) {
	return f(ctx, inputs)
}

type ModelCollectionOptions struct{ Embedder Embedder }
type RetrievalOptions struct{ IncludeVectors bool }
type SortField struct {
	Property   string
	Descending bool
}
type QueryOptions struct {
	Skip           int
	OrderBy        []SortField
	IncludeVectors bool
}
type ModelSearchOptions struct {
	VectorProperty string
	Filter         Filter
	Skip           int
	IncludeVectors bool
	// DistanceThreshold is an upper bound on raw backend distance.
	DistanceThreshold *float64
	// ScoreThreshold is a lower bound on this library's higher-is-better similarity score.
	ScoreThreshold *float64
	// ProviderOptions is an optional connector-specific value; unknown values must be rejected.
	ProviderOptions any
}
type ScoreKind string

const (
	ScoreSimilarity ScoreKind = "similarity"
	ScoreRRF        ScoreKind = "reciprocal_rank_fusion"
)

type ModelSearchResult struct {
	Record          ModelRecord
	Distance, Score float64
	ScoreKind       ScoreKind
}
type HybridSearchOptions struct {
	ModelSearchOptions
	TextProperty   string
	CandidateLimit int
	RRFConstant    int
}

// CollectionManager manages collections within a provider's configured namespace.
type CollectionManager interface {
	ListCollectionNames(context.Context) ([]string, error)
	CollectionExists(context.Context, string) (bool, error)
	DeleteCollection(context.Context, string) error
}
type ModelStore interface {
	CollectionManager
	GetModelCollection(string, CollectionDefinition, ModelCollectionOptions) (ModelCollection, error)
	EnsureModelCollection(context.Context, string, CollectionDefinition, ModelCollectionOptions) (ModelCollection, error)
}

// ModelCollection uses native keys and named properties. Get returns ErrNotFound;
// GetMany omits missing keys and makes no ordering guarantee. Reads exclude vectors by default.
type ModelCollection interface {
	Name() string
	Definition() CollectionDefinition
	Exists(context.Context) (bool, error)
	EnsureExists(context.Context) error
	EnsureDeleted(context.Context) error
	Insert(context.Context, []ModelRecord) ([]any, error)
	Upsert(context.Context, []ModelRecord) ([]any, error)
	Get(context.Context, any, RetrievalOptions) (ModelRecord, error)
	GetMany(context.Context, []any, RetrievalOptions) ([]ModelRecord, error)
	Query(context.Context, Filter, int, QueryOptions) ([]ModelRecord, error)
	QueryIter(context.Context, Filter, int, QueryOptions) iter.Seq2[ModelRecord, error]
	Delete(context.Context, []any) (int64, error)
	Count(context.Context, Filter) (int64, error)
	Search(context.Context, []float32, int, ModelSearchOptions) ([]ModelSearchResult, error)
	SearchIter(context.Context, []float32, int, ModelSearchOptions) iter.Seq2[ModelSearchResult, error]
	SearchText(context.Context, string, int, ModelSearchOptions) ([]ModelSearchResult, error)
}

// HybridSearcher is optional: providers without keyword search need not implement it.
type HybridSearcher interface {
	HybridSearch(context.Context, []float32, string, int, HybridSearchOptions) ([]ModelSearchResult, error)
	HybridSearchText(context.Context, string, string, int, HybridSearchOptions) ([]ModelSearchResult, error)
}

// OperationError adds provider context while preserving errors.Is/As through Unwrap.
type OperationError struct {
	Backend, Collection, Operation string
	Err                            error
}

func (e *OperationError) Error() string {
	return fmt.Sprintf("%s %s %q: %v", e.Backend, e.Operation, e.Collection, e.Err)
}
func (e *OperationError) Unwrap() error { return e.Err }

func validPropertyName(name string) bool {
	return name != "" && !strings.HasPrefix(name, "__vs_") && !strings.ContainsRune(name, 0) && len(name) <= 63
}

// Normalize validates a definition and returns a defensive copy with defaults applied.
func (d CollectionDefinition) Normalize() (CollectionDefinition, error) {
	fail := func(message string) (CollectionDefinition, error) {
		return CollectionDefinition{}, fmt.Errorf("%w: %s", ErrSchemaMismatch, message)
	}
	d = d.Clone()
	if d.Key.Type == "" {
		d.Key.Type = KeyString
	}
	if d.Key.Name == "" {
		return fail("key property name is required")
	}
	if d.Key.StorageName == "" {
		d.Key.StorageName = d.Key.Name
	}
	if d.Key.Type != KeyString && d.Key.Type != KeyInt64 && d.Key.Type != KeyUUID {
		return fail("unsupported key type")
	}
	if d.Key.AutoGenerated && d.Key.Type != KeyInt64 {
		return fail("generated keys require int64")
	}
	names, storage := map[string]bool{}, map[string]bool{}
	add := func(name, column string) bool {
		if !validPropertyName(name) || strings.TrimSpace(name) != name || !validPropertyName(column) || names[name] || storage[column] {
			return false
		}
		names[name] = true
		storage[column] = true
		return true
	}
	if !add(d.Key.Name, d.Key.StorageName) {
		return fail("invalid key name")
	}
	for i := range d.Data {
		p := &d.Data[i]
		if p.StorageName == "" {
			p.StorageName = p.Name
		}
		if !add(p.Name, p.StorageName) {
			return fail("invalid or duplicate data property")
		}
		switch p.Type {
		case TypeString, TypeInt64, TypeFloat64, TypeBool, TypeJSON, TypeTime, TypeStringArray:
		default:
			return fail("unsupported data property type")
		}
		if p.IsFullTextIndexed && p.Type != TypeString {
			return fail("full-text indexing requires a string property")
		}
		if p.IsIndexed && p.Type == TypeJSON {
			return fail("JSON properties need provider-specific indexing")
		}
	}
	for i := range d.Vectors {
		p := &d.Vectors[i]
		if p.StorageName == "" {
			p.StorageName = p.Name
		}
		if p.Metric == "" {
			p.Metric = DistanceCosine
		}
		if !add(p.Name, p.StorageName) || p.Dimensions <= 0 {
			return fail("invalid vector property")
		}
		if err := p.Metric.Validate(); err != nil {
			return CollectionDefinition{}, err
		}
		if p.Index != nil {
			if p.Index.Metric != "" && p.Index.Metric != p.Metric {
				return fail("vector index metric conflicts with property")
			}
			if p.Index.Method != "" && p.Index.Method != IndexMethodHNSW && p.Index.Method != IndexMethodIVFFlat {
				return fail("unsupported vector index method")
			}
			p.Index.Metric = p.Metric
			if p.Index.Method == "" {
				p.Index.Method = IndexMethodHNSW
			}
			if p.Index.Method == IndexMethodHNSW {
				if p.Index.HNSW.M == 0 {
					p.Index.HNSW.M = 16
				}
				if p.Index.HNSW.EfConstruction == 0 {
					p.Index.HNSW.EfConstruction = 64
				}
				if p.Index.HNSW.M < 2 || p.Index.HNSW.EfConstruction < 4 || p.Index.HNSW.M > p.Index.HNSW.EfConstruction/2 {
					return fail("invalid HNSW construction parameters")
				}
			} else {
				if p.Index.IVFFlat.Lists == 0 {
					p.Index.IVFFlat.Lists = 100
				}
				if p.Index.IVFFlat.Lists < 1 {
					return fail("invalid IVFFlat lists")
				}
			}

		}
		if p.SourceProperty != "" {
			found := false
			for _, field := range d.Data {
				if field.Name == p.SourceProperty && field.Type == TypeString {
					found = true
				}
			}
			if !found {
				return fail("embedding source must name a string data property")
			}
		}
	}
	return d, nil
}
func (d CollectionDefinition) Clone() CollectionDefinition {
	d.Data = append([]DataProperty(nil), d.Data...)
	d.Vectors = append([]VectorProperty(nil), d.Vectors...)
	for i := range d.Vectors {
		if d.Vectors[i].Index != nil {
			cp := *d.Vectors[i].Index
			d.Vectors[i].Index = &cp
		}
	}
	return d
}
func (d CollectionDefinition) Vector(name string) (VectorProperty, error) {
	if name == "" && len(d.Vectors) == 1 {
		return d.Vectors[0], nil
	}
	for _, p := range d.Vectors {
		if p.Name == name {
			return p, nil
		}
	}
	return VectorProperty{}, fmt.Errorf("%w: specify a vector property from the collection definition", ErrInvalidSearchOptions)
}
func ValidateModelVector(vector []float32, p VectorProperty) error {
	if len(vector) != p.Dimensions {
		return fmt.Errorf("%w: property %q expects %d, got %d", ErrDimensionMismatch, p.Name, p.Dimensions, len(vector))
	}
	nonzero := false
	for _, x := range vector {
		if math.IsNaN(float64(x)) || math.IsInf(float64(x), 0) {
			return fmt.Errorf("%w: non-finite element in %q", ErrInvalidVector, p.Name)
		}
		nonzero = nonzero || x != 0
	}
	if !nonzero && (p.Metric == "" || p.Metric == DistanceCosine) {
		return fmt.Errorf("%w: zero cosine vector in %q", ErrInvalidVector, p.Name)
	}
	return nil
}
func (d CollectionDefinition) NormalizeKey(key any) (any, error) {
	if isNilValue(key) {
		return nil, fmt.Errorf("%w: missing key", ErrInvalidRecord)
	}
	switch d.Key.Type {
	case KeyString:
		v := reflect.ValueOf(key)
		if v.Kind() == reflect.String && v.String() != "" {
			return v.String(), nil
		}
	case KeyInt64:
		v := reflect.ValueOf(key)
		switch v.Kind() {
		case reflect.Int, reflect.Int8, reflect.Int16, reflect.Int32, reflect.Int64:
			return v.Int(), nil
		case reflect.Uint, reflect.Uint8, reflect.Uint16, reflect.Uint32, reflect.Uint64:
			if v.Uint() <= math.MaxInt64 {
				return int64(v.Uint()), nil
			}
		}
	case KeyUUID:
		s, ok := key.(string)
		if !ok && reflect.ValueOf(key).Kind() == reflect.String {
			s = reflect.ValueOf(key).String()
		}
		if text, yes := key.(encoding.TextMarshaler); yes {
			raw, err := text.MarshalText()
			if err != nil {
				return nil, fmt.Errorf("%w: %v", ErrInvalidRecord, err)
			}
			s = string(raw)
		}
		if s == "" {
			if v, yes := key.(fmt.Stringer); yes {
				s = v.String()
			}
		}
		if len(s) == 36 {
			valid := true
			for i, c := range s {
				if i == 8 || i == 13 || i == 18 || i == 23 {
					valid = valid && c == '-'
				} else {
					valid = valid && (c >= '0' && c <= '9' || c >= 'a' && c <= 'f' || c >= 'A' && c <= 'F')
				}
			}
			if valid {
				return strings.ToLower(s), nil
			}
		}
	}
	return nil, fmt.Errorf("%w: invalid %s key", ErrInvalidRecord, d.Key.Type)
}
func normalizeData(value any, p DataProperty) (any, error) {
	if value == nil {
		if p.Optional {
			return nil, nil
		}
		return nil, fmt.Errorf("%w: missing data property %q", ErrInvalidRecord, p.Name)
	}
	invalid := func() (any, error) {
		return nil, fmt.Errorf("%w: invalid %s data property %q", ErrInvalidRecord, p.Type, p.Name)
	}
	switch p.Type {
	case TypeString:
		if v := reflect.ValueOf(value); v.Kind() == reflect.String {
			return v.String(), nil
		}
	case TypeInt64:
		return (CollectionDefinition{Key: KeyProperty{Type: KeyInt64}}).NormalizeKey(value)
	case TypeFloat64:
		v := reflect.ValueOf(value)
		var x float64
		switch v.Kind() {
		case reflect.Float32, reflect.Float64:
			x = v.Float()
		case reflect.Int, reflect.Int8, reflect.Int16, reflect.Int32, reflect.Int64:
			x = float64(v.Int())
		default:
			return invalid()
		}
		if !math.IsNaN(x) && !math.IsInf(x, 0) {
			return x, nil
		}
	case TypeBool:
		if v := reflect.ValueOf(value); v.Kind() == reflect.Bool {
			return v.Bool(), nil
		}
	case TypeTime:
		if x, ok := value.(time.Time); ok {
			return x, nil
		}
	case TypeStringArray:
		if x, ok := value.([]string); ok {
			if x == nil {
				x = []string{}
			}
			return append([]string{}, x...), nil
		}
	case TypeJSON:
		raw, err := json.Marshal(value)
		if err != nil {
			return nil, fmt.Errorf("%w: property %q: %v", ErrInvalidRecord, p.Name, err)
		}
		dec := json.NewDecoder(strings.NewReader(string(raw)))
		dec.UseNumber()
		var out any
		if err := dec.Decode(&out); err != nil {
			return nil, err
		}
		if out == nil {
			return JSONNull{}, nil
		}
		return out, nil
	}
	return invalid()
}

// PrepareModelRecords copies and validates inputs and batches automatic embedding
// generation per property. Providers call this before opening a write transaction.
func PrepareModelRecords(ctx context.Context, d CollectionDefinition, opts ModelCollectionOptions, records []ModelRecord) ([]ModelRecord, error) {
	out := make([]ModelRecord, len(records))
	for i, r := range records {
		if err := ctx.Err(); err != nil {
			return nil, err
		}
		out[i] = ModelRecord{Data: map[string]any{}, Vectors: map[string][]float32{}}
		if r.Key != nil || !d.Key.AutoGenerated {
			key, err := d.NormalizeKey(r.Key)
			if err != nil {
				return nil, err
			}
			out[i].Key = key
		}
		for name := range r.Data {
			found := false
			for _, p := range d.Data {
				found = found || p.Name == name
			}
			if !found {
				return nil, fmt.Errorf("%w: unknown data property %q", ErrInvalidRecord, name)
			}
		}
		for _, p := range d.Data {
			value, err := normalizeData(r.Data[p.Name], p)
			if err != nil {
				return nil, err
			}
			out[i].Data[p.Name] = value
		}
		for name, vector := range r.Vectors {
			found := false
			for _, p := range d.Vectors {
				found = found || p.Name == name
			}
			if !found {
				return nil, fmt.Errorf("%w: unknown vector property %q", ErrInvalidRecord, name)
			}
			out[i].Vectors[name] = append([]float32(nil), vector...)
		}
	}
	for _, p := range d.Vectors {
		var positions []int
		var inputs []string
		for i := range out {
			if len(out[i].Vectors[p.Name]) == 0 && p.SourceProperty != "" {
				value, ok := out[i].Data[p.SourceProperty].(string)
				if !ok {
					return nil, fmt.Errorf("%w: missing embedding source %q", ErrInvalidRecord, p.SourceProperty)
				}
				positions = append(positions, i)
				inputs = append(inputs, value)
			}
		}
		if len(inputs) > 0 {
			embedder := p.Embedder
			if isNilValue(embedder) {
				embedder = opts.Embedder
			}
			if isNilValue(embedder) {
				return nil, fmt.Errorf("%w: no embedder for %q", ErrUnsupported, p.Name)
			}
			vectors, err := embedder.Embed(ctx, inputs)
			if err != nil {
				return nil, err
			}
			if len(vectors) != len(inputs) {
				return nil, fmt.Errorf("%w: embedder returned %d vectors for %d inputs", ErrInvalidVector, len(vectors), len(inputs))
			}
			for j, i := range positions {
				out[i].Vectors[p.Name] = append([]float32(nil), vectors[j]...)
			}
		}
		for i := range out {
			if err := ValidateModelVector(out[i].Vectors[p.Name], p); err != nil {
				return nil, fmt.Errorf("%w: record %d: %w", ErrInvalidRecord, i, err)
			}
		}
	}
	return out, nil
}
func EmbedQuery(ctx context.Context, text string, p VectorProperty, opts ModelCollectionOptions) ([]float32, error) {
	embedder := p.Embedder
	if isNilValue(embedder) {
		embedder = opts.Embedder
	}
	if isNilValue(embedder) {
		return nil, fmt.Errorf("%w: text search requires an embedder", ErrUnsupported)
	}
	vectors, err := embedder.Embed(ctx, []string{text})
	if err != nil {
		return nil, err
	}
	if len(vectors) != 1 {
		return nil, fmt.Errorf("%w: expected one query embedding", ErrInvalidVector)
	}
	if err := ValidateModelVector(vectors[0], p); err != nil {
		return nil, err
	}
	return vectors[0], nil
}
func ValidateModelSearchOptions(top int, opts ModelSearchOptions) error {
	if top <= 0 || opts.Skip < 0 || top > int(^uint(0)>>1)-opts.Skip {
		return fmt.Errorf("%w: top must be positive and skip nonnegative", ErrInvalidSearchOptions)
	}
	for _, threshold := range []*float64{opts.DistanceThreshold, opts.ScoreThreshold} {
		if threshold != nil && (math.IsNaN(*threshold) || math.IsInf(*threshold, 0)) {
			return fmt.Errorf("%w: thresholds must be finite", ErrInvalidSearchOptions)
		}
	}
	return nil
}
func ValidateModelSearch(vector []float32, top int, opts ModelSearchOptions, p VectorProperty) error {
	if err := ValidateModelSearchOptions(top, opts); err != nil {
		return err
	}
	return ValidateModelVector(vector, p)
}

// ValidateModelQuery restricts portable ordering to keys and scalar data properties.
func ValidateModelQuery(d CollectionDefinition, top int, opts QueryOptions) error {
	if top <= 0 || opts.Skip < 0 {
		return fmt.Errorf("%w: positive top and nonnegative skip required", ErrInvalidSearchOptions)
	}
	for _, sort := range opts.OrderBy {
		if sort.Property == d.Key.Name {
			continue
		}
		found := false
		for _, p := range d.Data {
			if p.Name == sort.Property {
				found = true
				if p.Type == TypeJSON || p.Type == TypeStringArray {
					return fmt.Errorf("%w: ordering JSON or array properties is provider-specific", ErrUnsupported)
				}
			}
		}
		if !found {
			return fmt.Errorf("%w: unknown sort property %q", ErrInvalidFilter, sort.Property)
		}
	}
	return nil
}
