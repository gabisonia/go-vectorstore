// KeyType describes the native storage type of a model key.
type KeyType string

const (
	KeyString KeyType = "string"
	KeyInt64  KeyType = "int64"
	KeyUUID   KeyType = "uuid"
)

// DataType describes portable data properties supported by model collections.
type DataType string

const (
	TypeString        DataType = "string"
	TypeInt64         DataType = "int64"
	TypeFloat64       DataType = "float64"
	TypeBool          DataType = "bool"
	TypeJSON          DataType = "json"
	TypeTime          DataType = "time"
	TypeStringArray   DataType = "string_array"
	TypeUUID          DataType = "uuid"
	TypeBytes         DataType = "bytes"
	TypeInt64Array    DataType = "int64_array"
	TypeFloat64Array  DataType = "float64_array"
	TypeBoolArray     DataType = "bool_array"
	TypeUUIDArray     DataType = "uuid_array"
	TypeTimeArray     DataType = "time_array"
	TypeDateOnly      DataType = "date_only"
	TypeTimeOnly      DataType = "time_only"
	TypeDateOnlyArray DataType = "date_only_array"
	TypeTimeOnlyArray DataType = "time_only_array"
	TypeDecimal       DataType = "decimal"
	TypeDecimalArray  DataType = "decimal_array"
)

type KeyProperty struct {
	Name, StorageName string
	Type              KeyType
	AutoGenerated     bool
}
type DataProperty struct {
	Name, StorageName                      string
	Type                                   DataType
	Optional, IsIndexed, IsFullTextIndexed bool
}
type VectorProperty struct {
	Name, StorageName string
	Dimensions        int
	// Optional permits a missing vector; searches exclude records without the selected vector.
	Optional bool       `json:",omitempty"`
	Kind     VectorKind `json:",omitempty"`
	// Dense/sparse precision defaults to float32; binary properties leave it unset.
	// The canonical default stays empty so existing
	// serialized model registrations remain unchanged.
	Precision VectorPrecision `json:",omitempty"`
	Metric    DistanceMetric
	Index     *VectorIndexOptions
	// SourceProperty names a string data property used for automatic embedding.
	SourceProperty string
	Embedder       Embedder `json:"-"`
}

// CollectionDefinition is shared by mapping, schema creation, validation and search.
type CollectionDefinition struct {
	Key     KeyProperty
	Data    []DataProperty
	Vectors []VectorProperty
}

// JSONNull distinguishes a JSON null value from a native SQL NULL in dynamic records.
type JSONNull struct{}

func (JSONNull) MarshalJSON() ([]byte, error) { return []byte("null"), nil }

// ModelRecord is the dynamic counterpart of a typed application model. Maps use logical property names.
type ModelRecord struct {
	Key           any
	Data          map[string]any
	Vectors       map[string][]float32
	BinaryVectors map[string]BinaryVector `json:",omitempty"`
	SparseVectors map[string]SparseVector `json:",omitempty"`
}

// Embedder generates one vector for each input, preserving input order. Implementations must honor ctx.
type Embedder interface {
	Embed(context.Context, []string) ([][]float32, error)
}
type EmbeddingFunc func(context.Context, []string) ([][]float32, error)

func (f EmbeddingFunc) Embed(ctx context.Context, inputs []string) ([][]float32, error) {
	return f(ctx, inputs)
}

type ModelCollectionOptions struct {
	Embedder Embedder
	// EmbeddingBatchSize bounds inputs per embedding request for each property.
	// Zero inherits the store default, or uses one request when no default is set.
	// Positive values override the store default; negative values are invalid.
	EmbeddingBatchSize int
}

// WithDefaults resolves runtime collection settings without changing either input.
// Property embedders still override the resolved collection embedder.
func (o ModelCollectionOptions) WithDefaults(defaults ModelCollectionOptions) (ModelCollectionOptions, error) {
	if o.EmbeddingBatchSize < 0 || defaults.EmbeddingBatchSize < 0 {
		return ModelCollectionOptions{}, fmt.Errorf("%w: embedding batch size must be nonnegative", ErrInvalidEmbeddingOptions)
	}
	if isNilValue(o.Embedder) {
		o.Embedder = defaults.Embedder
	}
	if o.EmbeddingBatchSize == 0 {
		o.EmbeddingBatchSize = defaults.EmbeddingBatchSize
	}
	return o, nil
}

