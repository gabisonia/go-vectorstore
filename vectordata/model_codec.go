// ModelCodec maps domain values to dynamic model records; custom codecs can avoid reflection.
type ModelCodec[T any] interface {
	Encode(T) (ModelRecord, error)
	Decode(ModelRecord) (T, error)
}
type structField struct {
	index          []int
	name           string
	role           string
	dataType       DataType
	binary         bool
	sparse         bool
	embeddingInput bool
}

// StructCodec resolves field mappings once at construction, not once per record.
type StructCodec[T any] struct {
	typ        reflect.Type
	pointer    bool
	definition CollectionDefinition
	fields     []structField
}

func modelType[T any]() (reflect.Type, bool, error) {
	t := reflect.TypeFor[T]()
	pointer := t.Kind() == reflect.Pointer
	if pointer {
		t = t.Elem()
	}
	if t.Kind() != reflect.Struct {
		return nil, false, fmt.Errorf("%w: model must be a struct or pointer to struct", ErrSchemaMismatch)
	}
	return t, pointer, nil
}
func inferDataType(t reflect.Type) DataType {
	for t.Kind() == reflect.Pointer {
		t = t.Elem()
	}
	if t == reflect.TypeFor[time.Time]() {
		return TypeTime
	}
	switch t.Kind() {
	case reflect.String:
		return TypeString
	case reflect.Bool:
		return TypeBool
	case reflect.Int, reflect.Int8, reflect.Int16, reflect.Int32, reflect.Int64:
		return TypeInt64
	case reflect.Float32, reflect.Float64:
		return TypeFloat64
	case reflect.Slice:
		if t.Elem().Kind() == reflect.String {
			return TypeStringArray
		}
	}
	return TypeJSON
}

func uuidFieldType(typ reflect.Type) bool {
	textValue := typ.Implements(reflect.TypeFor[encoding.TextMarshaler]()) || typ.Implements(reflect.TypeFor[fmt.Stringer]())
	return typ.Kind() == reflect.String || textValue && reflect.PointerTo(typ).Implements(reflect.TypeFor[encoding.TextUnmarshaler]())
}

// DefinitionFor reads vectordata tags. Roles are key, data, or vector. Options:
// name=<storage name>, type=<type>, generated, optional, index, fulltext,
// dimensions=<n>, kind=dense|binary|sparse, precision=float32|float16, metric=<metric>,
// source=<data field>, method=hnsw|ivfflat|flat, input (transient embedding input).
func DefinitionFor[T any]() (CollectionDefinition, error) {
	t, _, err := modelType[T]()
	if err != nil {
		return CollectionDefinition{}, err
	}
	d := CollectionDefinition{}
	for _, f := range reflect.VisibleFields(t) {
		tag, ok := f.Tag.Lookup("vectordata")
		if !ok || tag == "-" {
			continue
		}
		if f.PkgPath != "" {
			return d, fmt.Errorf("%w: tagged field %q is unexported", ErrSchemaMismatch, f.Name)
		}
		parts := strings.Split(tag, ",")
		role := parts[0]
		flags := map[string]bool{}
		values := map[string]string{}
		for _, option := range parts[1:] {
			key, value, hasValue := strings.Cut(option, "=")
			if hasValue {
				switch key {
				case "name", "type", "dimensions", "precision", "metric", "source", "method", "kind":
				default:
					return d, fmt.Errorf("%w: unknown tag option %q", ErrSchemaMismatch, key)
				}
				if _, exists := values[key]; exists {
					return d, fmt.Errorf("%w: duplicate tag option", ErrSchemaMismatch)
				}
				values[key] = value
			} else {
				switch key {
				case "generated", "optional", "index", "fulltext", "input":
				default:
					return d, fmt.Errorf("%w: unknown tag flag %q", ErrSchemaMismatch, key)
				}
				flags[key] = true
			}
		}
		allowedFlags, allowedValues := map[string]bool{}, map[string]bool{"name": true}
		switch role {
		case "key":
			allowedFlags["generated"] = true
			allowedValues["type"] = true
		case "data":
			allowedFlags["optional"] = true
			allowedFlags["index"] = true
			allowedFlags["fulltext"] = true
			allowedValues["type"] = true
		case "vector":
			allowedFlags["optional"] = true
			allowedFlags["index"] = true
			allowedFlags["input"] = true
			for _, key := range []string{"dimensions", "precision", "metric", "source", "method", "kind"} {
				allowedValues[key] = true
			}
		}
		for flag := range flags {
			if !allowedFlags[flag] {
				return d, fmt.Errorf("%w: tag flag %q is invalid for %s", ErrSchemaMismatch, flag, role)
			}
		}
		for key := range values {
			if !allowedValues[key] {
				return d, fmt.Errorf("%w: tag option %q is invalid for %s", ErrSchemaMismatch, key, role)
			}
		}
		switch role {
		case "key":
			if d.Key.Name != "" {
				return d, fmt.Errorf("%w: exactly one key required", ErrSchemaMismatch)
			}
			kind := KeyType(values["type"])
			if kind == "" {
				keyType := f.Type
				for keyType.Kind() == reflect.Pointer {
					keyType = keyType.Elem()
				}
				if keyType.Kind() >= reflect.Uint && keyType.Kind() <= reflect.Uint64 {
					kind = KeyUint64
				} else if inferDataType(f.Type) == TypeInt64 {
					kind = KeyInt64
				} else {
					kind = KeyString
				}
			}
			d.Key = KeyProperty{Name: f.Name, StorageName: values["name"], Type: kind, AutoGenerated: flags["generated"]}
		case "data":
			kind := DataType(values["type"])
			if kind == "" {
				kind = inferDataType(f.Type)
			}
			d.Data = append(d.Data, DataProperty{Name: f.Name, StorageName: values["name"], Type: kind, Optional: flags["optional"] || f.Type.Kind() == reflect.Pointer, IsIndexed: flags["index"], IsFullTextIndexed: flags["fulltext"]})
		case "vector":
			dimensions, err := strconv.Atoi(values["dimensions"])
			if err != nil {
				return d, fmt.Errorf("%w: vector %q requires dimensions", ErrSchemaMismatch, f.Name)
			}
			p := VectorProperty{Optional: flags["optional"] || f.Type.Kind() == reflect.Pointer, Name: f.Name, StorageName: values["name"], Dimensions: dimensions, Kind: VectorKind(values["kind"]), Precision: VectorPrecision(values["precision"]), Metric: DistanceMetric(values["metric"]), SourceProperty: values["source"]}
			if flags["index"] || values["method"] != "" {
				p.Index = &VectorIndexOptions{Method: IndexMethod(values["method"])}
			}
			d.Vectors = append(d.Vectors, p)
		default:
			return d, fmt.Errorf("%w: unknown tag role %q", ErrSchemaMismatch, role)
		}
	}
	return d.Normalize()
}
func NewStructCodec[T any](definition *CollectionDefinition) (*StructCodec[T], error) {
	t, pointer, err := modelType[T]()
	if err != nil {
		return nil, err
	}
	var d CollectionDefinition
	if definition == nil {
		d, err = DefinitionFor[T]()
	} else {
		d, err = definition.Normalize()
	}
	if err != nil {
		return nil, err
	}
	codec := &StructCodec[T]{typ: t, pointer: pointer, definition: d}
	add := func(name, role string) error {
		field, ok := t.FieldByName(name)
		if !ok || field.PkgPath != "" {
			return fmt.Errorf("%w: no exported model field %q", ErrSchemaMismatch, name)
		}
		parent := t
		for _, index := range field.Index {
			for parent.Kind() == reflect.Pointer {
				parent = parent.Elem()
			}
			part := parent.Field(index)
			if part.PkgPath != "" {
				return fmt.Errorf("%w: field %q has an unexported embedded parent", ErrSchemaMismatch, name)
			}
			parent = part.Type
		}
		codec.fields = append(codec.fields, structField{index: field.Index, name: name, role: role})
		return nil
	}
	if err := add(d.Key.Name, "key"); err != nil {
		return nil, err
	}
	keyField, _ := t.FieldByName(d.Key.Name)
	keyType := keyField.Type
	for keyType.Kind() == reflect.Pointer {
		keyType = keyType.Elem()
	}
	validKey := d.Key.Type == KeyString && keyType.Kind() == reflect.String || d.Key.Type == KeyInt64 && (keyType.Kind() >= reflect.Int && keyType.Kind() <= reflect.Int64) || d.Key.Type == KeyUint64 && (keyType.Kind() >= reflect.Uint && keyType.Kind() <= reflect.Uint64) || d.Key.Type == KeyUUID && (keyType.Kind() == reflect.String || reflect.PointerTo(keyType).Implements(reflect.TypeFor[encoding.TextUnmarshaler]()))
	if !validKey || d.Key.AutoGenerated && d.Key.Type == KeyInt64 && keyType.Bits() < 64 {
		return nil, fmt.Errorf("%w: model key type conflicts with definition", ErrSchemaMismatch)
	}
	for _, p := range d.Data {
		if err := add(p.Name, "data"); err != nil {
			return nil, err
		}
		field, _ := t.FieldByName(p.Name)
		typ := field.Type
		for typ.Kind() == reflect.Pointer {
			typ = typ.Elem()
		}
		valid := p.Type == TypeJSON || inferDataType(field.Type) == p.Type
		if p.Type == TypeUUID {
			valid = uuidFieldType(typ)
		}
		if p.Type == TypeDateOnly || p.Type == TypeTimeOnly || p.Type == TypeDecimal {
			valid = typ.Kind() == reflect.String
		}
		if p.Type == TypeBytes {
			valid = typ.Kind() == reflect.Slice && typ.Elem().Kind() == reflect.Uint8
		}
		if element, array := p.Type.ArrayElementType(); array && p.Type != TypeStringArray {
			valid = typ.Kind() == reflect.Slice && nativeArrayKind(typ.Elem(), element)
			if p.Type == TypeFloat64Array && valid {
				valid = typ.Elem().Kind() == reflect.Float32 || typ.Elem().Kind() == reflect.Float64
			}
			if p.Type == TypeUUIDArray && valid {
				valid = uuidFieldType(typ.Elem())
			}
			if p.Type == TypeDecimalArray && valid {
				valid = typ.Elem().Kind() == reflect.String
			}
		}
		if !valid {
			return nil, fmt.Errorf("%w: field %q type conflicts with definition", ErrSchemaMismatch, p.Name)
		}
		codec.fields[len(codec.fields)-1].dataType = p.Type
	}
	for _, p := range d.Vectors {
		if err := add(p.Name, "vector"); err != nil {
			return nil, err
		}
		field, _ := t.FieldByName(p.Name)
		want := reflect.TypeFor[[]float32]()
		if p.Kind == VectorBinary {
			want = reflect.TypeFor[BinaryVector]()
			codec.fields[len(codec.fields)-1].binary = true
		}
		if p.Kind == VectorSparse {
			want = reflect.TypeFor[SparseVector]()
			codec.fields[len(codec.fields)-1].sparse = true
		}
		typ := field.Type
		if typ.Kind() == reflect.Pointer && p.Optional {
			typ = typ.Elem()
		}
		input := typ.Kind() == reflect.String
		for _, option := range strings.Split(field.Tag.Get("vectordata"), ",")[1:] {
			input = input || option == "input"
		}
		if input {
			if p.Kind == VectorBinary || p.Kind == VectorSparse || p.SourceProperty != "" {
				return nil, fmt.Errorf("%w: input field %q requires a dense vector without source", ErrSchemaMismatch, p.Name)
			}
			codec.fields[len(codec.fields)-1].embeddingInput = true
			continue
		}
		if typ != want {
			return nil, fmt.Errorf("%w: vector field %q must be %s", ErrSchemaMismatch, p.Name, want)
		}
	}
	return codec, nil
}
func (c *StructCodec[T]) Definition() CollectionDefinition { return c.definition.Clone() }
func structValue(root reflect.Value, index []int, allocate bool) (reflect.Value, error) {
	for _, i := range index {
		for root.Kind() == reflect.Pointer {
			if root.IsNil() {
				if !allocate {
					return reflect.Value{}, nil
				}
				root.Set(reflect.New(root.Type().Elem()))
			}
			root = root.Elem()
		}
		root = root.Field(i)
	}
	return root, nil
}
func (c *StructCodec[T]) Encode(value T) (ModelRecord, error) {
	root := reflect.ValueOf(value)
	if c.pointer {
		if root.IsNil() {
			return ModelRecord{}, fmt.Errorf("%w: nil model", ErrInvalidRecord)
		}
		root = root.Elem()
	}
	out := ModelRecord{Data: map[string]any{}, Vectors: map[string][]float32{}}
	for _, field := range c.fields {
		v, _ := structValue(root, field.index, false)
		if !v.IsValid() {
			if field.role == "data" {
				out.Data[field.name] = nil
			}
			continue
		}
		switch field.role {
		case "key":
			if c.definition.Key.AutoGenerated && v.IsZero() {
				out.Key = nil
			} else {
				for v.Kind() == reflect.Pointer {
					if v.IsNil() {
						return out, fmt.Errorf("%w: nil key", ErrInvalidRecord)
					}
					v = v.Elem()
				}
				out.Key = v.Interface()
			}
		case "vector":
			if field.embeddingInput {
				if out.EmbeddingInputs == nil {
					out.EmbeddingInputs = map[string]any{}
				}
				// Optional string fields use the same text contract as strings.
				// Other pointer inputs retain their application type.
				if v.Kind() == reflect.Pointer && v.Type().Elem().Kind() == reflect.String && !v.IsNil() {
					v = v.Elem()
				}
				out.EmbeddingInputs[field.name] = v.Interface()
				continue
			}
			if v.Kind() == reflect.Pointer {
				if v.IsNil() {
					continue
				}
				v = v.Elem()
			}
			if field.binary {
				if out.BinaryVectors == nil {
					out.BinaryVectors = map[string]BinaryVector{}
				}
				b := v.Interface().(BinaryVector)
				b.Bytes = append([]byte(nil), b.Bytes...)
				out.BinaryVectors[field.name] = b
			} else if field.sparse {
				if out.SparseVectors == nil {
					out.SparseVectors = map[string]SparseVector{}
				}
				out.SparseVectors[field.name] = cloneSparse(v.Interface().(SparseVector))
			} else {
				if !v.IsNil() {
					out.Vectors[field.name] = append([]float32{}, v.Interface().([]float32)...)
				}
			}
		case "data":
			for v.Kind() == reflect.Pointer {
				if v.IsNil() {
					break
				}
				v = v.Elem()
			}
			if v.Kind() == reflect.Pointer && v.IsNil() {
				out.Data[field.name] = nil
			} else if field.dataType == TypeUUID {
				out.Data[field.name] = v.Interface()
			} else {
				// Normalize integer and float aliases to portable native values.
				switch inferDataType(v.Type()) {
				case TypeInt64:
					out.Data[field.name] = v.Int()
				case TypeFloat64:
					out.Data[field.name] = v.Float()
				case TypeString:
					out.Data[field.name] = v.String()
				case TypeBool:
					out.Data[field.name] = v.Bool()
				default:
					out.Data[field.name] = v.Interface()
				}
			}
		}
	}
	return out, nil
}
func assignModelValue(target reflect.Value, value any) error {
	if value == nil {
		return nil
	}
	if target.Kind() == reflect.Pointer {
		if target.IsNil() {
			target.Set(reflect.New(target.Type().Elem()))
		}
		return assignModelValue(target.Elem(), value)
	}
	if text, ok := value.(string); ok && target.CanAddr() {
		if unmarshaler, ok := target.Addr().Interface().(encoding.TextUnmarshaler); ok {
			return unmarshaler.UnmarshalText([]byte(text))
		}
	}
	source := reflect.ValueOf(value)
	if source.Type().AssignableTo(target.Type()) {
		target.Set(source)
		return nil
	}
	switch target.Kind() {
	case reflect.Int, reflect.Int8, reflect.Int16, reflect.Int32, reflect.Int64:
		if source.Kind() == reflect.Int64 {
			if target.OverflowInt(source.Int()) {
				return fmt.Errorf("integer overflow")
			}
			target.SetInt(source.Int())
			return nil
		}
	case reflect.Uint, reflect.Uint8, reflect.Uint16, reflect.Uint32, reflect.Uint64:
		if source.Kind() == reflect.Uint64 {
			if target.OverflowUint(source.Uint()) {
				return fmt.Errorf("unsigned integer overflow")
			}
			target.SetUint(source.Uint())
			return nil
		}
	case reflect.Float32, reflect.Float64:
		if source.Kind() == reflect.Float64 {
			if target.OverflowFloat(source.Float()) {
				return fmt.Errorf("float overflow")
			}
			target.SetFloat(source.Float())
			return nil
		}
	case reflect.String:
		if source.Kind() == reflect.String {
			target.SetString(source.String())
			return nil
		}
	}
	payload, err := json.Marshal(value)
	if err != nil {
		return err
	}
	decoder := json.NewDecoder(strings.NewReader(string(payload)))
	decoder.UseNumber()
	return decoder.Decode(target.Addr().Interface())
}

// Structured native elements need their Go conversion/text decoding rather than
// a JSON round-trip (defined time.Time types need not implement JSON methods).
func assignStructuredArray(target reflect.Value, value any, kind DataType) error {
	if isNilValue(value) {
		return nil
	}
	if target.Kind() == reflect.Pointer {
		if target.IsNil() {
			target.Set(reflect.New(target.Type().Elem()))
		}
		return assignStructuredArray(target.Elem(), value, kind)
	}
	source := reflect.ValueOf(value)
	if source.Kind() != reflect.Slice || target.Kind() != reflect.Slice {
		return fmt.Errorf("expected native array slice")
	}
	out := reflect.MakeSlice(target.Type(), source.Len(), source.Len())
	for i := 0; i < source.Len(); i++ {
		normalized, err := NormalizeModelArrayElement(source.Index(i).Interface(), kind)
		if err != nil {
			return err
		}
		if normalized == nil {
			return fmt.Errorf("%w: native arrays cannot contain NULL elements", ErrInvalidRecord)
		}
		if kind == TypeTimeArray {
			out.Index(i).Set(reflect.ValueOf(normalized).Convert(target.Type().Elem()))
		} else if err := assignModelValue(out.Index(i), normalized); err != nil {
			return err
		}
	}
	target.Set(out)
	return nil
}
func (c *StructCodec[T]) Decode(record ModelRecord) (T, error) {
	var zero T
	root := reflect.New(c.typ).Elem()
	for _, field := range c.fields {
		// Source values are transient; a vector cannot be decoded back into them.
		if field.embeddingInput {
			continue
		}
		target, err := structValue(root, field.index, true)
		if err != nil {
			return zero, err
		}
		var value any
		switch field.role {
		case "key":
			value = record.Key
		case "data":
			value = record.Data[field.name]
		case "vector":
			if field.binary {
				if b, ok := record.BinaryVectors[field.name]; ok {
					b.Bytes = append([]byte(nil), b.Bytes...)
					value = b
				}
			} else if field.sparse {
				if v, ok := record.SparseVectors[field.name]; ok {
					value = cloneSparse(v)
				}
			} else if vector := record.Vectors[field.name]; vector != nil {
				value = append([]float32{}, vector...)
			}
		}
		var assignErr error
		if field.dataType == TypeUUIDArray || field.dataType == TypeTimeArray || field.dataType == TypeDateOnlyArray || field.dataType == TypeTimeOnlyArray || field.dataType == TypeDecimalArray {
			assignErr = assignStructuredArray(target, value, field.dataType)
		} else {
			assignErr = assignModelValue(target, value)
		}
		if err := assignErr; err != nil {
			return zero, fmt.Errorf("decode field %q: %w", field.name, err)
		}
	}
	if c.pointer {
		return root.Addr().Interface().(T), nil
	}
	return root.Interface().(T), nil
}

// TypedModelCollection provides native-key operations for a domain model.
// It complements the original TypedCollection[T], whose keys remain strings.
type TypedModelCollection[K comparable, T any] struct {
	base  ModelCollection
	codec ModelCodec[T]
}
type TypedModelSearchResult[T any] struct {
	Item            T
	Distance, Score float64
	ScoreKind       ScoreKind
}

func NewTypedModelCollection[K comparable, T any](base ModelCollection, codec ModelCodec[T]) (*TypedModelCollection[K, T], error) {
	if isNilValue(base) || isNilValue(codec) {
		return nil, fmt.Errorf("%w: collection and codec required", ErrSchemaMismatch)
	}
	typ := reflect.TypeFor[K]()
	key := base.Definition().Key
	valid := key.Type == KeyString && typ.Kind() == reflect.String || key.Type == KeyInt64 && typ.Kind() >= reflect.Int && typ.Kind() <= reflect.Int64 || key.Type == KeyUint64 && typ.Kind() >= reflect.Uint && typ.Kind() <= reflect.Uint64 || key.Type == KeyUUID && (typ.Kind() == reflect.String || reflect.PointerTo(typ).Implements(reflect.TypeFor[encoding.TextUnmarshaler]()))
	if !valid || key.AutoGenerated && key.Type == KeyInt64 && typ.Bits() < 64 {
		return nil, fmt.Errorf("%w: typed key conflicts with collection definition", ErrSchemaMismatch)
	}
	return &TypedModelCollection[K, T]{base, codec}, nil
}

// GetTypedModelCollection creates a typed handle without accessing or creating storage.
// Struct tags are inferred when definition is nil; explicit definitions use Go field names.
func GetTypedModelCollection[K comparable, T any](store ModelStore, name string, definition *CollectionDefinition, opts ModelCollectionOptions) (*TypedModelCollection[K, T], error) {
	if isNilValue(store) {
		return nil, fmt.Errorf("%w: store is required", ErrSchemaMismatch)
	}
	codec, err := NewStructCodec[T](definition)
	if err != nil {
		return nil, err
	}
	base, err := store.GetModelCollection(name, codec.Definition(), opts)
	if err != nil {
		return nil, err
	}
	return NewTypedModelCollection[K, T](base, codec)
}

// EnsureTypedModelCollection creates or validates storage before returning a typed handle.
func EnsureTypedModelCollection[K comparable, T any](ctx context.Context, store ModelStore, name string, definition *CollectionDefinition, opts ModelCollectionOptions) (*TypedModelCollection[K, T], error) {
	typed, err := GetTypedModelCollection[K, T](store, name, definition, opts)
	if err != nil {
		return nil, err
	}
	if err := typed.EnsureExists(ctx); err != nil {
		return nil, err
	}
	return typed, nil
}

func (c *TypedModelCollection[K, T]) Name() string                     { return c.base.Name() }
func (c *TypedModelCollection[K, T]) Definition() CollectionDefinition { return c.base.Definition() }
func (c *TypedModelCollection[K, T]) Exists(ctx context.Context) (bool, error) {
	return c.base.Exists(ctx)
}
func (c *TypedModelCollection[K, T]) EnsureExists(ctx context.Context) error {
	return c.base.EnsureExists(ctx)
}
func (c *TypedModelCollection[K, T]) EnsureDeleted(ctx context.Context) error {
	return c.base.EnsureDeleted(ctx)
}
func (c *TypedModelCollection[K, T]) encode(values []T) ([]ModelRecord, error) {
	records := make([]ModelRecord, len(values))
	typ := reflect.TypeFor[K]()
	narrowInteger := (typ.Kind() >= reflect.Int && typ.Kind() <= reflect.Int64 || typ.Kind() >= reflect.Uint && typ.Kind() <= reflect.Uint64) && typ.Bits() < 64
	var definition CollectionDefinition
	if narrowInteger {
		definition = c.base.Definition()
	}
	for i, value := range values {
		r, err := c.codec.Encode(value)
		if err != nil {
			return nil, err
		}
		// Check the whole batch before calling the provider. In particular, a
		// custom codec may emit keys wider than K; detecting that only while
		// converting returned keys would report an error after writes committed.
		if narrowInteger {
			key, err := definition.NormalizeKey(r.Key)
			if err != nil {
				return nil, err
			}
			var converted K
			if err := assignModelValue(reflect.ValueOf(&converted).Elem(), key); err != nil {
				return nil, fmt.Errorf("%w: record %d key cannot fit %s: %v", ErrInvalidRecord, i, typ, err)
			}
		}
		records[i] = r
	}
	return records, nil
}
func typedKeys[K comparable](values []any) ([]K, error) {
	out := make([]K, len(values))
	for i, value := range values {
		if isNilValue(value) {
			return nil, fmt.Errorf("%w: provider returned a nil key at index %d", ErrInvalidRecord, i)
		}
		if err := assignModelValue(reflect.ValueOf(&out[i]).Elem(), value); err != nil {
			return nil, err
		}
	}
	return out, nil
}
func (c *TypedModelCollection[K, T]) Insert(ctx context.Context, values []T) ([]K, error) {
	records, err := c.encode(values)
	if err != nil {
		return nil, err
	}
	keys, err := c.base.Insert(ctx, records)
	if err != nil {
		return nil, err
	}
	if len(keys) != len(records) {
		return nil, fmt.Errorf("%w: insert returned %d keys for %d records", ErrInvalidRecord, len(keys), len(records))
	}
	return typedKeys[K](keys)
}
