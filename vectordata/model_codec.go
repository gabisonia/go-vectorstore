// ModelCodec maps domain values to dynamic model records; custom codecs can avoid reflection.
type ModelCodec[T any] interface {
	Encode(T) (ModelRecord, error)
	Decode(ModelRecord) (T, error)
}
type structField struct {
	index []int
	name  string
	role  string
}

// StructCodec resolves field mappings once at construction, not once per record.
type StructCodec[T any] struct {
	typ        reflect.Type
	pointer    bool
	definition CollectionDefinition
	fields     []structField
}

func modelType[T any]() (reflect.Type, bool, error) {
	t := reflect.TypeFor[T]()
	pointer := t.Kind() == reflect.Pointer
	if pointer {
		t = t.Elem()
	}
	if t.Kind() != reflect.Struct {
		return nil, false, fmt.Errorf("%w: model must be a struct or pointer to struct", ErrSchemaMismatch)
	}
	return t, pointer, nil
}
func inferDataType(t reflect.Type) DataType {
	for t.Kind() == reflect.Pointer {
		t = t.Elem()
	}
	if t == reflect.TypeFor[time.Time]() {
		return TypeTime
	}
	switch t.Kind() {
	case reflect.String:
		return TypeString
	case reflect.Bool:
		return TypeBool
	case reflect.Int, reflect.Int8, reflect.Int16, reflect.Int32, reflect.Int64:
		return TypeInt64
	case reflect.Float32, reflect.Float64:
		return TypeFloat64
	case reflect.Slice:
		if t.Elem().Kind() == reflect.String {
			return TypeStringArray
		}
	}
	return TypeJSON
}

// DefinitionFor reads vectordata tags. Roles are key, data, or vector. Options:
// name=<storage name>, type=<type>, generated, optional, index, fulltext,
// dimensions=<n>, precision=float32|float16, metric=<metric>, source=<data field>, method=hnsw|ivfflat.
func DefinitionFor[T any]() (CollectionDefinition, error) {
	t, _, err := modelType[T]()
	if err != nil {
		return CollectionDefinition{}, err
	}
	d := CollectionDefinition{}
	for _, f := range reflect.VisibleFields(t) {
		tag, ok := f.Tag.Lookup("vectordata")
		if !ok || tag == "-" {
			continue
		}
		if f.PkgPath != "" {
			return d, fmt.Errorf("%w: tagged field %q is unexported", ErrSchemaMismatch, f.Name)
		}
		parts := strings.Split(tag, ",")
		role := parts[0]
		flags := map[string]bool{}
		values := map[string]string{}
		for _, option := range parts[1:] {
			key, value, hasValue := strings.Cut(option, "=")
			if hasValue {
				switch key {
				case "name", "type", "dimensions", "precision", "metric", "source", "method":
				default:
					return d, fmt.Errorf("%w: unknown tag option %q", ErrSchemaMismatch, key)
				}
				if _, exists := values[key]; exists {
					return d, fmt.Errorf("%w: duplicate tag option", ErrSchemaMismatch)
				}
				values[key] = value
			} else {
				switch key {
				case "generated", "optional", "index", "fulltext":
				default:
					return d, fmt.Errorf("%w: unknown tag flag %q", ErrSchemaMismatch, key)
				}
				flags[key] = true
			}
		}
		allowedFlags, allowedValues := map[string]bool{}, map[string]bool{"name": true}
		switch role {
		case "key":
			allowedFlags["generated"] = true
			allowedValues["type"] = true
		case "data":
			allowedFlags["optional"] = true
			allowedFlags["index"] = true
			allowedFlags["fulltext"] = true
			allowedValues["type"] = true
		case "vector":
			allowedFlags["index"] = true
			for _, key := range []string{"dimensions", "precision", "metric", "source", "method"} {
				allowedValues[key] = true
			}
		}
		for flag := range flags {
			if !allowedFlags[flag] {
				return d, fmt.Errorf("%w: tag flag %q is invalid for %s", ErrSchemaMismatch, flag, role)
			}
		}
		for key := range values {
			if !allowedValues[key] {
				return d, fmt.Errorf("%w: tag option %q is invalid for %s", ErrSchemaMismatch, key, role)
			}
		}
		switch role {
		case "key":
			if d.Key.Name != "" {
				return d, fmt.Errorf("%w: exactly one key required", ErrSchemaMismatch)
			}
			kind := KeyType(values["type"])
			if kind == "" {
				if inferDataType(f.Type) == TypeInt64 {
					kind = KeyInt64
				} else {
					kind = KeyString
				}
			}
			d.Key = KeyProperty{Name: f.Name, StorageName: values["name"], Type: kind, AutoGenerated: flags["generated"]}
		case "data":
			kind := DataType(values["type"])
			if kind == "" {
				kind = inferDataType(f.Type)
			}
			d.Data = append(d.Data, DataProperty{Name: f.Name, StorageName: values["name"], Type: kind, Optional: flags["optional"] || f.Type.Kind() == reflect.Pointer, IsIndexed: flags["index"], IsFullTextIndexed: flags["fulltext"]})
		case "vector":
			dimensions, err := strconv.Atoi(values["dimensions"])
			if err != nil {
				return d, fmt.Errorf("%w: vector %q requires dimensions", ErrSchemaMismatch, f.Name)
			}
			p := VectorProperty{Name: f.Name, StorageName: values["name"], Dimensions: dimensions, Precision: VectorPrecision(values["precision"]), Metric: DistanceMetric(values["metric"]), SourceProperty: values["source"]}
			if flags["index"] || values["method"] != "" {
				p.Index = &VectorIndexOptions{Method: IndexMethod(values["method"])}
			}
			d.Vectors = append(d.Vectors, p)
		default:
			return d, fmt.Errorf("%w: unknown tag role %q", ErrSchemaMismatch, role)
		}
	}
	return d.Normalize()
}
func NewStructCodec[T any](definition *CollectionDefinition) (*StructCodec[T], error) {
	t, pointer, err := modelType[T]()
	if err != nil {
		return nil, err
	}
	var d CollectionDefinition
	if definition == nil {
		d, err = DefinitionFor[T]()
	} else {
		d, err = definition.Normalize()
	}
	if err != nil {
		return nil, err
	}
	codec := &StructCodec[T]{typ: t, pointer: pointer, definition: d}
	add := func(name, role string) error {
		field, ok := t.FieldByName(name)
		if !ok || field.PkgPath != "" {
			return fmt.Errorf("%w: no exported model field %q", ErrSchemaMismatch, name)
		}
		if role == "vector" && field.Type != reflect.TypeFor[[]float32]() {
			return fmt.Errorf("%w: vector field %q must be []float32", ErrSchemaMismatch, name)
		}
		parent := t
		for _, index := range field.Index {
			for parent.Kind() == reflect.Pointer {
				parent = parent.Elem()
			}
			part := parent.Field(index)
			if part.PkgPath != "" {
				return fmt.Errorf("%w: field %q has an unexported embedded parent", ErrSchemaMismatch, name)
			}
			parent = part.Type
		}
		codec.fields = append(codec.fields, structField{field.Index, name, role})
		return nil
	}
	if err := add(d.Key.Name, "key"); err != nil {
		return nil, err
	}
	keyField, _ := t.FieldByName(d.Key.Name)
	keyType := keyField.Type
	for keyType.Kind() == reflect.Pointer {
		keyType = keyType.Elem()
	}
	validKey := d.Key.Type == KeyString && keyType.Kind() == reflect.String || d.Key.Type == KeyInt64 && (keyType.Kind() >= reflect.Int && keyType.Kind() <= reflect.Int64) || d.Key.Type == KeyUUID && (keyType.Kind() == reflect.String || reflect.PointerTo(keyType).Implements(reflect.TypeFor[encoding.TextUnmarshaler]()))
	if !validKey || d.Key.AutoGenerated && keyType.Bits() < 64 {
		return nil, fmt.Errorf("%w: model key type conflicts with definition", ErrSchemaMismatch)
	}
	for _, p := range d.Data {
		if err := add(p.Name, "data"); err != nil {
			return nil, err
		}
		field, _ := t.FieldByName(p.Name)
		if p.Type != TypeJSON && inferDataType(field.Type) != p.Type {
			return nil, fmt.Errorf("%w: field %q type conflicts with definition", ErrSchemaMismatch, p.Name)
		}
	}
	for _, p := range d.Vectors {
		if err := add(p.Name, "vector"); err != nil {
			return nil, err
		}
	}
	return codec, nil
}
func (c *StructCodec[T]) Definition() CollectionDefinition { return c.definition.Clone() }
func structValue(root reflect.Value, index []int, allocate bool) (reflect.Value, error) {
	for _, i := range index {
		for root.Kind() == reflect.Pointer {
			if root.IsNil() {
				if !allocate {
					return reflect.Value{}, nil
				}
				root.Set(reflect.New(root.Type().Elem()))
			}
			root = root.Elem()
		}
		root = root.Field(i)
	}
	return root, nil
}
func (c *StructCodec[T]) Encode(value T) (ModelRecord, error) {
	root := reflect.ValueOf(value)
	if c.pointer {
		if root.IsNil() {
			return ModelRecord{}, fmt.Errorf("%w: nil model", ErrInvalidRecord)
		}
		root = root.Elem()
	}
	out := ModelRecord{Data: map[string]any{}, Vectors: map[string][]float32{}}
	for _, field := range c.fields {
		v, _ := structValue(root, field.index, false)
		if !v.IsValid() {
			if field.role == "data" {
				out.Data[field.name] = nil
			}
			continue
		}
		switch field.role {
		case "key":
			if c.definition.Key.AutoGenerated && v.IsZero() {
				out.Key = nil
			} else {
				for v.Kind() == reflect.Pointer {
					if v.IsNil() {
						return out, fmt.Errorf("%w: nil key", ErrInvalidRecord)
					}
					v = v.Elem()
				}
				out.Key = v.Interface()
			}
		case "vector":
			out.Vectors[field.name] = append([]float32(nil), v.Interface().([]float32)...)
		case "data":
			for v.Kind() == reflect.Pointer {
				if v.IsNil() {
					break
				}
				v = v.Elem()
			}
			if v.Kind() == reflect.Pointer && v.IsNil() {
				out.Data[field.name] = nil
			} else {
				// Normalize integer and float aliases to portable native values.
				switch inferDataType(v.Type()) {
				case TypeInt64:
					out.Data[field.name] = v.Int()
				case TypeFloat64:
					out.Data[field.name] = v.Float()
				case TypeString:
					out.Data[field.name] = v.String()
				case TypeBool:
					out.Data[field.name] = v.Bool()
				default:
					out.Data[field.name] = v.Interface()
				}
			}
		}
	}
	return out, nil
}
func assignModelValue(target reflect.Value, value any) error {
	if value == nil {
		return nil
	}
	if target.Kind() == reflect.Pointer {
		if target.IsNil() {
			target.Set(reflect.New(target.Type().Elem()))
		}
		return assignModelValue(target.Elem(), value)
	}
	if text, ok := value.(string); ok && target.CanAddr() {
		if unmarshaler, ok := target.Addr().Interface().(encoding.TextUnmarshaler); ok {
			return unmarshaler.UnmarshalText([]byte(text))
		}
	}
	source := reflect.ValueOf(value)
	if source.Type().AssignableTo(target.Type()) {
		target.Set(source)
		return nil
	}
	switch target.Kind() {
	case reflect.Int, reflect.Int8, reflect.Int16, reflect.Int32, reflect.Int64:
		if source.Kind() == reflect.Int64 {
			if target.OverflowInt(source.Int()) {
				return fmt.Errorf("integer overflow")
			}
			target.SetInt(source.Int())
			return nil
		}
	case reflect.Float32, reflect.Float64:
		if source.Kind() == reflect.Float64 {
			if target.OverflowFloat(source.Float()) {
				return fmt.Errorf("float overflow")
			}
			target.SetFloat(source.Float())
			return nil
		}
	case reflect.String:
		if source.Kind() == reflect.String {
			target.SetString(source.String())
			return nil
		}
	}
	payload, err := json.Marshal(value)
	if err != nil {
		return err
	}
	decoder := json.NewDecoder(strings.NewReader(string(payload)))
	decoder.UseNumber()
	return decoder.Decode(target.Addr().Interface())
}
func (c *StructCodec[T]) Decode(record ModelRecord) (T, error) {
	var zero T
	root := reflect.New(c.typ).Elem()
	for _, field := range c.fields {
		target, err := structValue(root, field.index, true)
		if err != nil {
			return zero, err
		}
		var value any
		switch field.role {
		case "key":
			value = record.Key
		case "data":
			value = record.Data[field.name]
		case "vector":
			if record.Vectors != nil {
				value = record.Vectors[field.name]
			}
		}
		if err := assignModelValue(target, value); err != nil {
			return zero, fmt.Errorf("decode field %q: %w", field.name, err)
		}
	}
	if c.pointer {
		return root.Addr().Interface().(T), nil
	}
	return root.Interface().(T), nil
}

// TypedModelCollection provides native-key operations for a domain model.
// It complements the original TypedCollection[T], whose keys remain strings.
type TypedModelCollection[K comparable, T any] struct {
	base  ModelCollection
	codec ModelCodec[T]
}
type TypedModelSearchResult[T any] struct {
	Item            T
	Distance, Score float64
	ScoreKind       ScoreKind
}

func NewTypedModelCollection[K comparable, T any](base ModelCollection, codec ModelCodec[T]) (*TypedModelCollection[K, T], error) {
	if isNilValue(base) || isNilValue(codec) {
		return nil, fmt.Errorf("%w: collection and codec required", ErrSchemaMismatch)
	}
	typ := reflect.TypeFor[K]()
	kind := base.Definition().Key.Type
	valid := kind == KeyString && typ.Kind() == reflect.String || kind == KeyInt64 && (typ.Kind() == reflect.Int64 || typ.Kind() == reflect.Int && typ.Bits() == 64) || kind == KeyUUID && (typ.Kind() == reflect.String || reflect.PointerTo(typ).Implements(reflect.TypeFor[encoding.TextUnmarshaler]()))
	if !valid {
		return nil, fmt.Errorf("%w: typed key conflicts with collection definition", ErrSchemaMismatch)
	}
	return &TypedModelCollection[K, T]{base, codec}, nil
}

// GetTypedModelCollection creates a typed handle without accessing or creating storage.
// Struct tags are inferred when definition is nil; explicit definitions use Go field names.
func GetTypedModelCollection[K comparable, T any](store ModelStore, name string, definition *CollectionDefinition, opts ModelCollectionOptions) (*TypedModelCollection[K, T], error) {
	if isNilValue(store) {
		return nil, fmt.Errorf("%w: store is required", ErrSchemaMismatch)
	}
	codec, err := NewStructCodec[T](definition)
	if err != nil {
		return nil, err
	}
	base, err := store.GetModelCollection(name, codec.Definition(), opts)
	if err != nil {
		return nil, err
	}
	return NewTypedModelCollection[K, T](base, codec)
}

// EnsureTypedModelCollection creates or validates storage before returning a typed handle.
func EnsureTypedModelCollection[K comparable, T any](ctx context.Context, store ModelStore, name string, definition *CollectionDefinition, opts ModelCollectionOptions) (*TypedModelCollection[K, T], error) {
	typed, err := GetTypedModelCollection[K, T](store, name, definition, opts)
	if err != nil {
		return nil, err
	}
	if err := typed.EnsureExists(ctx); err != nil {
		return nil, err
	}
	return typed, nil
}

func (c *TypedModelCollection[K, T]) Name() string                     { return c.base.Name() }
func (c *TypedModelCollection[K, T]) Definition() CollectionDefinition { return c.base.Definition() }
func (c *TypedModelCollection[K, T]) Exists(ctx context.Context) (bool, error) {
	return c.base.Exists(ctx)
}
func (c *TypedModelCollection[K, T]) EnsureExists(ctx context.Context) error {
	return c.base.EnsureExists(ctx)
}
func (c *TypedModelCollection[K, T]) EnsureDeleted(ctx context.Context) error {
	return c.base.EnsureDeleted(ctx)
}
func (c *TypedModelCollection[K, T]) encode(values []T) ([]ModelRecord, error) {
	records := make([]ModelRecord, len(values))
	for i, value := range values {
		r, err := c.codec.Encode(value)
		if err != nil {
			return nil, err
		}
		records[i] = r
	}
	return records, nil
}
func typedKeys[K comparable](values []any) ([]K, error) {
	out := make([]K, len(values))
	for i, value := range values {
		if err := assignModelValue(reflect.ValueOf(&out[i]).Elem(), value); err != nil {
			return nil, err
		}
	}
	return out, nil
}
func (c *TypedModelCollection[K, T]) Insert(ctx context.Context, values []T) ([]K, error) {
	records, err := c.encode(values)
	if err != nil {
		return nil, err
	}
	keys, err := c.base.Insert(ctx, records)
	if err != nil {
		return nil, err
	}
	return typedKeys[K](keys)
}
func (c *TypedModelCollection[K, T]) Upsert(ctx context.Context, values []T) ([]K, error) {
	records, err := c.encode(values)
	if err != nil {
		return nil, err
	}
	keys, err := c.base.Upsert(ctx, records)
	if err != nil {
		return nil, err
	}
	return typedKeys[K](keys)
}
func (c *TypedModelCollection[K, T]) Get(ctx context.Context, key K, opts RetrievalOptions) (T, error) {
	r, err := c.base.Get(ctx, key, opts)
	if err != nil {
		var zero T
		return zero, err
	}
	return c.codec.Decode(r)
}
func (c *TypedModelCollection[K, T]) GetMany(ctx context.Context, keys []K, opts RetrievalOptions) ([]T, error) {
	values := make([]any, len(keys))
	for i, key := range keys {
		values[i] = key
	}
	records, err := c.base.GetMany(ctx, values, opts)
	if err != nil {
		return nil, err
	}
	return c.decode(records)
}
func (c *TypedModelCollection[K, T]) decode(records []ModelRecord) ([]T, error) {
	out := make([]T, len(records))
	for i, r := range records {
		v, err := c.codec.Decode(r)
		if err != nil {
			return nil, err
		}
		out[i] = v
	}
	return out, nil
}
func (c *TypedModelCollection[K, T]) Delete(ctx context.Context, keys []K) (int64, error) {
	values := make([]any, len(keys))
	for i, key := range keys {
		values[i] = key
	}
	return c.base.Delete(ctx, values)
}
func (c *TypedModelCollection[K, T]) Count(ctx context.Context, filter Filter) (int64, error) {
	return c.base.Count(ctx, filter)
}
func (c *TypedModelCollection[K, T]) QueryIter(ctx context.Context, filter Filter, top int, opts QueryOptions) iter.Seq2[T, error] {
	return func(yield func(T, error) bool) {
		for r, err := range c.base.QueryIter(ctx, filter, top, opts) {
			var value T
			if err == nil {
				value, err = c.codec.Decode(r)
			}
			if !yield(value, err) || err != nil {
				return
			}
		}
	}
}
func (c *TypedModelCollection[K, T]) Query(ctx context.Context, filter Filter, top int, opts QueryOptions) ([]T, error) {
	records, err := c.base.Query(ctx, filter, top, opts)
	if err != nil {
		return nil, err
	}
	return c.decode(records)
}
func (c *TypedModelCollection[K, T]) searchResults(results []ModelSearchResult, err error) ([]TypedModelSearchResult[T], error) {
	if err != nil {
		return nil, err
	}
	out := make([]TypedModelSearchResult[T], len(results))
	for i, r := range results {
		item, err := c.codec.Decode(r.Record)
		if err != nil {
			return nil, err
		}
		out[i] = TypedModelSearchResult[T]{item, r.Distance, r.Score, r.ScoreKind}
	}
	return out, nil
}
func (c *TypedModelCollection[K, T]) Search(ctx context.Context, vector []float32, top int, opts ModelSearchOptions) ([]TypedModelSearchResult[T], error) {
	return c.searchResults(c.base.Search(ctx, vector, top, opts))
}
func (c *TypedModelCollection[K, T]) SearchText(ctx context.Context, text string, top int, opts ModelSearchOptions) ([]TypedModelSearchResult[T], error) {
	return c.searchResults(c.base.SearchText(ctx, text, top, opts))
}
func (c *TypedModelCollection[K, T]) SearchIter(ctx context.Context, vector []float32, top int, opts ModelSearchOptions) iter.Seq2[TypedModelSearchResult[T], error] {
	return func(yield func(TypedModelSearchResult[T], error) bool) {
		for r, err := range c.base.SearchIter(ctx, vector, top, opts) {
			var item T
			if err == nil {
				item, err = c.codec.Decode(r.Record)
			}
			if !yield(TypedModelSearchResult[T]{item, r.Distance, r.Score, r.ScoreKind}, err) || err != nil {
				return
			}
		}
	}
}
func (c *TypedModelCollection[K, T]) HybridSearch(ctx context.Context, vector []float32, keywords string, top int, opts HybridSearchOptions) ([]TypedModelSearchResult[T], error) {
	h, ok := c.base.(HybridSearcher)
	if !ok {
		return nil, ErrUnsupported
	}
	return c.searchResults(h.HybridSearch(ctx, vector, keywords, top, opts))
}
func (c *TypedModelCollection[K, T]) HybridSearchText(ctx context.Context, text, keywords string, top int, opts HybridSearchOptions) ([]TypedModelSearchResult[T], error) {
	h, ok := c.base.(HybridSearcher)
	if !ok {
		return nil, ErrUnsupported
	}
	return c.searchResults(h.HybridSearchText(ctx, text, keywords, top, opts))
}
