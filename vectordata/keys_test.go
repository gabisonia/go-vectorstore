func TestUnsignedKeyNormalization(t *testing.T) {
	type ID uint64
	d := vectordata.CollectionDefinition{Key: vectordata.KeyProperty{Name: "ID", Type: vectordata.KeyUint64}}
	for _, tt := range []struct {
		input any
		want  uint64
	}{
		{uint64(math.MaxUint64), math.MaxUint64}, {ID(math.MaxUint64), math.MaxUint64},
		{int64(math.MaxInt64), math.MaxInt64}, {int(0), 0}, {uint8(255), 255},
	} {
		got, err := d.NormalizeKey(tt.input)
		if err != nil || got != tt.want {
			t.Fatalf("NormalizeKey(%v): %v, %v", tt.input, got, err)
		}
	}
	for _, invalid := range []any{nil, int(-1), int64(math.MinInt64), "1", float64(1), true, uintptr(1)} {
		if _, err := d.NormalizeKey(invalid); !errors.Is(err, vectordata.ErrInvalidRecord) {
			t.Fatalf("invalid unsigned key %v: %v", invalid, err)
		}
	}
	for _, kind := range []vectordata.KeyType{vectordata.KeyString, vectordata.KeyUint64} {
		d.Key.Type, d.Key.AutoGenerated = kind, true
		if _, err := d.Normalize(); !errors.Is(err, vectordata.ErrSchemaMismatch) {
			t.Fatalf("unexpected generated support for %v: %v", kind, err)
		}
	}
}

func TestGeneratedUUIDStringModels(t *testing.T) {
	type document struct {
		ID   string `vectordata:"key,type=uuid,generated"`
		Body string `vectordata:"data"`
	}
	ctx := context.Background()
	c, err := vectordata.EnsureTypedModelCollection[string, document](ctx, memory.New(), "uuid_strings", nil, vectordata.ModelCollectionOptions{})
	if err != nil {
		t.Fatal(err)
	}
	input := []document{{Body: "generated"}, {ID: "00000000-0000-0000-0000-000000000000", Body: "explicit zero UUID"}}
	keys, err := c.Insert(ctx, input)
	if err != nil || len(keys) != 2 || keys[0] == "" || keys[1] != input[1].ID || input[0].ID != "" {
		t.Fatalf("UUID string generation: %v, %v", keys, err)
	}
	for _, key := range keys {
		if got, err := c.Get(ctx, key, vectordata.RetrievalOptions{}); err != nil || got.ID != key {
			t.Fatalf("get generated UUID: %v, %v", got, err)
		}
	}
}

func TestNewUUIDKey(t *testing.T) {
	d := vectordata.CollectionDefinition{Key: vectordata.KeyProperty{Name: "ID", Type: vectordata.KeyUUID}}
	seen := map[string]bool{}
	for range 128 {
		key, err := vectordata.NewUUIDKey()
		if err != nil {
			t.Fatal(err)
		}
		canonical, err := d.NormalizeKey(key)
		if err != nil || canonical != key || key[14] != '4' || seen[key] {
			t.Fatalf("invalid/duplicate UUID: %s, %v", key, err)
		}
		seen[key] = true
	}
}

func TestUnsignedCodecNarrowingFails(t *testing.T) {
	type narrow struct {
		ID uint8 `vectordata:"key"`
	}
	codec, err := vectordata.NewStructCodec[narrow](nil)
	if err != nil {
		t.Fatal(err)
	}
	if _, err := codec.Decode(vectordata.ModelRecord{Key: uint64(256)}); err == nil {
		t.Fatal("unsigned key overflow silently narrowed")
	}
	if _, err := codec.Decode(vectordata.ModelRecord{Key: uint64(255)}); err != nil {
		t.Fatal(err)
	}
}
