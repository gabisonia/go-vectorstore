func openStore(t *testing.T, path string, opts sqlite.StoreOptions) *sqlite.Store {
	t.Helper()
	s, err := sqlite.Open(context.Background(), path, opts)
	if err != nil {
		t.Fatal(err)
	}
	t.Cleanup(func() {
		if err := s.Close(); err != nil {
			t.Error(err)
		}
	})
	return s
}
