func TestPersistenceAndAtomicity(t *testing.T) {
	ctx := context.Background()
	path := filepath.Join(t.TempDir(), "literal?# name.db")
	d := vectordata.CollectionDefinition{Key: vectordata.KeyProperty{Name: "ID", Type: vectordata.KeyInt64, AutoGenerated: true}, Data: []vectordata.DataProperty{{Name: "Name", Type: vectordata.TypeString}}}
	first, err := sqlite.Open(ctx, path, sqlite.StoreOptions{})
	if err != nil {
		t.Fatal(err)
	}
	c, err := first.EnsureModelCollection(ctx, "records", d, vectordata.ModelCollectionOptions{})
	if err != nil {
		t.Fatal(err)
	}
	if _, err = c.Insert(ctx, []vectordata.ModelRecord{{Data: map[string]any{"Name": "kept"}}}); err != nil {
		t.Fatal(err)
	}
	if _, err = c.Insert(ctx, []vectordata.ModelRecord{{Data: map[string]any{"Name": "rolled back"}}, {Key: int64(1), Data: map[string]any{"Name": "duplicate"}}}); !errors.Is(err, vectordata.ErrInvalidRecord) {
		t.Fatalf("duplicate: %v", err)
	}
	if err = first.Close(); err != nil {
		t.Fatal(err)
	}
	reopened := openStore(t, path, sqlite.StoreOptions{})
	c, err = reopened.EnsureModelCollection(ctx, "records", d, vectordata.ModelCollectionOptions{})
	if err != nil {
		t.Fatal(err)
	}
	row, err := c.Get(ctx, int64(1), vectordata.RetrievalOptions{})
	if err != nil || row.Data["Name"] != "kept" {
		t.Fatalf("persistence: %v %v", row, err)
	}
	keys, err := c.Insert(ctx, []vectordata.ModelRecord{{Data: map[string]any{"Name": "next"}}})
	if err != nil || len(keys) != 1 || keys[0] != int64(2) {
		t.Fatalf("atomic sequence: %v %v", keys, err)
	}
	if count, err := c.Count(ctx, nil); err != nil || count != 2 {
		t.Fatalf("batch rollback: %d %v", count, err)
	}
	changed := d.Clone()
	changed.Data[0].Optional = true
	wrong, err := reopened.GetModelCollection("records", changed, vectordata.ModelCollectionOptions{})
	if err != nil {
		t.Fatal(err)
	}
	if _, err := wrong.Get(ctx, int64(1), vectordata.RetrievalOptions{}); !errors.Is(err, vectordata.ErrSchemaMismatch) {
		t.Fatalf("stale schema: %v", err)
	}
	if err := c.EnsureDeleted(ctx); err != nil {
		t.Fatal(err)
	}
	if err := c.EnsureExists(ctx); err != nil {
		t.Fatal(err)
	}
	if n, err := c.Count(ctx, nil); err != nil || n != 0 {
		t.Fatalf("delete cascade: %d %v", n, err)
	}
}
func TestConcurrentStoreHandles(t *testing.T) {
	ctx := context.Background()
	path := filepath.Join(t.TempDir(), "shared.db")
	d := vectordata.CollectionDefinition{Key: vectordata.KeyProperty{Name: "ID", Type: vectordata.KeyInt64, AutoGenerated: true}}
	a := openStore(t, path, sqlite.StoreOptions{})
	b := openStore(t, path, sqlite.StoreOptions{})
	ca, err := a.EnsureModelCollection(ctx, "records", d, vectordata.ModelCollectionOptions{})
	if err != nil {
		t.Fatal(err)
	}
	cb, err := b.EnsureModelCollection(ctx, "records", d, vectordata.ModelCollectionOptions{})
	if err != nil {
		t.Fatal(err)
	}
	var wg sync.WaitGroup
	results := make(chan any, 40)
	for i := 0; i < 40; i++ {
		wg.Add(1)
		go func(i int) {
			defer wg.Done()
			c := ca
			if i%2 == 0 {
				c = cb
			}
			keys, err := c.Insert(ctx, []vectordata.ModelRecord{{}})
			if err != nil {
				t.Error(err)
				return
			}
			results <- keys[0]
		}(i)
	}
	wg.Wait()
	close(results)
	seen := map[any]bool{}
	for key := range results {
		if seen[key] {
			t.Errorf("duplicate generated key: %v", key)
		}
		seen[key] = true
	}
	if len(seen) != 40 {
		t.Fatalf("writes lost: %d", len(seen))
	}
	// Breaking an iterator must release its snapshot and connection.
	for _, err := range ca.QueryIter(ctx, nil, 40, vectordata.QueryOptions{}) {
		if err != nil {
			t.Fatal(err)
		}
		break
	}
	if _, err := cb.Insert(ctx, []vectordata.ModelRecord{{}}); err != nil {
		t.Fatal(err)
	}
	canceled, cancel := context.WithCancel(ctx)
	cancel()
	if _, err := ca.Count(canceled, nil); !errors.Is(err, context.Canceled) {
		t.Fatalf("cancellation: %v", err)
	}
}

func TestNativeValuesAfterReopen(t *testing.T) {
	ctx := context.Background()
	path := filepath.Join(t.TempDir(), "native.db")
	instant := time.Date(2026, 7, 1, 9, 2, 3, 123456000, time.UTC)
	d := vectordata.CollectionDefinition{Key: vectordata.KeyProperty{Name: "ID"}, Data: []vectordata.DataProperty{
		{Name: "JSON", Type: vectordata.TypeJSON, Optional: true}, {Name: "Bytes", Type: vectordata.TypeBytes},
		{Name: "Decimal", Type: vectordata.TypeDecimal}, {Name: "Decimals", Type: vectordata.TypeDecimalArray},
		{Name: "Times", Type: vectordata.TypeTimeArray}, {Name: "Ints", Type: vectordata.TypeInt64Array},
	}, Vectors: []vectordata.VectorProperty{{Name: "Dense", Dimensions: 2, Optional: true}, {Name: "Bits", Dimensions: 2, Kind: vectordata.VectorBinary, Optional: true}, {Name: "Sparse", Dimensions: 2, Kind: vectordata.VectorSparse, Optional: true}}}
	bits, _ := vectordata.ParseBinaryVector("10")
	sparse, _ := vectordata.NewSparseVector(2, []int{0}, []float32{1})
	input := vectordata.ModelRecord{Key: "exact", Data: map[string]any{
		"JSON": map[string]any{"number": json.Number("9007199254740993")}, "Bytes": []byte{0, 255},
		"Decimal": vectordata.Decimal("79228162514264337593543950335"), "Decimals": []vectordata.Decimal{"0.0000000000000000000000000001"},
		"Times": []time.Time{instant}, "Ints": []int64{9007199254740993},
	}, Vectors: map[string][]float32{"Dense": {1, 0}}, BinaryVectors: map[string]vectordata.BinaryVector{"Bits": bits}, SparseVectors: map[string]vectordata.SparseVector{"Sparse": sparse}}
	store, err := sqlite.Open(ctx, path, sqlite.StoreOptions{})
	if err != nil {
		t.Fatal(err)
	}
	c, err := store.EnsureModelCollection(ctx, "native", d, vectordata.ModelCollectionOptions{})
	if err != nil {
		t.Fatal(err)
	}
	null := input
	null.Key = "sql_null"
	null.Data = map[string]any{}
	for name, value := range input.Data {
		null.Data[name] = value
	}
	null.Data["JSON"] = nil
	jsonNull := null
	jsonNull.Key = "json_null"
	jsonNull.Data = map[string]any{}
	for name, value := range null.Data {
		jsonNull.Data[name] = value
	}
	jsonNull.Data["JSON"] = vectordata.JSONNull{}
	if _, err := c.Insert(ctx, []vectordata.ModelRecord{input, null, jsonNull}); err != nil {
		t.Fatal(err)
	}
	if err := store.Close(); err != nil {
		t.Fatal(err)
	}
	reopened := openStore(t, path, sqlite.StoreOptions{})
	c, err = reopened.EnsureModelCollection(ctx, "native", d, vectordata.ModelCollectionOptions{})
	if err != nil {
		t.Fatal(err)
	}
	row, err := c.Get(ctx, "exact", vectordata.RetrievalOptions{IncludeVectors: true})
	if err != nil || !reflect.DeepEqual(row, input) {
		t.Fatalf("native restart round trip: %+v %v", row, err)
	}
	sqlNull, err := c.Get(ctx, "sql_null", vectordata.RetrievalOptions{})
	if err != nil || sqlNull.Data["JSON"] != nil {
		t.Fatalf("SQL NULL: %+v %v", sqlNull, err)
	}
	literalNull, err := c.Get(ctx, "json_null", vectordata.RetrievalOptions{})
	if err != nil {
		t.Fatal(err)
	}
	if _, ok := literalNull.Data["JSON"].(vectordata.JSONNull); !ok {
		t.Fatalf("JSON null became SQL NULL: %+v", literalNull)
	}
}
func TestNativeTextValidationAndProviderError(t *testing.T) {
	ctx := context.Background()
	store := openStore(t, ":memory:", sqlite.StoreOptions{})
	d := vectordata.CollectionDefinition{Key: vectordata.KeyProperty{Name: "ID"}, Data: []vectordata.DataProperty{{Name: "Text", Type: vectordata.TypeString}}}
	c, err := store.EnsureModelCollection(ctx, "text", d, vectordata.ModelCollectionOptions{})
	if err != nil {
		t.Fatal(err)
	}
	bad := string([]byte{0xff})
	for _, row := range []vectordata.ModelRecord{{Key: bad, Data: map[string]any{"Text": "ok"}}, {Key: "bad", Data: map[string]any{"Text": bad}}} {
		if _, err := c.Insert(ctx, []vectordata.ModelRecord{row}); !errors.Is(err, vectordata.ErrInvalidRecord) {
			t.Fatalf("lossy text accepted: %v", err)
		}
	}
	row := vectordata.ModelRecord{Key: "good", Data: map[string]any{"Text": "ok"}}
	if _, err := c.Insert(ctx, []vectordata.ModelRecord{row}); err != nil {
		t.Fatal(err)
	}
	_, err = c.Insert(ctx, []vectordata.ModelRecord{row})
	var driverError *driver.Error
	if !errors.Is(err, vectordata.ErrInvalidRecord) || !errors.As(err, &driverError) {
		t.Fatalf("provider error lost: %v", err)
	}
}
