package sqlite_test

import (
	"context"
	"math"
	"path/filepath"
	"testing"

	"github.com/gabisonia/go-vectorstore/stores/sqlite"
	"github.com/gabisonia/go-vectorstore/vectordata"
)

func TestNativeKeysSurviveReopen(t *testing.T) {
	ctx := context.Background()
	path := filepath.Join(t.TempDir(), "keys.db")
	store, err := sqlite.Open(ctx, path, sqlite.StoreOptions{})
	if err != nil {
		t.Fatal(err)
	}
	defer store.Close()
	d := vectordata.CollectionDefinition{Key: vectordata.KeyProperty{Name: "ID", Type: vectordata.KeyUint64}}
	unsigned, err := store.EnsureModelCollection(ctx, "unsigned", d, vectordata.ModelCollectionOptions{})
	if err != nil {
		t.Fatal(err)
	}
	if _, err := unsigned.Upsert(ctx, []vectordata.ModelRecord{{Key: uint64(0)}, {Key: uint64(math.MaxUint64)}}); err != nil {
		t.Fatal(err)
	}
	u := vectordata.CollectionDefinition{Key: vectordata.KeyProperty{Name: "ID", Type: vectordata.KeyUUID, AutoGenerated: true}}
	uuids, err := store.EnsureModelCollection(ctx, "uuids", u, vectordata.ModelCollectionOptions{})
	if err != nil {
		t.Fatal(err)
	}
	keys, err := uuids.Insert(ctx, []vectordata.ModelRecord{{}})
	if err != nil {
		t.Fatal(err)
	}
	if err := store.Close(); err != nil {
		t.Fatal(err)
	}
	reopened := openStore(t, path, sqlite.StoreOptions{})
	unsigned, err = reopened.GetModelCollection("unsigned", d, vectordata.ModelCollectionOptions{})
	if err != nil {
		t.Fatal(err)
	}
	for _, key := range []uint64{0, math.MaxUint64} {
		got, err := unsigned.Get(ctx, key, vectordata.RetrievalOptions{})
		if err != nil || got.Key != key {
			t.Fatalf("uint64 reopen: %v, %v", got, err)
		}
	}
	uuids, err = reopened.GetModelCollection("uuids", u, vectordata.ModelCollectionOptions{})
	if err != nil {
		t.Fatal(err)
	}
	if got, err := uuids.Get(ctx, keys[0], vectordata.RetrievalOptions{}); err != nil || got.Key != keys[0] {
		t.Fatalf("UUID reopen: %v, %v", got, err)
	}
	if more, err := uuids.Insert(ctx, []vectordata.ModelRecord{{}}); err != nil || more[0] == keys[0] {
		t.Fatalf("UUID generation after reopen: %v, %v", more, err)
	}
}
