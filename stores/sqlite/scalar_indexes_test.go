func scalarIndexFixture(t *testing.T, d vectordata.CollectionDefinition, native bool) (*Store, *Collection) {
	t.Helper()
	s, err := Open(context.Background(), filepath.Join(t.TempDir(), "native.db"), StoreOptions{NativeIndexes: native})
	if err != nil {
		t.Fatal(err)
	}
	t.Cleanup(func() { s.Close() })
	base, err := s.EnsureModelCollection(context.Background(), "records", d, vectordata.ModelCollectionOptions{})
	if err != nil {
		t.Fatal(err)
	}
	return s, base.(*Collection)
}

func scalarIndexDefinition() vectordata.CollectionDefinition {
	return vectordata.CollectionDefinition{Key: vectordata.KeyProperty{Name: "ID", Type: vectordata.KeyInt64, AutoGenerated: true}, Data: []vectordata.DataProperty{
		{Name: scalarTextName, Type: vectordata.TypeString, IsIndexed: true, Optional: true},
		{Name: "Number", Type: vectordata.TypeInt64, IsIndexed: true, Optional: true},
		{Name: "Amount", Type: vectordata.TypeFloat64, IsIndexed: true, Optional: true},
		{Name: "Active", Type: vectordata.TypeBool, IsIndexed: true, Optional: true},
		{Name: "Unindexed", Type: vectordata.TypeString, Optional: true},
		{Name: "JSON", Type: vectordata.TypeJSON, Optional: true},
	}}
}

func scalarIndexRow(key any, number int64) vectordata.ModelRecord {
	return vectordata.ModelRecord{Key: key, Data: map[string]any{scalarTextName: "literal'\x00雪", "Number": number, "Amount": math.Nextafter(1, 2), "Active": true}}
}

func indexedPlan(t *testing.T, c *Collection, f vectordata.Filter, count bool) scalarQueryPlan {
	t.Helper()
	plan, ok, err := c.scalarPlan(f, 5, vectordata.QueryOptions{}, count)
	if err != nil || !ok {
		t.Fatalf("base plan: %v %v", ok, err)
	}
	tx, err := c.store.db.BeginTx(context.Background(), &sql.TxOptions{ReadOnly: true})
	if err != nil {
		t.Fatal(err)
	}
	defer tx.Rollback()
	plan, err = c.indexedScalarPlan(context.Background(), tx, plan)
	if err != nil {
		t.Fatal(err)
	}
	return plan
}

func TestNativeScalarIndexQueryPlans(t *testing.T) {
	ctx := context.Background()
	s, c := scalarIndexFixture(t, scalarIndexDefinition(), true)
	var input []vectordata.ModelRecord
	for i := range 128 {
		input = append(input, scalarIndexRow(int64(i), int64(i)))
	}
	if _, err := c.Insert(ctx, input); err != nil {
		t.Fatal(err)
	}
	for _, f := range []vectordata.Filter{
		vectordata.Eq(vectordata.Column(scalarTextName), "literal'\x00雪"),
		vectordata.Eq(vectordata.Column("Number"), int64(99)),
		vectordata.Gte(vectordata.Column("Number"), int64(99)),
		vectordata.In(vectordata.Column("Number"), int64(99), int64(100), nil),
		vectordata.Eq(vectordata.Column("Amount"), math.Nextafter(1, 2)),
		vectordata.Eq(vectordata.Column("Active"), true),
		vectordata.Eq(vectordata.Column("Active"), nil),
	} {
		for _, count := range []bool{false, true} {
			plan := indexedPlan(t, c, f, count)
			rows, err := s.db.QueryContext(ctx, "EXPLAIN QUERY PLAN "+plan.sql, plan.args...)
			if err != nil {
				t.Fatal(err)
			}
			var details []string
			for rows.Next() {
				var a, b, d int
				var detail string
				if err := rows.Scan(&a, &b, &d, &detail); err != nil {
					t.Fatal(err)
				}
				details = append(details, detail)
			}
			if err := rows.Err(); err != nil {
				t.Fatal(err)
			}
			rows.Close()
			proof := strings.Join(details, "\n")
			if !strings.Contains(proof, "__vectorstore_scalar_lookup (collection=? AND property=? AND value") || !strings.Contains(proof, "(collection=? AND key=?)") {
				t.Fatalf("filter did not use value index and record key lookup: %T\n%s", f, proof)
			}
			if strings.Contains(plan.sql, scalarTextName) || strings.Contains(plan.sql, "literal'") {
				t.Fatal("unbound names/values")
			}
		}
	}
	for _, f := range []vectordata.Filter{
		vectordata.Not(vectordata.In(vectordata.Column("Number"), int64(99), nil)),
		vectordata.Or(vectordata.Eq(vectordata.Column("Number"), int64(99)), vectordata.Eq(vectordata.Column("Unindexed"), "x")),
	} {
		if strings.Contains(indexedPlan(t, c, f, true).sql, "__vectorstore_scalar_values") {
			t.Fatal("unsafe candidate restriction")
		}
	}
	// Discard parameters from an unindexable OR nested after a useful conjunct.
	f := vectordata.And(vectordata.Eq(vectordata.Column("Number"), int64(99)), vectordata.Or(vectordata.Eq(vectordata.Column("Active"), true), vectordata.Eq(vectordata.Column("Unindexed"), "x")))
	if n, err := c.Count(ctx, f); err != nil || n != 1 {
		t.Fatalf("mixed groups: %d %v", n, err)
	}
}

func TestNativeScalarIndexBackfillAndLegacyWriters(t *testing.T) {
	ctx := context.Background()
	path := filepath.Join(t.TempDir(), "legacy.db")
	old, err := Open(ctx, path, StoreOptions{})
	if err != nil {
		t.Fatal(err)
	}
	defer old.Close()
	d := scalarIndexDefinition()
	legacy, err := old.EnsureModelCollection(ctx, "records", d, vectordata.ModelCollectionOptions{})
	if err != nil {
		t.Fatal(err)
	}
	if _, err := legacy.Insert(ctx, []vectordata.ModelRecord{scalarIndexRow(nil, 9007199254740993)}); err != nil {
		t.Fatal(err)
	}
	var before []byte
	if err := old.db.QueryRow(`SELECT payload FROM __vectorstore_records`).Scan(&before); err != nil {
		t.Fatal(err)
	}
	native, err := Open(ctx, path, StoreOptions{NativeIndexes: true})
	if err != nil {
		t.Fatal(err)
	}
	defer native.Close()
	base, err := native.EnsureModelCollection(ctx, "records", d, vectordata.ModelCollectionOptions{})
	if err != nil {
		t.Fatal(err)
	}
	c := base.(*Collection)
	f := vectordata.Eq(vectordata.Column("Number"), int64(9007199254740993))
	if strings.Contains(indexedPlan(t, c, f, true).sql, "__vectorstore_scalar_values") {
		t.Fatal("existing collection implicitly backfilled")
	}
	if n, err := c.Count(ctx, f); err != nil || n != 1 {
		t.Fatalf("unbuilt fallback: %d %v", n, err)
	}
	if err := c.RebuildScalarIndexes(ctx); err != nil {
		t.Fatal(err)
	}
	if !strings.Contains(indexedPlan(t, c, f, true).sql, "__vectorstore_scalar_values") {
		t.Fatal("backfill not used")
	}
	var after []byte
	var format int
	if err := native.db.QueryRow(`SELECT payload,format FROM __vectorstore_records JOIN __vectorstore_collections ON name=collection`).Scan(&after, &format); err != nil {
		t.Fatal(err)
	}
	if format != 1 || !bytes.Equal(before, after) {
		t.Fatal("canonical format changed")
	}
	if _, err := legacy.Upsert(ctx, []vectordata.ModelRecord{scalarIndexRow(int64(1), math.MaxInt64), scalarIndexRow(nil, math.MinInt64)}); err != nil {
		t.Fatal(err)
	}
	if n, err := c.Count(ctx, f); err != nil || n != 0 {
		t.Fatalf("stale projection: %d %v", n, err)
	}
	for _, number := range []int64{math.MinInt64, math.MaxInt64} {
		if n, err := c.Count(ctx, vectordata.Eq(vectordata.Column("Number"), number)); err != nil || n != 1 {
			t.Fatalf("legacy writer index: %d %v", n, err)
		}
	}
	if _, err := legacy.Delete(ctx, []any{int64(1)}); err != nil {
		t.Fatal(err)
	}
	if n, err := c.Count(ctx, vectordata.Eq(vectordata.Column("Number"), int64(math.MaxInt64))); err != nil || n != 0 {
		t.Fatalf("delete projection: %d %v", n, err)
	}
	if err := legacy.EnsureDeleted(ctx); err != nil {
		t.Fatal(err)
	}
	var n int
	for _, table := range []string{"__vectorstore_scalar_indexes", "__vectorstore_scalar_values"} {
		if err := native.db.QueryRow(`SELECT count(*) FROM ` + table).Scan(&n); err != nil || n != 0 {
			t.Fatalf("cleanup %s: %d %v", table, n, err)
		}
	}
	if err := c.EnsureExists(ctx); err != nil {
		t.Fatal(err)
	}
	if _, err := c.Insert(ctx, []vectordata.ModelRecord{scalarIndexRow(nil, 1)}); err != nil {
		t.Fatal(err)
	}
	if n, err := c.Count(ctx, vectordata.Eq(vectordata.Column("Number"), int64(1))); err != nil || n != 1 {
		t.Fatalf("recreated collection: %d %v", n, err)
	}
}

func TestNativeScalarIndexFailureAtomicity(t *testing.T) {
	ctx := context.Background()
	s, c := scalarIndexFixture(t, scalarIndexDefinition(), true)
	if _, err := c.Insert(ctx, []vectordata.ModelRecord{scalarIndexRow(nil, 1)}); err != nil {
		t.Fatal(err)
	}
	_, err := s.db.Exec(`CREATE TRIGGER fail_scalar BEFORE INSERT ON __vectorstore_scalar_values WHEN NEW.property='Number' AND NEW.value=3 BEGIN SELECT RAISE(ABORT,'injected projection failure'); END`)
	if err != nil {
		t.Fatal(err)
	}
	if _, err := c.Insert(ctx, []vectordata.ModelRecord{scalarIndexRow(nil, 2), scalarIndexRow(nil, 3)}); !errors.Is(err, vectordata.ErrInvalidRecord) {
		t.Fatalf("projection failure: %v", err)
	}
	if n, err := c.Count(ctx, vectordata.Gte(vectordata.Column("Number"), int64(2))); err != nil || n != 0 {
		t.Fatalf("partial index: %d %v", n, err)
	}
	if _, err := c.Upsert(ctx, []vectordata.ModelRecord{scalarIndexRow(int64(1), 2), scalarIndexRow(nil, 3)}); err == nil {
		t.Fatal("upsert should fail")
	}
	if n, err := c.Count(ctx, vectordata.Eq(vectordata.Column("Number"), int64(1))); err != nil || n != 1 {
		t.Fatalf("update rollback: %d %v", n, err)
	}
	if _, err := s.db.Exec(`DROP TRIGGER fail_scalar`); err != nil {
		t.Fatal(err)
	}
	keys, err := c.Insert(ctx, []vectordata.ModelRecord{scalarIndexRow(nil, 3)})
	if err != nil || !reflect.DeepEqual(keys, []any{int64(2)}) {
		t.Fatalf("sequence rollback: %v %v", keys, err)
	}
	if _, err := s.db.Exec(`CREATE TRIGGER fail_rebuild BEFORE INSERT ON __vectorstore_scalar_values BEGIN SELECT RAISE(ABORT,'injected rebuild failure'); END`); err != nil {
		t.Fatal(err)
	}
	if err := c.RebuildScalarIndexes(ctx); !errors.Is(err, vectordata.ErrInvalidRecord) {
		t.Fatalf("rebuild failure: %v", err)
	}
	if n, err := c.Count(ctx, vectordata.Eq(vectordata.Column("Number"), int64(3))); err != nil || n != 1 {
		t.Fatalf("failed rebuild destroyed ready index: %d %v", n, err)
	}
	canceled, cancel := context.WithCancel(ctx)
	cancel()
	if err := c.RebuildScalarIndexes(canceled); !errors.Is(err, context.Canceled) {
		t.Fatal(err)
	}
}

func TestNativeScalarIndexValidation(t *testing.T) {
	ctx := context.Background()
	plain, c := scalarIndexFixture(t, scalarIndexDefinition(), false)
	if len(plain.Capabilities().IndexedDataTypes) != 0 {
		t.Fatal("plain indexes advertised")
	}
	if err := c.RebuildScalarIndexes(ctx); !errors.Is(err, vectordata.ErrUnsupported) {
		t.Fatal(err)
	}
	s, c := scalarIndexFixture(t, scalarIndexDefinition(), true)
	if len(s.Capabilities().IndexedDataTypes) != 4 || len(s.Capabilities().VectorIndexMethods) != 0 || s.Capabilities().FullTextIndexing {
		t.Fatal("native capabilities")
	}
	missing, err := s.GetModelCollection("absent", c.Definition(), vectordata.ModelCollectionOptions{})
	if err != nil {
		t.Fatal(err)
	}
	if err := missing.(*Collection).RebuildScalarIndexes(ctx); !errors.Is(err, vectordata.ErrCollectionNotFound) {
		t.Fatal(err)
	}
	d := c.Definition()
	d.Data[0].IsIndexed = false
	stale, err := s.GetModelCollection(c.name, d, vectordata.ModelCollectionOptions{})
	if err != nil {
		t.Fatal(err)
	}
	if err := stale.(*Collection).RebuildScalarIndexes(ctx); !errors.Is(err, vectordata.ErrSchemaMismatch) {
		t.Fatal(err)
	}
	if _, err := s.db.Exec(`UPDATE __vectorstore_scalar_indexes SET properties='{}'`); err != nil {
		t.Fatal(err)
	}
	if _, err := c.Count(ctx, vectordata.Eq(vectordata.Column("Number"), int64(1))); !errors.Is(err, vectordata.ErrSchemaMismatch) {
		t.Fatalf("index drift: %v", err)
	}
	if err := c.RebuildScalarIndexes(ctx); err != nil {
		t.Fatal(err)
	}
}
