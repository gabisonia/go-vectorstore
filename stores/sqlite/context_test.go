// The competing writer uses a separate raw connection, so provider-side mutexes
// cannot satisfy these tests. The IMMEDIATE transaction owns SQLite's write lock.
func holdWriter(t *testing.T, path string) func() {
	t.Helper()
	db, err := sql.Open("sqlite", path)
	if err != nil {
		t.Fatal(err)
	}
	t.Cleanup(func() { db.Close() })
	conn, err := db.Conn(context.Background())
	if err != nil {
		t.Fatal(err)
	}
	t.Cleanup(func() { conn.Close() })
	if _, err := conn.ExecContext(context.Background(), "BEGIN IMMEDIATE"); err != nil {
		t.Fatal(err)
	}
	released := false
	release := func() {
		if !released {
			if _, err := conn.ExecContext(context.Background(), "ROLLBACK"); err != nil {
				t.Error(err)
			}
			released = true
		}
	}
	t.Cleanup(release)
	return release
}
func TestWriteContentionDeadline(t *testing.T) {
	ctx := context.Background()
	path := filepath.Join(t.TempDir(), "locked.db")
	store := openStore(t, path, sqlite.StoreOptions{})
	d := vectordata.CollectionDefinition{Key: vectordata.KeyProperty{Name: "ID", Type: vectordata.KeyInt64, AutoGenerated: true}}
	c, err := store.EnsureModelCollection(ctx, "records", d, vectordata.ModelCollectionOptions{})
	if err != nil {
		t.Fatal(err)
	}
	release := holdWriter(t, path)
	deadline, cancel := context.WithTimeout(ctx, 50*time.Millisecond)
	defer cancel()
	start := time.Now()
	_, err = c.Insert(deadline, []vectordata.ModelRecord{{}})
	if !errors.Is(err, context.DeadlineExceeded) {
		t.Errorf("deadline error lost: %v", err)
	}
	if elapsed := time.Since(start); elapsed > time.Second {
		t.Errorf("50ms deadline blocked for %v", elapsed)
	}
	release()
	if n, err := c.Count(ctx, nil); err != nil || n != 0 {
		t.Fatalf("timed out batch committed: %d %v", n, err)
	}
	keys, err := c.Insert(ctx, []vectordata.ModelRecord{{}})
	if err != nil || len(keys) != 1 || keys[0] != int64(1) {
		t.Fatalf("connection/sequence not reusable: %v %v", keys, err)
	}
}

func TestMutationContentionDeadlines(t *testing.T) {
	for _, operation := range []string{"upsert", "delete", "ensure", "delete_collection", "open"} {
		t.Run(operation, func(t *testing.T) {
			ctx := context.Background()
			path := filepath.Join(t.TempDir(), "locked.db")
			store := openStore(t, path, sqlite.StoreOptions{})
			d := vectordata.CollectionDefinition{Key: vectordata.KeyProperty{Name: "ID", Type: vectordata.KeyInt64, AutoGenerated: true}}
			c, err := store.EnsureModelCollection(ctx, "records", d, vectordata.ModelCollectionOptions{})
			if err != nil {
				t.Fatal(err)
			}
			release := holdWriter(t, path)
			deadline, cancel := context.WithTimeout(ctx, 50*time.Millisecond)
			defer cancel()
			start := time.Now()
			switch operation {
			case "upsert":
				_, err = c.Upsert(deadline, []vectordata.ModelRecord{{}})
			case "delete":
				_, err = c.Delete(deadline, []any{int64(1)})
			case "ensure":
				err = c.EnsureExists(deadline)
			case "delete_collection":
				err = store.DeleteCollection(deadline, "records")
			case "open":
				var other *sqlite.Store
				other, err = sqlite.Open(deadline, path, sqlite.StoreOptions{})
				if other != nil {
					other.Close()
				}
			}
			if !errors.Is(err, context.DeadlineExceeded) {
				t.Errorf("deadline error lost: %v", err)
			}
			if elapsed := time.Since(start); elapsed > time.Second {
				t.Errorf("50ms deadline blocked for %v", elapsed)
			}
			release()
			if n, err := c.Count(ctx, nil); err != nil || n != 0 {
				t.Fatalf("timed out operation changed collection: %d %v", n, err)
			}
			keys, err := c.Insert(ctx, []vectordata.ModelRecord{{}})
			if err != nil || len(keys) != 1 || keys[0] != int64(1) {
				t.Fatalf("connection/sequence not reusable: %v %v", keys, err)
			}
		})
	}
}

func TestCancelInFlightWrite(t *testing.T) {
	ctx := context.Background()
	path := filepath.Join(t.TempDir(), "locked.db")
	store := openStore(t, path, sqlite.StoreOptions{})
	d := vectordata.CollectionDefinition{Key: vectordata.KeyProperty{Name: "ID", Type: vectordata.KeyInt64, AutoGenerated: true}}
	c, err := store.EnsureModelCollection(ctx, "records", d, vectordata.ModelCollectionOptions{})
	if err != nil {
		t.Fatal(err)
	}
	release := holdWriter(t, path)
	canceled, cancel := context.WithCancel(ctx)
	defer cancel()
	started := make(chan struct{})
	done := make(chan error, 1)
	go func() { close(started); _, err := c.Insert(canceled, []vectordata.ModelRecord{{}}); done <- err }()
	<-started
	select {
	case err := <-done:
		t.Fatalf("write did not wait for writer: %v", err)
	case <-time.After(75 * time.Millisecond):
	}
	start := time.Now()
	cancel()
	select {
	case err := <-done:
		if !errors.Is(err, context.Canceled) {
			t.Fatalf("cancellation error lost: %v", err)
		}
	case <-time.After(time.Second):
		t.Fatal("write ignored cancellation")
	}
	if elapsed := time.Since(start); elapsed > time.Second {
		t.Fatalf("cancellation took %v", elapsed)
	}
	release()
	if n, err := c.Count(ctx, nil); err != nil || n != 0 {
		t.Fatalf("canceled batch committed: %d %v", n, err)
	}
	keys, err := c.Insert(ctx, []vectordata.ModelRecord{{}})
	if err != nil || len(keys) != 1 || keys[0] != int64(1) {
		t.Fatalf("connection/sequence not reusable: %v %v", keys, err)
	}
}

func TestWriteSucceedsAfterContention(t *testing.T) {
	ctx, cancel := context.WithTimeout(context.Background(), 3*time.Second)
	defer cancel()
	path := filepath.Join(t.TempDir(), "locked.db")
	store := openStore(t, path, sqlite.StoreOptions{})
	d := vectordata.CollectionDefinition{Key: vectordata.KeyProperty{Name: "ID", Type: vectordata.KeyInt64, AutoGenerated: true}}
	c, err := store.EnsureModelCollection(ctx, "records", d, vectordata.ModelCollectionOptions{})
	if err != nil {
		t.Fatal(err)
	}
	release := holdWriter(t, path)
	type result struct {
		keys []any
		err  error
	}
	done := make(chan result, 1)
	go func() { keys, err := c.Insert(ctx, []vectordata.ModelRecord{{}}); done <- result{keys, err} }()
	select {
	case result := <-done:
		t.Fatalf("write did not wait for writer: %+v", result)
	case <-time.After(75 * time.Millisecond):
	}
	// WAL readers must still run while the same Store retries a competing writer.
	if n, err := c.Count(ctx, nil); err != nil || n != 0 {
		t.Fatalf("reader blocked behind retry loop: %d %v", n, err)
	}
	release()
	select {
	case result := <-done:
		if result.err != nil || len(result.keys) != 1 || result.keys[0] != int64(1) {
			t.Fatalf("write after lock release: %+v", result)
		}
	case <-ctx.Done():
		t.Fatal(ctx.Err())
	}
	if n, err := c.Count(ctx, nil); err != nil || n != 1 {
		t.Fatalf("write replayed or lost: %d %v", n, err)
	}
	keys, err := c.Insert(ctx, []vectordata.ModelRecord{{}})
	if err != nil || len(keys) != 1 || keys[0] != int64(2) {
		t.Fatalf("sequence advanced more than once: %v %v", keys, err)
	}
}

func TestContentionWaitLimitPreservesSQLiteError(t *testing.T) {
	ctx := context.Background()
	path := filepath.Join(t.TempDir(), "locked.db")
	store := openStore(t, path, sqlite.StoreOptions{})
	c, err := store.EnsureModelCollection(ctx, "records", vectordata.CollectionDefinition{Key: vectordata.KeyProperty{Name: "ID"}}, vectordata.ModelCollectionOptions{})
	if err != nil {
		t.Fatal(err)
	}
	release := holdWriter(t, path)
	start := time.Now()
	_, err = c.Insert(ctx, []vectordata.ModelRecord{{Key: "a"}})
	var busy *driver.Error
	if !errors.As(err, &busy) || busy.Code()&255 != 5 {
		t.Fatalf("SQLite busy error lost: %v", err)
	}
	if errors.Is(err, context.DeadlineExceeded) {
		t.Fatalf("internal contention limit became a caller deadline: %v", err)
	}
	if elapsed := time.Since(start); elapsed < 4500*time.Millisecond || elapsed > 7*time.Second {
		t.Fatalf("five-second lock wait changed: %v", elapsed)
	}
	release()
	if _, err := c.Insert(ctx, []vectordata.ModelRecord{{Key: "a"}}); err != nil {
		t.Fatalf("connection unusable after contention timeout: %v", err)
	}
}
