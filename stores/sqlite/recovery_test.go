func recoveryDefinition() vectordata.CollectionDefinition {
	return vectordata.CollectionDefinition{Key: vectordata.KeyProperty{Name: "ID", Type: vectordata.KeyInt64, AutoGenerated: true}, Data: []vectordata.DataProperty{{Name: "Body", Type: vectordata.TypeString}}}
}

// A real driver hook pauses only after the provider has written every row and
// its sequence update, but before Commit. No hooks are added to production code.
type crashConnector struct {
	base  driver.Driver
	dsn   string
	after func(string)
}

func (c crashConnector) Driver() driver.Driver { return c.base }
func (c crashConnector) Connect(ctx context.Context) (driver.Conn, error) {
	conn, err := c.base.Open(c.dsn)
	if err != nil {
		return nil, err
	}
	return &crashConn{Conn: conn, after: c.after}, nil
}

type crashConn struct {
	driver.Conn
	after func(string)
}

func (c *crashConn) BeginTx(ctx context.Context, opts driver.TxOptions) (driver.Tx, error) {
	return c.Conn.(driver.ConnBeginTx).BeginTx(ctx, opts)
}
func (c *crashConn) QueryContext(ctx context.Context, q string, args []driver.NamedValue) (driver.Rows, error) {
	return c.Conn.(driver.QueryerContext).QueryContext(ctx, q, args)
}
func (c *crashConn) ExecContext(ctx context.Context, q string, args []driver.NamedValue) (driver.Result, error) {
	result, err := c.Conn.(driver.ExecerContext).ExecContext(ctx, q, args)
	if err == nil {
		c.after(q)
	}
	return result, err
}

// TestSQLiteCrashWorker runs only in the subprocess launched below. The parent
// kills it without closing the Store or allowing Go/SQLite cleanup to run.
func TestSQLiteCrashWorker(t *testing.T) {
	if os.Getenv("VSTORE_CRASH_WORKER") != "1" {
		t.Skip("subprocess worker")
	}
	path := os.Getenv("VSTORE_CRASH_PATH")
	ctx := context.Background()
	store, err := Open(ctx, path, StoreOptions{})
	if err != nil {
		t.Fatal(err)
	}
	base := store.db.Driver()
	if err := store.db.Close(); err != nil {
		t.Fatal(err)
	}
	armed := false
	var baseline int64
	ready := func() {
		info, err := os.Stat(path + "-wal")
		if err != nil || info.Size() == 0 {
			t.Fatalf("missing WAL: %v", err)
		}
		if armed && info.Size() <= baseline {
			t.Fatalf("pending transaction did not spill WAL pages: %d <= %d", info.Size(), baseline)
		}
		fmt.Fprintln(os.Stdout, "ready")
		// The parent keeps stdin open until Process.Kill; no timing sleeps.
		_, _ = io.Copy(io.Discard, os.Stdin)
		t.Fatal("parent closed worker stdin instead of killing process")
	}
	dsn := sqliteFileURI(filepath.ToSlash(path)) + "?_txlock=immediate&_pragma=journal_mode(WAL)&_pragma=synchronous(FULL)&_pragma=foreign_keys(1)&_pragma=wal_autocheckpoint(0)"
	store.db = sql.OpenDB(crashConnector{base: base, dsn: dsn, after: func(q string) {
		if armed && strings.HasPrefix(q, "UPDATE __vectorstore_collections SET next_key=") {
			ready()
		}
	}})
	store.db.SetMaxOpenConns(1)
	c, err := store.EnsureModelCollection(ctx, "records", recoveryDefinition(), vectordata.ModelCollectionOptions{})
	if err != nil {
		t.Fatal(err)
	}
	if _, err := c.Insert(ctx, []vectordata.ModelRecord{{Data: map[string]any{"Body": "kept"}}}); err != nil {
		t.Fatal(err)
	}
	if os.Getenv("VSTORE_CRASH_PHASE") == "committed" {
		ready()
		return
	}
	info, err := os.Stat(path + "-wal")
	if err != nil {
		t.Fatal(err)
	}
	baseline = info.Size()
	armed = true
	rows := make([]vectordata.ModelRecord, 32)
	for i := range rows {
		rows[i] = vectordata.ModelRecord{Data: map[string]any{"Body": strings.Repeat("x", 256<<10)}}
	}
	_, err = c.Insert(ctx, rows)
	t.Fatalf("write passed crash hook: %v", err)
}

func TestWALRecoveryAfterProcessKill(t *testing.T) {
	for _, phase := range []string{"committed", "uncommitted"} {
		t.Run(phase, func(t *testing.T) {
			ctx, cancel := context.WithTimeout(context.Background(), 30*time.Second)
			defer cancel()
			path := filepath.Join(t.TempDir(), "recovery.db")
			command := exec.CommandContext(ctx, os.Args[0], "-test.run=^TestSQLiteCrashWorker$")
			command.Env = append(os.Environ(), "VSTORE_CRASH_WORKER=1", "VSTORE_CRASH_PATH="+path, "VSTORE_CRASH_PHASE="+phase)
			stdout, err := command.StdoutPipe()
			if err != nil {
				t.Fatal(err)
			}
			stdin, err := command.StdinPipe()
			if err != nil {
				t.Fatal(err)
			}
			defer stdin.Close()
			var stderr bytes.Buffer
			command.Stderr = &stderr
			if err := command.Start(); err != nil {
				t.Fatal(err)
			}
			waited := false
			defer func() {
				if !waited {
					_ = command.Process.Kill()
					_ = command.Wait()
				}
			}()
			ready := make(chan error, 1)
			go func() {
				line, err := bufio.NewReader(stdout).ReadString('\n')
				if err == nil && line != "ready\n" {
					err = fmt.Errorf("unexpected worker output %q", line)
				}
				ready <- err
			}()
			select {
			case err := <-ready:
				if err != nil {
					t.Fatalf("worker not ready: %v", err)
				}
			case <-ctx.Done():
				t.Fatal("worker readiness timed out")
			}
			if err := command.Process.Kill(); err != nil {
				t.Fatal(err)
			}
			err = command.Wait()
			waited = true
			var exit *exec.ExitError
			if !errors.As(err, &exit) {
				t.Fatalf("worker was not killed: %v %s", err, &stderr)
			}
			store, err := Open(ctx, path, StoreOptions{})
			if err != nil {
				t.Fatal(err)
			}
			defer store.Close()
			var integrity string
			if err := store.db.QueryRowContext(ctx, "PRAGMA quick_check").Scan(&integrity); err != nil || integrity != "ok" {
				t.Fatalf("integrity after kill: %s %v", integrity, err)
			}
			c, err := store.EnsureModelCollection(ctx, "records", recoveryDefinition(), vectordata.ModelCollectionOptions{})
			if err != nil {
				t.Fatal(err)
			}
			if count, err := c.Count(ctx, nil); err != nil || count != 1 {
				t.Fatalf("uncommitted batch survived: count=%d %v", count, err)
			}
			row, err := c.Get(ctx, int64(1), vectordata.RetrievalOptions{})
			if err != nil || row.Data["Body"] != "kept" {
				t.Fatalf("lost committed data: %+v %v", row, err)
			}
			keys, err := c.Insert(ctx, []vectordata.ModelRecord{{Data: map[string]any{"Body": "after recovery"}}})
			if err != nil || len(keys) != 1 || keys[0] != int64(2) {
				t.Fatalf("sequence/connection recovery: %v %v", keys, err)
			}
		})
	}
}
