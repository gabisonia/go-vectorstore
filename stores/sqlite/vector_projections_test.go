const projectedProperty = "Dense'\".雪"

func projectionDefinition() vectordata.CollectionDefinition {
	return vectordata.CollectionDefinition{Key: vectordata.KeyProperty{Name: "ID", Type: vectordata.KeyInt64, AutoGenerated: true},
		Data:    []vectordata.DataProperty{{Name: "Version", Type: vectordata.TypeString}},
		Vectors: []vectordata.VectorProperty{{Name: projectedProperty, StorageName: "unrelated_storage_name", Dimensions: 2, Metric: vectordata.DistanceL2, Optional: true}, {Name: "Half", Dimensions: 2, Precision: vectordata.VectorFloat16, Optional: true}}}
}

func projectionRow(key any, version string, x float32) vectordata.ModelRecord {
	return vectordata.ModelRecord{Key: key, Data: map[string]any{"Version": version}, Vectors: map[string][]float32{projectedProperty: {x, 0}, "Half": {1, 0.12345}}}
}

func projectionFixture(t *testing.T, path string, enabled bool) (*Store, *Collection) {
	t.Helper()
	s, err := Open(context.Background(), path, StoreOptions{VectorProjections: enabled})
	if err != nil {
		t.Fatal(err)
	}
	t.Cleanup(func() { s.Close() })
	base, err := s.EnsureModelCollection(context.Background(), "projected", projectionDefinition(), vectordata.ModelCollectionOptions{})
	if err != nil {
		t.Fatal(err)
	}
	return s, base.(*Collection)
}

func requireProjectionState(t *testing.T, s *Store, registryCount, ready, values int) {
	t.Helper()
	var count, actualReady, actualValues int
	if err := s.db.QueryRow(`SELECT count(*),coalesce(sum(ready),0) FROM __vectorstore_vector_projections`).Scan(&count, &actualReady); err != nil {
		t.Fatal(err)
	}
	if err := s.db.QueryRow(`SELECT count(*) FROM __vectorstore_vector_values`).Scan(&actualValues); err != nil {
		t.Fatal(err)
	}
	if count != registryCount || ready != actualReady || values != actualValues {
		t.Fatalf("projection state %d/%d/%d, want %d/%d/%d", count, actualReady, actualValues, registryCount, ready, values)
	}
}

func TestVectorProjectionsExplicitBackfillAndMixedWriters(t *testing.T) {
	ctx := context.Background()
	path := filepath.Join(t.TempDir(), "mixed.db")
	_, plain := projectionFixture(t, path, false)
	if _, err := plain.Insert(ctx, []vectordata.ModelRecord{projectionRow(nil, "before", 1)}); err != nil {
		t.Fatal(err)
	}
	s, projected := projectionFixture(t, path, true)
	requireProjectionState(t, s, 0, 0, 0)
	var payload, registration []byte
	if err := s.db.QueryRow(`SELECT r.payload,c.definition FROM __vectorstore_records r JOIN __vectorstore_collections c ON c.name=r.collection`).Scan(&payload, &registration); err != nil {
		t.Fatal(err)
	}
	// A write to an old collection must not implicitly backfill it.
	if _, err := projected.Upsert(ctx, []vectordata.ModelRecord{projectionRow(int64(1), "before", 1)}); err != nil {
		t.Fatal(err)
	}
	requireProjectionState(t, s, 0, 0, 0)
	if err := projected.RebuildVectorProjections(ctx); err != nil {
		t.Fatal(err)
	}
	requireProjectionState(t, s, 1, 1, 2)
	var afterPayload, afterRegistration []byte
	if err := s.db.QueryRow(`SELECT r.payload,c.definition FROM __vectorstore_records r JOIN __vectorstore_collections c ON c.name=r.collection`).Scan(&afterPayload, &afterRegistration); err != nil {
		t.Fatal(err)
	}
	if !bytes.Equal(payload, afterPayload) || !bytes.Equal(registration, afterRegistration) {
		t.Fatal("backfill changed canonical format")
	}
	if _, err := plain.Upsert(ctx, []vectordata.ModelRecord{projectionRow(int64(1), "legacy", 9)}); err != nil {
		t.Fatal(err)
	}
	requireProjectionState(t, s, 1, 0, 2)
	hits, err := projected.Search(ctx, []float32{9, 0}, 1, vectordata.ModelSearchOptions{VectorProperty: projectedProperty})
	if err != nil || len(hits) != 1 || hits[0].Distance != 0 || hits[0].Record.Data["Version"] != "legacy" {
		t.Fatalf("dirty fallback: %+v %v", hits, err)
	}
	// Updating just one row cannot repair an already dirty collection.
	if _, err := projected.Insert(ctx, []vectordata.ModelRecord{projectionRow(nil, "aware", 2)}); err != nil {
		t.Fatal(err)
	}
	requireProjectionState(t, s, 1, 0, 2)
	if err := projected.RebuildVectorProjections(ctx); err != nil {
		t.Fatal(err)
	}
	requireProjectionState(t, s, 1, 1, 4)
	if _, err := plain.Delete(ctx, []any{int64(1)}); err != nil {
		t.Fatal(err)
	}
	requireProjectionState(t, s, 1, 0, 2)
	if err := projected.RebuildVectorProjections(ctx); err != nil {
		t.Fatal(err)
	}
	if err := projected.EnsureDeleted(ctx); err != nil {
		t.Fatal(err)
	}
	requireProjectionState(t, s, 0, 0, 0)
}

func TestVectorProjectionAtomicWritesAndOptionalVectors(t *testing.T) {
	ctx := context.Background()
	s, c := projectionFixture(t, filepath.Join(t.TempDir(), "atomic.db"), true)
	requireProjectionState(t, s, 1, 1, 0)
	if _, err := c.Insert(ctx, []vectordata.ModelRecord{projectionRow(nil, "one", 1)}); err != nil {
		t.Fatal(err)
	}
	requireProjectionState(t, s, 1, 1, 2)
	if _, err := c.Insert(ctx, []vectordata.ModelRecord{projectionRow(nil, "rollback", 2), projectionRow(int64(1), "duplicate", 3)}); !errors.Is(err, vectordata.ErrInvalidRecord) {
		t.Fatalf("duplicate: %v", err)
	}
	requireProjectionState(t, s, 1, 1, 2)
	row := projectionRow(nil, "next", 2)
	row.Vectors = nil
	keys, err := c.Insert(ctx, []vectordata.ModelRecord{row})
	if err != nil || !reflect.DeepEqual(keys, []any{int64(2)}) {
		t.Fatalf("generated sequence: %v %v", keys, err)
	}
	requireProjectionState(t, s, 1, 1, 2)
	// Replacing a present vector with absence removes its projection.
	row.Key = int64(1)
	if _, err := c.Upsert(ctx, []vectordata.ModelRecord{row}); err != nil {
		t.Fatal(err)
	}
	requireProjectionState(t, s, 1, 1, 0)
	if _, err := c.Upsert(ctx, []vectordata.ModelRecord{projectionRow(int64(1), "restored", 4)}); err != nil {
		t.Fatal(err)
	}
	if _, err := c.Delete(ctx, []any{int64(1), int64(1), int64(999)}); err != nil {
		t.Fatal(err)
	}
	requireProjectionState(t, s, 1, 1, 0)
}

func TestVectorProjectionRebuildBatchesAndRollback(t *testing.T) {
	ctx := context.Background()
	s, c := projectionFixture(t, filepath.Join(t.TempDir(), "rebuild.db"), true)
	rows := make([]vectordata.ModelRecord, 260)
	for i := range rows {
		rows[i] = projectionRow(nil, "valid", float32(i))
	}
	if _, err := c.Insert(ctx, rows); err != nil {
		t.Fatal(err)
	}
	if err := c.RebuildVectorProjections(ctx); err != nil {
		t.Fatal(err)
	}
	requireProjectionState(t, s, 1, 1, 520)
	// Invalid record is beyond the first keyset batch: all staged changes roll back.
	if _, err := s.db.Exec(`UPDATE __vectorstore_records SET payload='invalid' WHERE key=?`, keyToken(int64(99))); err != nil {
		t.Fatal(err)
	}
	if err := c.RebuildVectorProjections(ctx); err == nil {
		t.Fatal("accepted corrupt canonical record")
	}
	requireProjectionState(t, s, 1, 0, 520)
	if _, err := c.Upsert(ctx, []vectordata.ModelRecord{projectionRow(int64(99), "repaired", 99)}); err != nil {
		t.Fatal(err)
	}
	if err := c.RebuildVectorProjections(ctx); err != nil {
		t.Fatal(err)
	}
	deadline, cancel := context.WithCancel(ctx)
	cancel()
	if err := c.RebuildVectorProjections(deadline); !errors.Is(err, context.Canceled) {
		t.Fatalf("cancellation: %v", err)
	}
	requireProjectionState(t, s, 1, 1, 520)
	if err := c.EnsureDeleted(ctx); err != nil {
		t.Fatal(err)
	}
	if err := c.RebuildVectorProjections(ctx); !errors.Is(err, vectordata.ErrCollectionNotFound) {
		t.Fatalf("missing collection: %v", err)
	}
	_, plain := projectionFixture(t, filepath.Join(t.TempDir(), "plain.db"), false)
	if err := plain.RebuildVectorProjections(ctx); !errors.Is(err, vectordata.ErrUnsupported) {
		t.Fatalf("default mode: %v", err)
	}
}

func TestVectorProjectionReadSnapshotAndPageFetch(t *testing.T) {
	ctx := context.Background()
	path := filepath.Join(t.TempDir(), "snapshot.db")
	s, c := projectionFixture(t, path, true)
	_, writer := projectionFixture(t, path, true)
	before, after := make([]vectordata.ModelRecord, 520), make([]vectordata.ModelRecord, 520)
	for i := range before {
		before[i] = projectionRow(int64(i), "before", 1)
		after[i] = projectionRow(int64(i), "after", 9)
	}
	if _, err := c.Insert(ctx, before); err != nil {
		t.Fatal(err)
	}
	wrote, scans, pageFetches := false, 0, 0
	var writeErr error
	connector := lookupConnector{base: s.db.Driver(), dsn: path + "?_txlock=immediate&_pragma=foreign_keys(1)", before: func(query string) {
		if strings.HasPrefix(query, "SELECT key,vector") {
			scans++
			if !wrote {
				wrote = true
				// The 520-row write is deliberately larger than a lookup chunk.
				// Allow race-instrumented projection writes to finish; an accidental
				// immediate reader still fails at the five-second lock-wait limit.
				deadline, cancel := context.WithTimeout(ctx, 15*time.Second)
				defer cancel()
				_, writeErr = writer.Upsert(deadline, after)
			}
		}
		if strings.HasPrefix(query, "SELECT payload FROM") {
			if !strings.Contains(query, "key IN (") {
				t.Error("projected search decoded all canonical payloads")
			}
			pageFetches++
		}
	}}
	if err := s.db.Close(); err != nil {
		t.Fatal(err)
	}
	s.db = sql.OpenDB(connector)
	s.db.SetMaxOpenConns(1)
	hits, err := c.Search(ctx, []float32{1, 0}, 510, vectordata.ModelSearchOptions{VectorProperty: projectedProperty, IncludeVectors: true, Skip: 1})
	if err != nil || len(hits) != 510 || !wrote || writeErr != nil || scans != 1 || pageFetches != 2 {
		t.Fatalf("snapshot/page read: hits=%d wrote=%v writeErr=%v scans=%d fetches=%d err=%v", len(hits), wrote, writeErr, scans, pageFetches, err)
	}
	for i, hit := range hits {
		if hit.Record.Key != int64(i+1) || hit.Record.Data["Version"] != "before" || hit.Distance != 0 || hit.Record.Vectors[projectedProperty][0] != 1 {
			t.Fatalf("mixed snapshot: %+v", hit)
		}
	}
	if _, err := c.Delete(ctx, []any{int64(0)}); err != nil {
		t.Fatalf("read leaked transaction: %v", err)
	}
}

func TestVectorProjectionNativeKeysAndPrecision(t *testing.T) {
	for _, tc := range []struct {
		kind vectordata.KeyType
		keys []any
	}{
		{vectordata.KeyString, []any{"a", "z"}},
		{vectordata.KeyInt64, []any{int64(-9007199254740993), int64(9007199254740993)}},
		{vectordata.KeyUint64, []any{uint64(9007199254740993), uint64(math.MaxUint64)}},
		{vectordata.KeyUUID, []any{"00000000-0000-4000-8000-000000000001", "00000000-0000-4000-8000-000000000002"}},
	} {
		t.Run(string(tc.kind), func(t *testing.T) {
			ctx := context.Background()
			s, _ := projectionFixture(t, filepath.Join(t.TempDir(), "keys.db"), true)
			d := projectionDefinition()
			d.Key.Type, d.Key.AutoGenerated = tc.kind, false
			base, err := s.EnsureModelCollection(ctx, "keys", d, vectordata.ModelCollectionOptions{})
			if err != nil {
				t.Fatal(err)
			}
			c := base.(*Collection)
			far, near := projectionRow(tc.keys[0], "far", 1), projectionRow(tc.keys[1], "near", 1)
			far.Vectors[projectedProperty][1] = 0.0001
			if _, err := c.Insert(ctx, []vectordata.ModelRecord{far, near}); err != nil {
				t.Fatal(err)
			}
			hits, err := c.Search(ctx, []float32{0, 0}, 1, vectordata.ModelSearchOptions{VectorProperty: projectedProperty})
			if err != nil || len(hits) != 1 || hits[0].Record.Key != tc.keys[1] || hits[0].Distance != 1 {
				t.Fatalf("precision boundary: %+v %v", hits, err)
			}
			far.Vectors[projectedProperty][1] = 0
			if _, err := c.Upsert(ctx, []vectordata.ModelRecord{far}); err != nil {
				t.Fatal(err)
			}
			hits, err = c.Search(ctx, []float32{0, 0}, 1, vectordata.ModelSearchOptions{VectorProperty: projectedProperty})
			if err != nil || len(hits) != 1 || hits[0].Record.Key != tc.keys[0] {
				t.Fatalf("native key tie: %+v %v", hits, err)
			}
		})
	}
}

func TestVectorProjectionDriftAndReadErrors(t *testing.T) {
	ctx := context.Background()
	s, c := projectionFixture(t, filepath.Join(t.TempDir(), "errors.db"), true)
	if _, err := c.Insert(ctx, []vectordata.ModelRecord{projectionRow(nil, "one", 1)}); err != nil {
		t.Fatal(err)
	}
	// Foreign registration is unusable; canonical fallback must still succeed.
	if _, err := s.db.Exec(`UPDATE __vectorstore_vector_projections SET definition='wrong'`); err != nil {
		t.Fatal(err)
	}
	if hits, err := c.Search(ctx, []float32{1, 0}, 1, vectordata.ModelSearchOptions{VectorProperty: projectedProperty}); err != nil || len(hits) != 1 {
		t.Fatalf("drift fallback: %+v %v", hits, err)
	}
	if err := c.RebuildVectorProjections(ctx); err != nil {
		t.Fatal(err)
	}
	// Truncated packed values fail without exposing a partial page or leaking SQL.
	if _, err := s.db.Exec(`UPDATE __vectorstore_vector_values SET vector=x'00' WHERE property=?`, projectedProperty); err != nil {
		t.Fatal(err)
	}
	if hits, err := c.Search(ctx, []float32{1, 0}, 1, vectordata.ModelSearchOptions{VectorProperty: projectedProperty}); hits != nil || !errors.Is(err, vectordata.ErrDimensionMismatch) {
		t.Fatalf("packed error: %+v %v", hits, err)
	}
	if err := c.RebuildVectorProjections(ctx); err != nil {
		t.Fatalf("leaked connection: %v", err)
	}
	// A filter always takes the canonical path in this first increment.
	if _, err := s.db.Exec(`UPDATE __vectorstore_vector_values SET vector=x'00'`); err != nil {
		t.Fatal(err)
	}
	if hits, err := c.Search(ctx, []float32{1, 0}, 1, vectordata.ModelSearchOptions{VectorProperty: projectedProperty, Filter: vectordata.Eq(vectordata.Column("Version"), "one")}); err != nil || len(hits) != 1 {
		t.Fatalf("filter fallback: %+v %v", hits, err)
	}
}

func TestVectorProjectionCancellationDiscardsStagedWork(t *testing.T) {
	for _, operation := range []string{"rebuild", "search"} {
		t.Run(operation, func(t *testing.T) {
			ctx, cancel := context.WithCancel(context.Background())
			defer cancel()
			path := filepath.Join(t.TempDir(), "cancel.db")
			s, c := projectionFixture(t, path, true)
			records := make([]vectordata.ModelRecord, 520)
			for i := range records {
				records[i] = projectionRow(nil, "kept", 1)
			}
			if _, err := c.Insert(context.Background(), records); err != nil {
				t.Fatal(err)
			}
			queries := 0
			connector := lookupConnector{base: s.db.Driver(), dsn: path + "?_txlock=immediate&_pragma=foreign_keys(1)", before: func(query string) {
				if operation == "rebuild" && strings.HasPrefix(query, "SELECT key,payload") || operation == "search" && strings.HasPrefix(query, "SELECT payload FROM") {
					queries++
					if queries == 2 {
						cancel()
					}
				}
			}}
			if err := s.db.Close(); err != nil {
				t.Fatal(err)
			}
			s.db = sql.OpenDB(connector)
			s.db.SetMaxOpenConns(1)
			if operation == "rebuild" {
				if err := c.RebuildVectorProjections(ctx); !errors.Is(err, context.Canceled) {
					t.Fatalf("rebuild cancellation: %v", err)
				}
			} else {
				if hits, err := c.Search(ctx, []float32{1, 0}, 510, vectordata.ModelSearchOptions{VectorProperty: projectedProperty}); hits != nil || !errors.Is(err, context.Canceled) {
					t.Fatalf("partial canceled page: hits=%d %v", len(hits), err)
				}
			}
			if queries != 2 {
				t.Fatalf("did not cancel after first batch: %d", queries)
			}
			requireProjectionState(t, s, 1, 1, 1040)
			if err := c.RebuildVectorProjections(context.Background()); err != nil {
				t.Fatalf("cancellation leaked transaction: %v", err)
			}
		})
	}
}

func TestVectorProjectionRebuildNeverEmbeds(t *testing.T) {
	ctx := context.Background()
	s, _ := projectionFixture(t, filepath.Join(t.TempDir(), "embedding.db"), true)
	d := projectionDefinition()
	d.Vectors[0].SourceProperty = "Version"
	calls := 0
	d.Vectors[0].Embedder = vectordata.EmbeddingFunc(func(context.Context, []string) ([][]float32, error) {
		calls++
		return nil, errors.New("stored records must never invoke an embedder")
	})
	base, err := s.EnsureModelCollection(ctx, "embedded", d, vectordata.ModelCollectionOptions{})
	if err != nil {
		t.Fatal(err)
	}
	c := base.(*Collection)
	if _, err := c.Insert(ctx, []vectordata.ModelRecord{projectionRow(int64(1), "source", 1)}); err != nil {
		t.Fatal(err)
	}
	if err := c.RebuildVectorProjections(ctx); err != nil {
		t.Fatal(err)
	}
	if hits, err := c.Search(ctx, []float32{1, 0}, 1, vectordata.ModelSearchOptions{VectorProperty: projectedProperty}); err != nil || len(hits) != 1 {
		t.Fatalf("projected stored read: %+v %v", hits, err)
	}
	if calls != 0 {
		t.Fatalf("called embedder %d times", calls)
	}
}
