// ModelCollection maps a CollectionDefinition to native PostgreSQL columns.
type ModelCollection struct {
	store      *PostgresVectorStore
	name       string
	definition vectordata.CollectionDefinition
	options    vectordata.ModelCollectionOptions
}

var _ vectordata.ModelCollection = (*ModelCollection)(nil)
var _ vectordata.HybridSearcher = (*ModelCollection)(nil)

func (c *ModelCollection) Name() string                                { return c.name }
func (c *ModelCollection) Definition() vectordata.CollectionDefinition { return c.definition.Clone() }
func (c *ModelCollection) table() string                               { return qualifiedTable(c.store.opts.Schema, c.name) }
func (c *ModelCollection) operation(op string, err error) error {
	if err == nil {
		return nil
	}
	var pgErr *pgconn.PgError
	if errors.As(err, &pgErr) && pgErr.Code == "42P01" {
		err = fmt.Errorf("%w: %w", vectordata.ErrCollectionNotFound, err)
	}
	return &vectordata.OperationError{Backend: "postgres", Collection: c.name, Operation: op, Err: err}
}
func (c *ModelCollection) Exists(ctx context.Context) (bool, error) {
	return c.store.CollectionExists(ctx, c.name)
}
func (c *ModelCollection) EnsureDeleted(ctx context.Context) error {
	return c.store.DeleteCollection(ctx, c.name)
}
func (c *ModelCollection) Insert(ctx context.Context, records []vectordata.ModelRecord) ([]any, error) {
	return c.write(ctx, records, false)
}
func (c *ModelCollection) Upsert(ctx context.Context, records []vectordata.ModelRecord) ([]any, error) {
	return c.write(ctx, records, true)
}
func (c *ModelCollection) write(ctx context.Context, records []vectordata.ModelRecord, upsert bool) ([]any, error) {
	dimensions := 0
	for _, p := range c.definition.Vectors {
		dimensions += min(p.Dimensions, minBinaryVectorValues-dimensions)
	}
	return c.writeEncoded(ctx, records, upsert, useBinaryVectors(len(records), dimensions))
}
func (c *ModelCollection) writeEncoded(ctx context.Context, records []vectordata.ModelRecord, upsert, useBinary bool) (keys []any, err error) {
	defer func() { err = c.operation("write", err) }()
	prepared, err := vectordata.PrepareModelRecords(ctx, c.definition, c.options, records)
	if err != nil {
		return nil, err
	}
	keys = []any{}
	if len(records) == 0 {
		return keys, nil
	}
	tx, release, err := beginVectorWrite(ctx, c.store.pool, useBinary)
	if err != nil {
		return nil, err
	}
	defer release()
	defer rollbackTx(ctx, tx)
	for start := 0; start < len(prepared); start += maxRowsPerStatement {
		end := min(start+maxRowsPerStatement, len(prepared))
		batch := &pgx.Batch{}
		for _, r := range prepared[start:end] {
			sql, args, err := c.writeStatement(r, upsert, useBinary)
			if err != nil {
				return nil, err
			}
			batch.Queue(sql, args...)
		}
		results := tx.SendBatch(ctx, batch)
		for range prepared[start:end] {
			var key any
			if err := results.QueryRow().Scan(&key); err != nil {
				_ = results.Close()
				return nil, err
			}
			keys = append(keys, key)
		}
		if err := results.Close(); err != nil {
			return nil, err
		}
	}
	if err := tx.Commit(ctx); err != nil {
		return nil, err
	}
	return keys, nil
}
func (c *ModelCollection) writeStatement(r vectordata.ModelRecord, upsert, useBinary bool) (string, []any, error) {
	d := c.definition
	columns := []string{quoteIdent(d.Key.StorageName)}
	values := []string{}
	args := []any{}
	bind := func(v any, cast string) string { args = append(args, v); return fmt.Sprintf("$%d%s", len(args), cast) }
	if r.Key == nil && d.Key.AutoGenerated {
		values = append(values, "DEFAULT")
	} else {
		values = append(values, bind(r.Key, ""))
	}
	updates := []string{}
	for _, p := range d.Data {
		column := quoteIdent(p.StorageName)
		columns = append(columns, column)
		updates = append(updates, column+"=EXCLUDED."+column)
		value := r.Data[p.Name]
		cast := ""
		if p.Type == vectordata.TypeJSON && !(p.Optional && value == nil) {
			payload, err := json.Marshal(value)
			if err != nil {
				return "", nil, err
			}
			value = payload
			cast = "::jsonb"
		}
		values = append(values, bind(value, cast))
	}
	for _, p := range d.Vectors {
		column := quoteIdent(p.StorageName)
		columns = append(columns, column)
		updates = append(updates, column+"=EXCLUDED."+column)
		values = append(values, bind(vectorWriteArg(r.Vectors[p.Name], useBinary), "::vector"))
	}
	query := "INSERT INTO " + c.table() + " (" + strings.Join(columns, ",") + ") VALUES (" + strings.Join(values, ",") + ")"
	if upsert && r.Key != nil {
		query += " ON CONFLICT (" + quoteIdent(d.Key.StorageName) + ") "
		if len(updates) == 0 {
			query += "DO UPDATE SET " + quoteIdent(d.Key.StorageName) + "=EXCLUDED." + quoteIdent(d.Key.StorageName)
		} else {
			query += "DO UPDATE SET " + strings.Join(updates, ",")
		}
	}
	query += " RETURNING " + quoteIdent(d.Key.StorageName)
	if d.Key.Type == vectordata.KeyUUID {
		query += "::text"
	}
	return query, args, nil
}
func (c *ModelCollection) columns(alias string, vectors bool) []string {
	qualify := func(column string) string {
		if alias != "" {
			return alias + "." + quoteIdent(column)
		}
		return quoteIdent(column)
	}
	key := qualify(c.definition.Key.StorageName)
	if c.definition.Key.Type == vectordata.KeyUUID {
		key += "::text"
	}
	columns := []string{key}
	for _, p := range c.definition.Data {
		column := qualify(p.StorageName)
		if p.Type == vectordata.TypeJSON {
			column += "::text"
		}
		columns = append(columns, column)
	}
	if vectors {
		for _, p := range c.definition.Vectors {
			columns = append(columns, qualify(p.StorageName)+"::text")
		}
	}
	return columns
}

type modelScanner interface{ Scan(...any) error }

func (c *ModelCollection) scan(row modelScanner, vectors, withDistance bool) (vectordata.ModelRecord, float64, error) {
	r := vectordata.ModelRecord{Data: map[string]any{}}
	targets := []any{&r.Key}
	data := make([]any, len(c.definition.Data))
	for i := range data {
		targets = append(targets, &data[i])
	}
	vectorTexts := make([]string, len(c.definition.Vectors))
	if vectors {
		for i := range vectorTexts {
			targets = append(targets, &vectorTexts[i])
		}
	}
	var distance float64
	if withDistance {
		targets = append(targets, &distance)
	}
	if err := row.Scan(targets...); err != nil {
		return r, 0, err
	}
	for i, p := range c.definition.Data {
		value := data[i]
		if value != nil && p.Type == vectordata.TypeJSON {
			decoder := json.NewDecoder(strings.NewReader(value.(string)))
			decoder.UseNumber()
			if err := decoder.Decode(&value); err != nil {
				return r, 0, err
			}
			if value == nil {
				value = vectordata.JSONNull{}
			}
		}
		if value != nil && p.Type == vectordata.TypeStringArray {
			if array, ok := value.([]any); ok {
				stringsValue := make([]string, len(array))
				for j, x := range array {
					text, ok := x.(string)
					if !ok {
						return r, 0, fmt.Errorf("%w: null/non-string element in %q", vectordata.ErrInvalidRecord, p.Name)
					}
					stringsValue[j] = text
				}
				value = stringsValue
			}
		}
		r.Data[p.Name] = value
	}
	if vectors {
		r.Vectors = map[string][]float32{}
		for i, p := range c.definition.Vectors {
			v, err := parseVectorText(vectorTexts[i])
			if err != nil {
				return r, 0, err
			}
			r.Vectors[p.Name] = v
		}
	}
	return r, distance, nil
}
func (c *ModelCollection) Get(ctx context.Context, key any, opts vectordata.RetrievalOptions) (r vectordata.ModelRecord, err error) {
	defer func() { err = c.operation("get", err) }()
	normalized, err := c.definition.NormalizeKey(key)
	if err != nil {
		return r, err
	}
	row := c.store.pool.QueryRow(ctx, "SELECT "+strings.Join(c.columns("", opts.IncludeVectors), ",")+" FROM "+c.table()+" WHERE "+quoteIdent(c.definition.Key.StorageName)+"=$1", normalized)
	r, _, err = c.scan(row, opts.IncludeVectors, false)
	if errors.Is(err, pgx.ErrNoRows) {
		err = vectordata.ErrNotFound
	}
	return r, err
}
func (c *ModelCollection) GetMany(ctx context.Context, keys []any, opts vectordata.RetrievalOptions) ([]vectordata.ModelRecord, error) {
	values := []any{}
	seen := map[any]bool{}
	for _, key := range keys {
		v, err := c.definition.NormalizeKey(key)
		if err != nil {
			return nil, c.operation("get_many", err)
		}
		if !seen[v] {
			seen[v] = true
			values = append(values, v)
		}
	}
	out := []vectordata.ModelRecord{}
	for start := 0; start < len(values); start += maxRowsPerStatement {
		chunk := values[start:min(start+maxRowsPerStatement, len(values))]
		records, err := c.Query(ctx, vectordata.In(vectordata.Column(c.definition.Key.Name), chunk...), len(chunk), vectordata.QueryOptions{IncludeVectors: opts.IncludeVectors})
		if err != nil {
			return nil, err
		}
		out = append(out, records...)
	}
	return out, ctx.Err()
}
func (c *ModelCollection) filterConfig() filtersql.FilterSQLConfig {
	cfg := filtersql.FilterSQLConfig{ColumnExpr: map[string]string{c.definition.Key.Name: "t." + quoteIdent(c.definition.Key.StorageName)}, JSONColumnExpr: map[string]string{}, ArrayColumns: map[string]bool{}, UseMetadataContainment: true}
	for _, p := range c.definition.Data {
		expr := "t." + quoteIdent(p.StorageName)
		cfg.ColumnExpr[p.Name] = expr
		if p.Type == vectordata.TypeJSON {
			cfg.JSONColumnExpr[p.Name] = expr
		}
		if p.Type == vectordata.TypeStringArray {
			cfg.ArrayColumns[p.Name] = true
		}
	}
	return cfg
}
func (c *ModelCollection) queryPlan(filter vectordata.Filter, top int, opts vectordata.QueryOptions) (string, []any, error) {
	if err := vectordata.ValidateModelQuery(c.definition, top, opts); err != nil {
		return "", nil, err
	}
	if err := vectordata.ValidateModelFilter(filter, c.definition); err != nil {
		return "", nil, err
	}
	where, args, next, err := filtersql.CompileFilterSQL(filter, c.filterConfig(), 1)
	if err != nil {
		return "", nil, err
	}
	sql := "SELECT " + strings.Join(c.columns("t", opts.IncludeVectors), ",") + " FROM " + c.table() + " t"
	if where != "" {
		sql += " WHERE " + where
	}
	order := []string{}
	cfg := c.filterConfig()
	for _, field := range opts.OrderBy {
		expr, ok := cfg.ColumnExpr[field.Property]
		if !ok {
			return "", nil, fmt.Errorf("%w: unknown sort property %q", vectordata.ErrInvalidFilter, field.Property)
		}
		direction := " ASC NULLS LAST"
		if field.Descending {
			direction = " DESC NULLS LAST"
		}
		order = append(order, expr+direction)
	}
	// A key tie-breaker makes paging deterministic for equal sort values.
	order = append(order, "t."+quoteIdent(c.definition.Key.StorageName)+" ASC")
	sql += " ORDER BY " + strings.Join(order, ",") + fmt.Sprintf(" LIMIT $%d OFFSET $%d", next, next+1)
	args = append(args, top, opts.Skip)
	return sql, args, nil
}
func (c *ModelCollection) QueryIter(ctx context.Context, filter vectordata.Filter, top int, opts vectordata.QueryOptions) iter.Seq2[vectordata.ModelRecord, error] {
	return func(yield func(vectordata.ModelRecord, error) bool) {
		sql, args, err := c.queryPlan(filter, top, opts)
		if err != nil {
			yield(vectordata.ModelRecord{}, c.operation("query", err))
			return
		}
		rows, err := c.store.pool.Query(ctx, sql, args...)
		if err != nil {
			yield(vectordata.ModelRecord{}, c.operation("query", err))
			return
		}
		defer rows.Close()
		for rows.Next() {
			r, _, err := c.scan(rows, opts.IncludeVectors, false)
			if err != nil {
				yield(vectordata.ModelRecord{}, c.operation("query", err))
				return
			}
			if !yield(r, nil) {
				return
			}
		}
		if err := rows.Err(); err != nil {
			yield(vectordata.ModelRecord{}, c.operation("query", err))
		}
	}
}
func (c *ModelCollection) Query(ctx context.Context, filter vectordata.Filter, top int, opts vectordata.QueryOptions) ([]vectordata.ModelRecord, error) {
	out := []vectordata.ModelRecord{}
	for r, err := range c.QueryIter(ctx, filter, top, opts) {
		if err != nil {
			return nil, err
		}
		out = append(out, r)
	}
	return out, nil
}
func (c *ModelCollection) Delete(ctx context.Context, keys []any) (count int64, err error) {
	defer func() { err = c.operation("delete", err) }()
	if len(keys) == 0 {
		return 0, ctx.Err()
	}
	tx, err := c.store.pool.Begin(ctx)
	if err != nil {
		return 0, err
	}
	defer rollbackTx(ctx, tx)
	for start := 0; start < len(keys); start += maxRowsPerStatement {
		args := []any{}
		parameters := []string{}
		for _, key := range keys[start:min(start+maxRowsPerStatement, len(keys))] {
			value, err := c.definition.NormalizeKey(key)
			if err != nil {
				return 0, err
			}
			args = append(args, value)
			parameters = append(parameters, fmt.Sprintf("$%d", len(args)))
		}
		cmd, err := tx.Exec(ctx, "DELETE FROM "+c.table()+" WHERE "+quoteIdent(c.definition.Key.StorageName)+" IN ("+strings.Join(parameters, ",")+")", args...)
		if err != nil {
			return 0, err
		}
		count += cmd.RowsAffected()
	}
	if err := tx.Commit(ctx); err != nil {
		return 0, err
	}
	return count, nil
}
func (c *ModelCollection) Count(ctx context.Context, filter vectordata.Filter) (count int64, err error) {
	defer func() { err = c.operation("count", err) }()
	if err := vectordata.ValidateModelFilter(filter, c.definition); err != nil {
		return 0, err
	}
	where, args, _, err := filtersql.CompileFilterSQL(filter, c.filterConfig(), 1)
	if err != nil {
		return 0, err
	}
	sql := "SELECT count(*) FROM " + c.table() + " t"
	if where != "" {
		sql += " WHERE " + where
	}
	err = c.store.pool.QueryRow(ctx, sql, args...).Scan(&count)
	return count, err
}
