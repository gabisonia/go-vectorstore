// copyBenchmarkModels compares COPY staging on the supplied-key benchmark fixture.
// It is deliberately not a production write path: it requires TEMP privilege and
// does not implement generated keys, duplicate-key sequencing or trigger key mapping.
func copyBenchmarkModels(ctx context.Context, c *ModelCollection, records []vectordata.ModelRecord, upsert bool) (keys []any, err error) {
	if c.definition.Key.Type != vectordata.KeyInt64 || c.definition.Key.AutoGenerated || len(c.definition.Data) != 3 || len(c.definition.Vectors) != 1 {
		return nil, vectordata.ErrUnsupported
	}
	prepared, err := vectordata.PrepareModelRecords(ctx, c.definition, c.options, records)
	if err != nil {
		return nil, err
	}
	for _, r := range prepared {
		if r.Key == nil {
			return nil, vectordata.ErrUnsupported
		}
	}
	tx, release, err := beginVectorWrite(ctx, c.store.pool, true)
	if err != nil {
		return nil, err
	}
	defer release()
	defer rollbackTx(ctx, tx)
	const stage = "__vs_bench_ingest"
	staged := qualifiedTable("pg_temp", stage)
	if _, err := tx.Exec(ctx, "CREATE TEMP TABLE "+quoteIdent(stage)+" (LIKE "+c.table()+") ON COMMIT DROP"); err != nil {
		return nil, err
	}
	columns := []string{c.definition.Key.StorageName}
	for _, p := range c.definition.Data {
		columns = append(columns, p.StorageName)
	}
	for _, p := range c.definition.Vectors {
		columns = append(columns, p.StorageName)
	}
	_, err = tx.CopyFrom(ctx, pgx.Identifier{"pg_temp", stage}, columns, pgx.CopyFromSlice(len(prepared), func(i int) ([]any, error) {
		r := prepared[i]
		row := []any{r.Key}
		for _, p := range c.definition.Data {
			row = append(row, r.Data[p.Name])
		}
		for _, p := range c.definition.Vectors {
			row = append(row, writeVector(r.Vectors[p.Name]))
		}
		return row, nil
	}))
	if err != nil {
		return nil, err
	}
	quoted := make([]string, len(columns))
	updates := make([]string, 0, len(columns)-1)
	for i, column := range columns {
		quoted[i] = quoteIdent(column)
		if i > 0 {
			updates = append(updates, quoted[i]+"=EXCLUDED."+quoted[i])
		}
	}
	key := quoteIdent(c.definition.Key.StorageName)
	sql := "INSERT INTO " + c.table() + " (" + strings.Join(quoted, ",") + ") SELECT " + strings.Join(quoted, ",") + " FROM " + staged
	if upsert {
		sql += " ON CONFLICT (" + key + ") DO UPDATE SET " + strings.Join(updates, ",")
	}
	sql += " RETURNING " + key
	rows, err := tx.Query(ctx, sql)
	if err != nil {
		return nil, err
	}
	for rows.Next() {
		var key any
		if err := rows.Scan(&key); err != nil {
			rows.Close()
			return nil, err
		}
		keys = append(keys, key)
	}
	rows.Close()
	if err := rows.Err(); err != nil {
		return nil, err
	}
	if err := tx.Commit(ctx); err != nil {
		return nil, err
	}
	return keys, nil
}

func BenchmarkModelWriteTransport(b *testing.B) {
	for _, dimensions := range []int{128, 1536} {
		for _, rows := range []int{100, 1000} {
			for _, upsert := range []bool{false, true} {
				mode := "insert"
				if upsert {
					mode = "upsert_existing"
				}
				b.Run(fmt.Sprintf("dim%d/rows%d/%s", dimensions, rows, mode), func(b *testing.B) {
					c, records := modelFixture(b, dimensions, rows, false)
					for _, transport := range []string{"text", "binary", "copy_stage"} {
						b.Run(transport, func(b *testing.B) {
							ctx := context.Background()
							b.ReportAllocs()
							b.ResetTimer()
							for range b.N {
								b.StopTimer()
								if _, err := c.store.pool.Exec(ctx, "TRUNCATE "+c.table()); err != nil {
									b.Fatal(err)
								}
								if upsert {
									if _, err := c.Insert(ctx, records); err != nil {
										b.Fatal(err)
									}
								}
								b.StartTimer()
								var keys []any
								var err error
								if transport == "copy_stage" {
									keys, err = copyBenchmarkModels(ctx, c, records, upsert)
								} else {
									keys, err = c.writeEncoded(ctx, records, upsert, transport == "binary")
								}
								if err != nil || len(keys) != rows {
									b.Fatalf("keys=%d: %v", len(keys), err)
								}
							}
							b.StopTimer()
							if count, err := c.Count(ctx, nil); err != nil || count != int64(rows) {
								b.Fatalf("count=%d: %v", count, err)
							}
						})
					}
				})
			}
		}
	}
}

func BenchmarkSmallModelWriteTransport(b *testing.B) {
	for _, dimensions := range []int{3, 128, 1536} {
		for _, rows := range []int{1, 8} {
			b.Run(fmt.Sprintf("dim%d/rows%d", dimensions, rows), func(b *testing.B) {
				c, records := modelFixture(b, dimensions, rows, false)
				for _, useBinary := range []bool{false, true} {
					b.Run(fmt.Sprintf("binary%t", useBinary), func(b *testing.B) {
						b.ReportAllocs()
						b.ResetTimer()
						for b.Loop() {
							if _, err := c.writeEncoded(context.Background(), records, true, useBinary); err != nil {
								b.Fatal(err)
							}
						}
					})
				}
			})
		}
	}
}

func BenchmarkRecordWriteTransport(b *testing.B) {
	for _, dimensions := range []int{128, 1536} {
		b.Run(fmt.Sprintf("dim%d/rows1000", dimensions), func(b *testing.B) {
			fixture, _ := modelFixture(b, dimensions, 0, false)
			ctx := context.Background()
			base, err := fixture.store.EnsureCollection(ctx, vectordata.CollectionSpec{Name: "legacy_transport", Dimension: dimensions})
			if err != nil {
				b.Fatal(err)
			}
			c := base.(*PostgresCollection)
			records := benchmarkRecords(1000, dimensions)
			for _, mode := range []writeMode{writeModeInsert, writeModeUpsert} {
				for _, binary := range []bool{false, true} {
					b.Run(fmt.Sprintf("upsert%t/binary%t", mode == writeModeUpsert, binary), func(b *testing.B) {
						b.ReportAllocs()
						b.ResetTimer()
						for range b.N {
							b.StopTimer()
							if _, err := c.store.pool.Exec(ctx, "TRUNCATE "+c.tableName()); err != nil {
								b.Fatal(err)
							}
							if mode == writeModeUpsert {
								if err := c.Insert(ctx, records); err != nil {
									b.Fatal(err)
								}
							}
							b.StartTimer()
							if err := c.writeRecordsEncoded(ctx, records, mode, binary); err != nil {
								b.Fatal(err)
							}
						}
						b.StopTimer()
						if count, err := c.Count(ctx, nil); err != nil || count != 1000 {
							b.Fatalf("count=%d, error=%v", count, err)
						}
					})
				}
			}
		})
	}
}
