package postgres

import (
	"fmt"

	"github.com/gabisonia/go-vectorstore/vectordata"
)

type migrationProperty struct {
	name, column, role, typ string
	optional, generated     bool
	vector                  *vectordata.VectorProperty
}

func migrationProperties(d vectordata.CollectionDefinition) []migrationProperty {
	properties := []migrationProperty{{name: d.Key.Name, column: d.Key.StorageName, role: "key", typ: keySQLType(d.Key.Type), generated: d.Key.AutoGenerated}}
	for _, p := range d.Data {
		properties = append(properties, migrationProperty{name: p.Name, column: p.StorageName, role: "data", typ: dataSQLType(p.Type), optional: p.Optional})
	}
	for i := range d.Vectors {
		p := d.Vectors[i]
		properties = append(properties, migrationProperty{name: p.Name, column: p.StorageName, role: "vector", optional: p.Optional, typ: vectorColumnType(p), vector: &p})
	}
	return properties
}
func sourceColumn(d vectordata.CollectionDefinition, source string) string {
	for _, p := range d.Data {
		if p.Name == source {
			return p.StorageName
		}
	}
	return ""
}
func (c *ModelCollection) propertyMigrationSteps(registered vectordata.CollectionDefinition) []vectordata.MigrationStep {
	before, after := migrationProperties(registered), migrationProperties(c.definition)
	used := map[int]bool{}
	matches := make([]int, len(after))
	for i := range matches {
		matches[i] = -1
	}
	for i, p := range after {
		if p.role == "key" {
			matches[i] = 0
			used[0] = true
			continue
		}
		for j, old := range before {
			if !used[j] && old.role != "key" && old.name == p.name {
				matches[i] = j
				used[j] = true
				break
			}
		}
	}
	// A logical-name change can match the same physical column. Changing both
	// names is deliberately treated as removal/addition, rather than guessing intent.
	for i, p := range after {
		if matches[i] >= 0 {
			continue
		}
		for j, old := range before {
			if !used[j] && old.role != "key" && old.column == p.column {
				matches[i] = j
				used[j] = true
				break
			}
		}
	}
	occupied := map[string]bool{}
	for _, p := range before {
		occupied[p.column] = true
	}
	var steps []vectordata.MigrationStep
	for j, p := range before {
		if !used[j] {
			steps = append(steps, vectordata.MigrationStep{Kind: vectordata.MigrationRemoveProperty, Property: p.name, StorageName: p.column, Description: "remove the stored property and its data (without CASCADE)", DataLoss: true, SQL: "ALTER TABLE " + c.table() + " DROP COLUMN " + quoteIdent(p.column)})
		}
	}
	for i, p := range after {
		if matches[i] < 0 {
			step := vectordata.MigrationStep{Kind: vectordata.MigrationAddProperty, Property: p.name, StorageName: p.column, Description: "add the property as a nullable column", SQL: "ALTER TABLE " + c.table() + " ADD COLUMN " + quoteIdent(p.column) + " " + p.typ}
			if occupied[p.column] {
				step.SQL = ""
				step.Manual = true
				step.Description = "resolve the occupied target column before adding the property"
			}
			steps = append(steps, step)
			if !p.optional {
				steps = append(steps, vectordata.MigrationStep{Kind: vectordata.MigrationBackfill, Property: p.name, StorageName: p.column, Description: "populate and verify every existing row before enforcing NOT NULL", Manual: true, RequiresBackfill: true, RequiresReembedding: p.role == "vector"})
				steps = append(steps, vectordata.MigrationStep{Kind: vectordata.MigrationAlterProperty, Property: p.name, StorageName: p.column, Description: "enforce the required property after backfill", SQL: "ALTER TABLE " + c.table() + " ALTER COLUMN " + quoteIdent(p.column) + " SET NOT NULL"})
			}
			continue
		}
		old := before[matches[i]]
		if old.name != p.name {
			steps = append(steps, vectordata.MigrationStep{Kind: vectordata.MigrationAlterProperty, Property: p.name, StorageName: p.column, Description: fmt.Sprintf("map logical property %q to %q without changing stored values", old.name, p.name)})
		}
		if old.column != p.column {
			step := vectordata.MigrationStep{Kind: vectordata.MigrationRenameProperty, Property: p.name, StorageName: p.column, Description: fmt.Sprintf("rename storage column %q to %q", old.column, p.column), SQL: "ALTER TABLE " + c.table() + " RENAME COLUMN " + quoteIdent(old.column) + " TO " + quoteIdent(p.column)}
			if occupied[p.column] {
				step.SQL = ""
				step.Manual = true
				step.Description += "; resolve the occupied target column or rename cycle explicitly"
			}
			steps = append(steps, step)
		}
		if old.role != p.role || old.typ != p.typ {
			steps = append(steps, vectordata.MigrationStep{Kind: vectordata.MigrationAlterProperty, Property: p.name, StorageName: p.column, Description: fmt.Sprintf("convert %s property %s to %s property %s using an application-defined conversion", old.role, old.typ, p.role, p.typ), Manual: true, DataLoss: true, RequiresBackfill: true, RequiresReembedding: p.role == "vector" || old.role == "vector"})
		} else if old.optional != p.optional {
			action := "DROP NOT NULL"
			description := "allow null values"
			if !p.optional {
				steps = append(steps, vectordata.MigrationStep{Kind: vectordata.MigrationBackfill, Property: p.name, StorageName: p.column, Description: "backfill or verify null values before enforcing NOT NULL", Manual: true, RequiresBackfill: true})
				action = "SET NOT NULL"
				description = "enforce NOT NULL after backfill/verification"
			}
			steps = append(steps, vectordata.MigrationStep{Kind: vectordata.MigrationAlterProperty, Property: p.name, StorageName: p.column, Description: description, SQL: "ALTER TABLE " + c.table() + " ALTER COLUMN " + quoteIdent(p.column) + " " + action})
		}
		if old.generated != p.generated {
			steps = append(steps, vectordata.MigrationStep{Kind: vectordata.MigrationAlterProperty, Property: p.name, StorageName: p.column, Description: "change identity generation only after reviewing sequence ownership, privileges and alignment with existing keys", Manual: true})
		}
		if old.vector != nil && p.vector != nil {
			if old.vector.Metric != p.vector.Metric {
				steps = append(steps, vectordata.MigrationStep{Kind: vectordata.MigrationAlterProperty, Property: p.name, StorageName: p.column, Description: "verify existing vectors and search semantics for the changed distance metric", Manual: true})
			}
			if old.vector.SourceProperty != p.vector.SourceProperty && sourceColumn(registered, old.vector.SourceProperty) != sourceColumn(c.definition, p.vector.SourceProperty) {
				steps = append(steps, vectordata.MigrationStep{Kind: vectordata.MigrationReembed, Property: p.name, StorageName: p.column, Description: "regenerate or verify stored embeddings for the changed embedding source", Manual: true, RequiresReembedding: true})
			}
		}
	}
	return steps
}
