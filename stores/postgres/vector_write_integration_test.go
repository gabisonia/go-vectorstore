type retainedWriteAlias string

func TestIntegrationBinaryWritesPreserveProtocolsAndPoolMappings(t *testing.T) {
	for _, mode := range []pgx.QueryExecMode{pgx.QueryExecModeCacheStatement, pgx.QueryExecModeCacheDescribe, pgx.QueryExecModeDescribeExec} {
		t.Run(mode.String(), func(t *testing.T) {
			ctx, cancel := context.WithTimeout(context.Background(), 30*time.Second)
			defer cancel()
			cfg, err := pgxpool.ParseConfig(integrationDSN)
			if err != nil {
				t.Fatal(err)
			}
			cfg.MaxConns = 1
			cfg.ConnConfig.DefaultQueryExecMode = mode
			pool, err := pgxpool.NewWithConfig(ctx, cfg)
			if err != nil {
				t.Fatal(err)
			}
			t.Cleanup(pool.Close)
			store := newTestStore(t, pool)
			d := vectordata.CollectionDefinition{Key: vectordata.KeyProperty{Name: "ID", Type: vectordata.KeyInt64, AutoGenerated: true}, Data: []vectordata.DataProperty{{Name: "Rank", Type: vectordata.TypeInt64}}, Vectors: []vectordata.VectorProperty{{Name: "Vector", Dimensions: 3, Metric: vectordata.DistanceL2}}}
			base, err := store.EnsureModelCollection(ctx, "encoded", d, vectordata.ModelCollectionOptions{})
			if err != nil {
				t.Fatal(err)
			}
			c := base.(*ModelCollection)
			if _, err := pool.Exec(ctx, "ALTER TABLE "+c.table()+" ADD CHECK (\"Rank\">=0)"); err != nil {
				t.Fatal(err)
			}
			conn, err := pool.Acquire(ctx)
			if err != nil {
				t.Fatal(err)
			}
			m := conn.Conn().TypeMap()
			var oid uint32
			if err := conn.QueryRow(ctx, "SELECT 'vector'::regtype::oid").Scan(&oid); err != nil {
				t.Fatal(err)
			}
			original := &pgtype.Type{Name: "vector", OID: oid, Codec: pgtype.TextCodec{}}
			m.RegisterType(original)
			m.RegisterDefaultPgType(retainedWriteAlias(""), "text")
			marker := func(any) (pgtype.WrappedEncodePlanNextSetter, any, bool) { return nil, nil, false }
			m.TryWrapEncodePlanFuncs = append([]pgtype.TryWrapEncodePlanFunc{marker}, m.TryWrapEncodePlanFuncs...)
			markerPointer := reflect.ValueOf(marker).Pointer()
			conn.Release()
			checkMappings := func() {
				t.Helper()
				conn, err := pool.Acquire(ctx)
				if err != nil {
					t.Fatal(err)
				}
				defer conn.Release()
				m := conn.Conn().TypeMap()
				if typ, _ := m.TypeForName("vector"); typ != original {
					t.Fatal("write codec escaped into the shared pool")
				}
				if typ, ok := m.TypeForValue(retainedWriteAlias("x")); !ok || typ.Name != "text" {
					t.Fatal("caller default mapping was lost")
				}
				if reflect.ValueOf(m.TryWrapEncodePlanFuncs[0]).Pointer() != markerPointer {
					t.Fatal("caller wrapper was lost")
				}
			}
			records := make([]vectordata.ModelRecord, 501)
			vector := []float32{1, -2.5, math.SmallestNonzeroFloat32}
			for i := range records {
				records[i] = vectordata.ModelRecord{Data: map[string]any{"Rank": int64(i)}, Vectors: map[string][]float32{"Vector": vector}}
			}
			keys, err := c.writeEncoded(ctx, records, false, true)
			if err != nil || len(keys) != len(records) {
				t.Fatalf("generated keys: %v, %v", keys, err)
			}
			for i, key := range keys {
				r, err := c.Get(ctx, key, vectordata.RetrievalOptions{IncludeVectors: true})
				if err != nil || r.Data["Rank"] != int64(i) || !reflect.DeepEqual(r.Vectors["Vector"], vector) {
					t.Fatalf("record %d: %+v, %v", i, r, err)
				}
			}
			checkMappings()
			// Repeated keys are sequential updates and return a key for each input.
			first := records[0]
			first.Key = keys[0]
			first.Data = map[string]any{"Rank": int64(42)}
			last := first
			last.Data = map[string]any{"Rank": int64(43)}
			updated, err := c.writeEncoded(ctx, []vectordata.ModelRecord{first, last}, true, true)
			if err != nil || !reflect.DeepEqual(updated, []any{keys[0], keys[0]}) {
				t.Fatalf("duplicate upsert: %v, %v", updated, err)
			}
			for i := range records {
				records[i].Key = keys[i]
				records[i].Data = map[string]any{"Rank": int64(1000 + i)}
			}
			records[len(records)-1].Data["Rank"] = int64(-1)
			if keys, err := c.writeEncoded(ctx, records, true, true); err == nil || keys != nil {
				t.Fatalf("constraint failure: keys=%v, error=%v", keys, err)
			} else {
				var pgErr *pgconn.PgError
				if !errors.As(err, &pgErr) || pgErr.Code != "23514" {
					t.Fatalf("constraint error lost: %v", err)
				}
			}
			if first, err := c.Get(ctx, keys[0], vectordata.RetrievalOptions{}); err != nil || first.Data["Rank"] != int64(43) {
				t.Fatalf("later failure did not roll back earlier batch: %+v, %v", first, err)
			}
			checkMappings()
			// The original Record API uses the same transport and must restore mappings too.
			legacyBase, err := store.EnsureCollection(ctx, vectordata.CollectionSpec{Name: "legacy_encoded", Dimension: 3})
			if err != nil {
				t.Fatal(err)
			}
			legacy := legacyBase.(*PostgresCollection)
			if err := legacy.writeRecordsEncoded(ctx, []vectordata.Record{{ID: "one", Vector: vector}}, writeModeInsert, true); err != nil {
				t.Fatal(err)
			}
			if r, err := legacy.Get(ctx, "one"); err != nil || !reflect.DeepEqual(r.Vector, vector) {
				t.Fatalf("legacy round trip: %+v, %v", r, err)
			}
			checkMappings()
			late := benchmarkRecords(501, 3)
			late[len(late)-1].ID = late[0].ID
			if err := legacy.Insert(ctx, late); err == nil {
				t.Fatal("expected late duplicate error")
			}
			if count, err := legacy.Count(ctx, nil); err != nil || count != 1 {
				t.Fatalf("legacy partial insert: count=%d, error=%v", count, err)
			}
			checkMappings()
			late = benchmarkRecords(501, 3)
			late[len(late)-1].Metadata = map[string]any{"bad": func() {}}
			if err := legacy.Upsert(ctx, late); !errors.Is(err, vectordata.ErrInvalidRecord) {
				t.Fatalf("late metadata validation: %v", err)
			}
			if count, err := legacy.Count(ctx, nil); err != nil || count != 1 {
				t.Fatalf("legacy partial upsert: count=%d, error=%v", count, err)
			}
			checkMappings()
		})
	}
}

// Vector parameters retain a text fallback when pgx is configured without
// statement descriptions. Test it independently of schema-registry JSON encoding.
func TestIntegrationVectorParametersTextProtocols(t *testing.T) {
	bootstrap := newTestStore(t, integrationPool(t))
	ctx := context.Background()
	if err := bootstrap.ensureBaseSchema(ctx); err != nil {
		t.Fatal(err)
	}
	for _, mode := range []pgx.QueryExecMode{pgx.QueryExecModeExec, pgx.QueryExecModeSimpleProtocol} {
		t.Run(mode.String(), func(t *testing.T) {
			cfg, err := pgxpool.ParseConfig(integrationDSN)
			if err != nil {
				t.Fatal(err)
			}
			cfg.ConnConfig.DefaultQueryExecMode = mode
			pool, err := pgxpool.NewWithConfig(ctx, cfg)
			if err != nil {
				t.Fatal(err)
			}
			t.Cleanup(pool.Close)
			tx, release, err := beginVectorWrite(ctx, pool, true)
			if err != nil {
				t.Fatal(err)
			}
			defer release()
			defer rollbackTx(ctx, tx)
			var text string
			if err := tx.QueryRow(ctx, "SELECT $1::vector::text", writeVector{1, -2.5, 0}).Scan(&text); err != nil || text != "[1,-2.5,0]" {
				t.Fatalf("text fallback: %q, %v", text, err)
			}
			if err := tx.Commit(ctx); err != nil {
				t.Fatal(err)
			}
		})
	}
}

func TestIntegrationBinaryModelsPreserveNativeDataAndCancellation(t *testing.T) {
	ctx, cancel := context.WithTimeout(context.Background(), 20*time.Second)
	defer cancel()
	pool := integrationPool(t)
	store := newTestStore(t, pool)
	d := vectordata.CollectionDefinition{
		Key:     vectordata.KeyProperty{Name: "ID", Type: vectordata.KeyUUID},
		Data:    []vectordata.DataProperty{{Name: "Details", Type: vectordata.TypeJSON, Optional: true}, {Name: "Created", Type: vectordata.TypeTime, Optional: true}, {Name: "Tags", Type: vectordata.TypeStringArray}},
		Vectors: []vectordata.VectorProperty{{Name: "Text", Dimensions: 512, Metric: vectordata.DistanceL2}, {Name: "Image", Dimensions: 512, Metric: vectordata.DistanceInnerProduct}},
	}
	base, err := store.EnsureModelCollection(ctx, "native_binary", d, vectordata.ModelCollectionOptions{})
	if err != nil {
		t.Fatal(err)
	}
	c := base.(*ModelCollection)
	keys := []string{"8f516db6-38ca-4e8f-ad79-d71b015f5419", "8f516db6-38ca-4e8f-ad79-d71b015f5420", "8f516db6-38ca-4e8f-ad79-d71b015f5421"}
	vector := make([]float32, 512)
	vector[0] = 1
	vector[1] = math.SmallestNonzeroFloat32
	vector[2] = math.Float32frombits(0x80000000)
	created := time.Date(2026, 1, 1, 0, 0, 0, 123456000, time.UTC)
	details := []any{map[string]any{"n": json.Number("9007199254740993")}, nil, vectordata.JSONNull{}}
	records := make([]vectordata.ModelRecord, len(keys))
	for i, key := range keys {
		records[i] = vectordata.ModelRecord{Key: key, Data: map[string]any{"Details": details[i], "Created": created, "Tags": []string{"news"}}, Vectors: map[string][]float32{"Text": vector, "Image": vector}}
	}
	inserted, err := c.Insert(ctx, records)
	if err != nil || len(inserted) != len(keys) {
		t.Fatalf("native keys: %v, %v", inserted, err)
	}
	for i, key := range keys {
		got, err := c.Get(ctx, key, vectordata.RetrievalOptions{IncludeVectors: true})
		if err != nil || got.Key != key || !got.Data["Created"].(time.Time).Equal(created) || !reflect.DeepEqual(got.Data["Tags"], []string{"news"}) || !reflect.DeepEqual(got.Data["Details"], details[i]) || !reflect.DeepEqual(got.Vectors["Text"], vector) || !reflect.DeepEqual(got.Vectors["Image"], vector) {
			t.Fatalf("native round trip %d: %+v, %v", i, got, err)
		}
	}
	// Hold a row lock so cancellation occurs after the binary write has started.
	blocker, err := pool.Begin(ctx)
	if err != nil {
		t.Fatal(err)
	}
	defer rollbackTx(ctx, blocker)
	if _, err := blocker.Exec(ctx, "SELECT 1 FROM "+c.table()+" WHERE \"ID\"=$1 FOR UPDATE", keys[0]); err != nil {
		t.Fatal(err)
	}
	pending, cancelWrite := context.WithTimeout(ctx, 100*time.Millisecond)
	defer cancelWrite()
	if _, err := c.Upsert(pending, records); !errors.Is(err, context.DeadlineExceeded) {
		t.Fatalf("write cancellation: %v", err)
	}
	if err := blocker.Rollback(ctx); err != nil {
		t.Fatal(err)
	}
	if count, err := c.Count(ctx, nil); err != nil || count != int64(len(keys)) {
		t.Fatalf("pool unusable after cancellation: %d, %v", count, err)
	}
	if _, err := c.Upsert(ctx, records); err != nil {
		t.Fatalf("write retry after cancellation: %v", err)
	}
}
