func additiveReview(t *testing.T, store *PostgresVectorStore, c *ModelCollection, d vectordata.CollectionDefinition) vectordata.MigrationPlan {
	t.Helper()
	d = d.Clone()
	d.Data = append(d.Data, vectordata.DataProperty{Name: "Added", Type: vectordata.TypeString, Optional: true, IsIndexed: true})
	plan, err := store.PlanMigration(context.Background(), c.name, d)
	if err != nil || plan.HasManualWork() {
		t.Fatalf("review: %+v, %v", plan, err)
	}
	return plan
}
func copyMigrationReview(t *testing.T, plan vectordata.MigrationPlan) vectordata.MigrationPlan {
	t.Helper()
	raw, err := json.Marshal(plan)
	if err != nil {
		t.Fatal(err)
	}
	var copy vectordata.MigrationPlan
	if err := json.Unmarshal(raw, &copy); err != nil {
		t.Fatal(err)
	}
	return copy
}
func assertOriginalMigrationStorage(t *testing.T, c *ModelCollection) {
	t.Helper()
	ctx := context.Background()
	if err := c.EnsureExists(ctx); err != nil {
		t.Fatalf("original storage/registration changed: %v", err)
	}
	if count, err := c.Count(ctx, nil); err != nil || count != 2 {
		t.Fatalf("original rows changed: count=%d, error=%v", count, err)
	}
}
func TestIntegrationApplyAdditiveMigration(t *testing.T) {
	store, c, d := migrationFixture(t)
	ctx := context.Background()
	d.Data[1].IsIndexed = true // Add an index on an existing optional property.
	d.Data = append(d.Data, vectordata.DataProperty{Name: "Added", StorageName: `added"; --`, Type: vectordata.TypeString, Optional: true, IsFullTextIndexed: true}, vectordata.DataProperty{Name: "Tags", Type: vectordata.TypeStringArray, Optional: true, IsIndexed: true}, vectordata.DataProperty{Name: "Details", Type: vectordata.TypeJSON, Optional: true})
	plan, err := store.PlanMigration(ctx, c.name, d)
	if err != nil || plan.HasManualWork() || plan.Revision == "" {
		t.Fatalf("review: %+v, %v", plan, err)
	}
	original := copyMigrationReview(t, plan)
	if err := store.ApplyMigration(ctx, plan); err != nil {
		t.Fatal(err)
	}
	if _, err := store.EnsureModelCollection(ctx, c.name, d, vectordata.ModelCollectionOptions{}); err != nil {
		t.Fatal(err)
	}
	updated, err := store.GetModelCollection(c.name, d, vectordata.ModelCollectionOptions{})
	if err != nil {
		t.Fatal(err)
	}
	row, err := updated.Get(ctx, "a", vectordata.RetrievalOptions{IncludeVectors: true})
	if err != nil || row.Data["Title"] != "first" || row.Data["Rank"] != int64(1) || row.Data["Added"] != nil || row.Data["Tags"] != nil || row.Data["Details"] != nil || len(row.Vectors["Vector"]) != 3 {
		t.Fatalf("existing row: %+v, %v", row, err)
	}
	left, _ := json.Marshal(plan)
	right, _ := json.Marshal(original)
	if string(left) != string(right) {
		t.Fatal("apply mutated the reviewed plan")
	}
	if err := store.ApplyMigration(ctx, original); !errors.Is(err, vectordata.ErrMigrationConflict) {
		t.Fatalf("stale retry: %v", err)
	}
	noop, err := store.PlanMigration(ctx, c.name, d)
	if err != nil || len(noop.Steps) != 0 || noop.Finalization != nil {
		t.Fatalf("final plan: %+v, %v", noop, err)
	}
	if err := store.ApplyMigration(ctx, noop); err != nil {
		t.Fatalf("current no-op apply: %v", err)
	}
}
func TestIntegrationApplyVectorIndexAddition(t *testing.T) {
	ctx := context.Background()
	store := newTestStore(t, integrationPool(t))
	d := vectordata.CollectionDefinition{Key: vectordata.KeyProperty{Name: "ID", Type: vectordata.KeyInt64, AutoGenerated: true}, Vectors: []vectordata.VectorProperty{{Name: "Vector", Dimensions: 3}}}
	c, err := store.EnsureModelCollection(ctx, "index_addition", d, vectordata.ModelCollectionOptions{})
	if err != nil {
		t.Fatal(err)
	}
	keys, err := c.Insert(ctx, []vectordata.ModelRecord{{Vectors: map[string][]float32{"Vector": {1, 0, 0}}}})
	if err != nil {
		t.Fatal(err)
	}
	d.Vectors[0].Index = &vectordata.VectorIndexOptions{Method: vectordata.IndexMethodHNSW}
	plan, err := store.PlanMigration(ctx, c.Name(), d)
	if err != nil {
		t.Fatal(err)
	}
	if err := store.ApplyMigration(ctx, plan); err != nil {
		t.Fatal(err)
	}
	next, err := store.EnsureModelCollection(ctx, c.Name(), d, vectordata.ModelCollectionOptions{})
	if err != nil {
		t.Fatal(err)
	}
	more, err := next.Insert(ctx, []vectordata.ModelRecord{{Vectors: map[string][]float32{"Vector": {0, 1, 0}}}})
	if err != nil || len(more) != 1 || more[0] == keys[0] {
		t.Fatalf("identity after index migration: %v, %v", more, err)
	}
}
func TestIntegrationApplyRejectsNonAdditivePlans(t *testing.T) {
	store, c, d := migrationFixture(t)
	ctx := context.Background()
	for _, tt := range []struct {
		name   string
		change func(*vectordata.CollectionDefinition)
	}{
		{"required property", func(d *vectordata.CollectionDefinition) {
			d.Data = append(d.Data, vectordata.DataProperty{Name: "Required", Type: vectordata.TypeString})
		}},
		{"new vector", func(d *vectordata.CollectionDefinition) {
			d.Vectors = append(d.Vectors, vectordata.VectorProperty{Name: "Other", Dimensions: 3})
		}},
		{"remove data", func(d *vectordata.CollectionDefinition) { d.Data = d.Data[:1] }},
		{"storage rename", func(d *vectordata.CollectionDefinition) { d.Data[1].StorageName = "renamed" }},
		{"logical rename", func(d *vectordata.CollectionDefinition) { d.Data[1].Name = "Renamed" }},
		{"nullability relaxation", func(d *vectordata.CollectionDefinition) { d.Data[0].Optional = true }},
		{"nullability tightening", func(d *vectordata.CollectionDefinition) { d.Data[1].Optional = false }},
		{"native type", func(d *vectordata.CollectionDefinition) { d.Data[1].Type = vectordata.TypeString }},
		{"key change", func(d *vectordata.CollectionDefinition) { d.Key.StorageName = "new_key" }},
		{"drop index", func(d *vectordata.CollectionDefinition) { d.Data[0].IsIndexed = false }},
		{"rebuild index", func(d *vectordata.CollectionDefinition) {
			d.Vectors[0].Index.HNSW.M = 20
			d.Vectors[0].Index.HNSW.EfConstruction = 80
		}},
		{"vector dimensions", func(d *vectordata.CollectionDefinition) { d.Vectors[0].Dimensions = 4 }},
		{"embedding source", func(d *vectordata.CollectionDefinition) { d.Vectors[0].SourceProperty = "" }},
	} {
		t.Run(tt.name, func(t *testing.T) {
			desired := d.Clone()
			tt.change(&desired)
			plan, err := store.PlanMigration(ctx, c.name, desired)
			if err != nil {
				t.Fatal(err)
			}
			if err := store.ApplyMigration(ctx, plan); !errors.Is(err, vectordata.ErrMigrationNotAdditive) {
				t.Fatalf("non-additive error: %v", err)
			}
			assertOriginalMigrationStorage(t, c)
		})
	}
}
func TestIntegrationApplyRejectsEditedAndStaleReviews(t *testing.T) {
	store, c, d := migrationFixture(t)
	ctx := context.Background()
	plan := additiveReview(t, store, c, d)
	for _, tt := range []struct {
		name string
		edit func(*vectordata.MigrationPlan)
	}{
		{"SQL", func(p *vectordata.MigrationPlan) { p.Steps[0].SQL = "DROP TABLE " + c.table() }},
		{"risk flag", func(p *vectordata.MigrationPlan) { p.Steps[0].DataLoss = true }},
		{"revision", func(p *vectordata.MigrationPlan) { p.Revision = "edited" }},
		{"namespace", func(p *vectordata.MigrationPlan) { p.Namespace = "elsewhere" }},
		{"desired model", func(p *vectordata.MigrationPlan) {
			p.Desired.Data = append(p.Desired.Data, vectordata.DataProperty{Name: "Unreviewed", Type: vectordata.TypeString, Optional: true})
		}},
		{"finalization arguments", func(p *vectordata.MigrationPlan) { p.Finalization.Args[0] = "elsewhere" }},
	} {
		t.Run(tt.name, func(t *testing.T) {
			edited := copyMigrationReview(t, plan)
			tt.edit(&edited)
			if err := store.ApplyMigration(ctx, edited); !errors.Is(err, vectordata.ErrMigrationConflict) {
				t.Fatalf("edited review error: %v", err)
			}
			assertOriginalMigrationStorage(t, c)
		})
	}
	t.Run("schema drift", func(t *testing.T) {
		if _, err := store.pool.Exec(ctx, "ALTER TABLE "+c.table()+" ALTER COLUMN \"Rank\" SET DEFAULT 1"); err != nil {
			t.Fatal(err)
		}
		if err := store.ApplyMigration(ctx, plan); !errors.Is(err, vectordata.ErrMigrationConflict) || !errors.Is(err, vectordata.ErrSchemaMismatch) {
			t.Fatalf("drift error: %v", err)
		}
		if _, err := store.pool.Exec(ctx, "ALTER TABLE "+c.table()+" ALTER COLUMN \"Rank\" DROP DEFAULT"); err != nil {
			t.Fatal(err)
		}
	})
	t.Run("replaced table identity", func(t *testing.T) {
		if _, err := store.pool.Exec(ctx, "DROP TABLE "+c.table()); err != nil {
			t.Fatal(err)
		}
		if err := c.EnsureExists(ctx); err != nil {
			t.Fatal(err)
		}
		fresh, err := store.PlanMigration(ctx, c.name, plan.Desired)
		if err != nil || fresh.Revision == plan.Revision {
			t.Fatalf("replaced storage revision: %+v, %v", fresh, err)
		}
		if err := store.ApplyMigration(ctx, plan); !errors.Is(err, vectordata.ErrMigrationConflict) {
			t.Fatalf("replaced table error: %v", err)
		}
	})
}
func TestIntegrationApplyRollsBackDDLOnFinalizationFailure(t *testing.T) {
	for _, scenario := range []string{"raise", "skip", "rewrite"} {
		t.Run(scenario, func(t *testing.T) {
			store, c, d := migrationFixture(t)
			ctx := context.Background()
			plan := additiveReview(t, store, c, d)
			body := "RAISE EXCEPTION 'finalization blocked' USING ERRCODE='P0001';"
			if scenario == "skip" {
				body = "RETURN NULL;"
			}
			if scenario == "rewrite" {
				body = `NEW.definition=jsonb_set(NEW.definition,'{Key,Name}','"Spoofed"'); RETURN NEW;`
			}
			function := qualifiedTable(store.opts.Schema, "finalization_hook")
			registry := qualifiedTable(store.opts.Schema, modelRegistry)
			if _, err := store.pool.Exec(ctx, "CREATE FUNCTION "+function+"() RETURNS trigger LANGUAGE plpgsql AS $hook$ BEGIN "+body+" END $hook$; CREATE TRIGGER finalization_hook BEFORE UPDATE ON "+registry+" FOR EACH ROW EXECUTE FUNCTION "+function+"()"); err != nil {
				t.Fatal(err)
			}
			err := store.ApplyMigration(ctx, plan)
			if scenario == "raise" {
				var pgErr *pgconn.PgError
				if !errors.As(err, &pgErr) || pgErr.Code != "P0001" {
					t.Fatalf("database error lost: %v", err)
				}
			} else if !errors.Is(err, vectordata.ErrMigrationConflict) {
				t.Fatalf("finalization guard: %v", err)
			}
			assertOriginalMigrationStorage(t, c)
			var added bool
			if err := store.pool.QueryRow(ctx, "SELECT EXISTS (SELECT 1 FROM pg_attribute WHERE attrelid=to_regclass($1) AND attname='Added' AND NOT attisdropped)", c.table()).Scan(&added); err != nil || added {
				t.Fatalf("partial DDL survived: %v, %v", added, err)
			}
			if _, err := store.pool.Exec(ctx, "DROP TRIGGER finalization_hook ON "+registry); err != nil {
				t.Fatal(err)
			}
			if err := store.ApplyMigration(ctx, plan); err != nil {
				t.Fatalf("retry after rollback: %v", err)
			}
		})
	}
}
func TestIntegrationApplySerializesConcurrentReviews(t *testing.T) {
	store, c, d := migrationFixture(t)
	ctx, cancel := context.WithTimeout(context.Background(), 20*time.Second)
	defer cancel()
	plan := additiveReview(t, store, c, d)
	var wg sync.WaitGroup
	start := make(chan struct{})
	results := make(chan error, 2)
	for range 2 {
		wg.Add(1)
		go func() { defer wg.Done(); <-start; results <- store.ApplyMigration(ctx, plan) }()
	}
	close(start)
	wg.Wait()
	close(results)
	successes, conflicts := 0, 0
	for err := range results {
		if err == nil {
			successes++
		} else if errors.Is(err, vectordata.ErrMigrationConflict) {
			conflicts++
		} else {
			t.Fatal(err)
		}
	}
	if successes != 1 || conflicts != 1 {
		t.Fatalf("successes=%d, conflicts=%d", successes, conflicts)
	}
	if _, err := store.EnsureModelCollection(ctx, c.name, plan.Desired, vectordata.ModelCollectionOptions{}); err != nil {
		t.Fatal(err)
	}
}
func TestIntegrationApplyCancellationAndSingleConnection(t *testing.T) {
	bootstrap, c, d := migrationFixture(t)
	ctx, cancel := context.WithTimeout(context.Background(), 20*time.Second)
	defer cancel()
	cfg, err := pgxpool.ParseConfig(integrationDSN)
	if err != nil {
		t.Fatal(err)
	}
	cfg.MaxConns = 1
	pool, err := pgxpool.NewWithConfig(ctx, cfg)
	if err != nil {
		t.Fatal(err)
	}
	t.Cleanup(pool.Close)
	store, err := NewVectorStore(pool, bootstrap.opts)
	if err != nil {
		t.Fatal(err)
	}
	plan := additiveReview(t, store, c, d)
	blocker, err := bootstrap.pool.Begin(ctx)
	if err != nil {
		t.Fatal(err)
	}
	defer rollbackTx(ctx, blocker)
	if _, err := blocker.Exec(ctx, "SELECT pg_advisory_xact_lock(hashtextextended($1,0))", c.table()); err != nil {
		t.Fatal(err)
	}
	waiting, cancelWait := context.WithTimeout(ctx, 100*time.Millisecond)
	err = store.ApplyMigration(waiting, plan)
	cancelWait()
	if !errors.Is(err, context.DeadlineExceeded) {
		t.Fatalf("lock cancellation: %v", err)
	}
	if err := blocker.Rollback(ctx); err != nil {
		t.Fatal(err)
	}
	assertOriginalMigrationStorage(t, c)
	if err := pool.Ping(ctx); err != nil {
		t.Fatalf("lease leaked: %v", err)
	}
	if err := store.ApplyMigration(ctx, plan); err != nil {
		t.Fatalf("single-connection retry: %v", err)
	}
}
