//go:build integration

package postgres

import (
	"errors"
	"fmt"
	"io"
	"slices"
	"testing"
	"time"

	"github.com/gabisonia/go-vectorstore/vectordata"
	"github.com/jackc/pgx/v5/pgxpool"
	tcexec "github.com/testcontainers/testcontainers-go/exec"
)

// Keep both databases and the archive inside the container owned by TestMain.
func TestIntegrationLogicalBackupRestore(t *testing.T) {
	if integrationContainer == nil {
		t.Skip("logical restore drill requires an owned container")
	}
	ctx := t.Context()
	id := schemaSeq.Add(1)
	source := fmt.Sprintf("backup_source_%d", id)
	target := fmt.Sprintf("backup_target_%d", id)
	archive := "/tmp/" + source + ".dump"
	run := func(args ...string) {
		t.Helper()
		code, r, err := integrationContainer.Exec(ctx, args, tcexec.Multiplexed())
		if err != nil {
			t.Fatal(err)
		}
		output, err := io.ReadAll(r)
		if code != 0 || err != nil {
			t.Fatalf("%v: exit %d: %s (%v)", args, code, output, err)
		}
	}
	open := func(db string) (*PostgresVectorStore, *pgxpool.Pool) {
		t.Helper()
		cfg, err := pgxpool.ParseConfig(integrationDSN)
		if err != nil {
			t.Fatal(err)
		}
		cfg.ConnConfig.Database = db
		pool, err := pgxpool.NewWithConfig(ctx, cfg)
		if err != nil {
			t.Fatal(err)
		}
		t.Cleanup(pool.Close)
		store, err := NewVectorStore(pool, StoreOptions{Schema: "recovery", EnsureExtension: db == source, StrictByDefault: true})
		if err != nil {
			t.Fatal(err)
		}
		return store, pool
	}
	run("createdb", "-U", integrationPostgresUser, source)
	store, _ := open(source)
	def := vectordata.CollectionDefinition{Key: vectordata.KeyProperty{Name: "ID", Type: vectordata.KeyInt64, AutoGenerated: true}, Data: []vectordata.DataProperty{{Name: "Value", Type: vectordata.TypeInt64}}, Vectors: []vectordata.VectorProperty{{Name: "V", Dimensions: 2, Metric: vectordata.DistanceL2}}}
	opts := vectordata.ModelCollectionOptions{}
	c, err := store.EnsureModelCollection(ctx, "items", def, opts)
	if err != nil {
		t.Fatal(err)
	}

	// The oracle is independent of reads from either database.
	const precise = int64(9007199254740993)
	insert := func(c vectordata.ModelCollection, value int64, x float32) int64 {
		t.Helper()
		row := vectordata.ModelRecord{Data: map[string]any{"Value": value}, Vectors: map[string][]float32{"V": {x, 0}}}
		keys, err := c.Insert(ctx, []vectordata.ModelRecord{row})
		if err != nil || len(keys) != 1 {
			t.Fatalf("insert: keys=%v err=%v", keys, err)
		}
		key, ok := keys[0].(int64)
		if !ok {
			t.Fatalf("unexpected key %v", keys[0])
		}
		return key
	}
	kept := insert(c, precise, 3)
	excluded := insert(c, precise-1, 0)
	deleted := insert(c, precise, 0)
	if count, err := c.Delete(ctx, []any{deleted}); err != nil || count != 1 {
		t.Fatalf("delete: count=%d err=%v", count, err)
	}
	run("pg_dump", "-U", integrationPostgresUser, "-Fc", "-f", archive, source)
	later := insert(c, precise, 1)

	start := time.Now()
	run("createdb", "-U", integrationPostgresUser, "-T", "template0", target)
	run("pg_restore", "-U", integrationPostgresUser, "--exit-on-error", "--single-transaction", "-d", target, archive)
	restored, pool := open(target)
	names, err := restored.ListCollectionNames(ctx)
	if err != nil || !slices.Equal(names, []string{"items"}) {
		t.Fatalf("restored registrations: %v %v", names, err)
	}
	incompatible := def
	incompatible.Vectors = []vectordata.VectorProperty{{Name: "V", Dimensions: 3, Metric: vectordata.DistanceL2}}
	if _, err := restored.EnsureModelCollection(ctx, "items", incompatible, opts); !errors.Is(err, vectordata.ErrSchemaMismatch) {
		t.Fatalf("incompatible registration: %v", err)
	}
	handle, err := restored.EnsureModelCollection(ctx, "items", def, opts)
	if err != nil {
		t.Fatal(err)
	}
	check := func(key, value int64, x float32) {
		t.Helper()
		got, err := handle.Get(ctx, key, vectordata.RetrievalOptions{IncludeVectors: true})
		if err != nil || got.Key != key || got.Data["Value"] != value || !slices.Equal(got.Vectors["V"], []float32{x, 0}) {
			t.Fatalf("restored key %d: %+v %v", key, got, err)
		}
	}
	check(kept, precise, 3)
	check(excluded, precise-1, 0)
	for _, key := range []int64{deleted, later} {
		if _, err := handle.Get(ctx, key, vectordata.RetrievalOptions{}); !errors.Is(err, vectordata.ErrNotFound) {
			t.Fatalf("unexpected read of key %d: %v", key, err)
		}
	}
	if count, err := handle.Count(ctx, nil); err != nil || count != 2 {
		t.Fatalf("restored count %d: %v", count, err)
	}
	hits, err := handle.Search(ctx, []float32{0, 0}, 3, vectordata.ModelSearchOptions{Filter: vectordata.Eq(vectordata.Column("Value"), precise)})
	if err != nil || len(hits) != 1 || hits[0].Record.Key != kept || hits[0].Distance != 3 {
		t.Fatalf("filtered L2 results: %+v %v", hits, err)
	}
	next := insert(handle, precise+1, 2)
	if next <= max(kept, excluded, deleted) {
		t.Fatalf("restored sequence allocated %d after %v", next, []int64{kept, excluded, deleted})
	}
	check(next, precise+1, 2)
	elapsed := time.Since(start)
	var pg, extension string
	if err := pool.QueryRow(ctx, "SELECT current_setting('server_version'), extversion FROM pg_extension WHERE extname='vector'").Scan(&pg, &extension); err != nil {
		t.Fatal(err)
	}
	t.Logf("PostgreSQL %s pgvector %s: create target through verified fresh write %s; cutoff keys %v, later source key %d, new target key %d", pg, extension, elapsed, []int64{kept, excluded, deleted}, later, next)
}
