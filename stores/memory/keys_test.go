func TestGeneratedSequenceRollsBackAndExhausts(t *testing.T) {
	ctx := context.Background()
	s := New()
	c, err := s.EnsureModelCollection(ctx, "keys", vectordata.CollectionDefinition{Key: vectordata.KeyProperty{Name: "ID", Type: vectordata.KeyInt64, AutoGenerated: true}}, vectordata.ModelCollectionOptions{})
	if err != nil {
		t.Fatal(err)
	}
	s.collections["keys"].next = math.MaxInt64
	if _, err := c.Insert(ctx, []vectordata.ModelRecord{{}, {}}); !errors.Is(err, vectordata.ErrInvalidRecord) {
		t.Fatalf("exhausted batch: %v", err)
	}
	if count, err := c.Count(ctx, nil); err != nil || count != 0 || s.collections["keys"].next != math.MaxInt64 {
		t.Fatalf("partial record/sequence update: %d, %v", count, err)
	}
	keys, err := c.Insert(ctx, []vectordata.ModelRecord{{}})
	if err != nil || len(keys) != 1 || keys[0] != int64(math.MaxInt64) {
		t.Fatalf("last valid key: %v, %v", keys, err)
	}
	if _, err := c.Insert(ctx, []vectordata.ModelRecord{{}}); !errors.Is(err, vectordata.ErrInvalidRecord) {
		t.Fatalf("sequence wrapped: %v", err)
	}
}

func TestStagedUpsertRollsBackOnGeneratedKeyCollision(t *testing.T) {
	ctx := t.Context()
	s := New()
	d := vectordata.CollectionDefinition{Key: vectordata.KeyProperty{Name: "ID", Type: vectordata.KeyInt64, AutoGenerated: true}, Data: []vectordata.DataProperty{{Name: "Value", Type: vectordata.TypeString}}}
	c, err := s.EnsureModelCollection(ctx, "keys", d, vectordata.ModelCollectionOptions{})
	if err != nil {
		t.Fatal(err)
	}
	row := func(key any, value string) vectordata.ModelRecord {
		return vectordata.ModelRecord{Key: key, Data: map[string]any{"Value": value}}
	}
	if _, err = c.Insert(ctx, []vectordata.ModelRecord{row(int64(2), "original")}); err != nil {
		t.Fatal(err)
	}
	_, err = c.Upsert(ctx, []vectordata.ModelRecord{row(int64(2), "changed"), row(nil, "first"), row(nil, "collision")})
	if !errors.Is(err, vectordata.ErrInvalidRecord) {
		t.Fatal(err)
	}
	got, err := c.Get(ctx, int64(2), vectordata.RetrievalOptions{})
	if err != nil || got.Data["Value"] != "original" {
		t.Fatalf("stored=%v err=%v", got, err)
	}
	keys, err := c.Insert(ctx, []vectordata.ModelRecord{row(nil, "next")})
	if err != nil || len(keys) != 1 || keys[0] != int64(1) {
		t.Fatalf("keys=%v err=%v", keys, err)
	}
}

func BenchmarkMemorySingleUpsert(b *testing.B) {
	for _, size := range []int{100, 10000} {
		b.Run(fmt.Sprint(size), func(b *testing.B) {
			c := memoryReadsFixture(b, size)
			batch := []vectordata.ModelRecord{{Key: int64(1), Data: map[string]any{"Body": "updated"}, Vectors: map[string][]float32{"Vector": {1, 0}}}}
			b.ReportAllocs()
			for b.Loop() {
				if _, err := c.Upsert(b.Context(), batch); err != nil {
					b.Fatal(err)
				}
			}
		})
	}
}
