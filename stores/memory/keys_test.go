package memory

import (
	"context"
	"errors"
	"math"
	"testing"

	"github.com/gabisonia/go-vectorstore/vectordata"
)

func TestGeneratedSequenceRollsBackAndExhausts(t *testing.T) {
	ctx := context.Background()
	s := New()
	c, err := s.EnsureModelCollection(ctx, "keys", vectordata.CollectionDefinition{Key: vectordata.KeyProperty{Name: "ID", Type: vectordata.KeyInt64, AutoGenerated: true}}, vectordata.ModelCollectionOptions{})
	if err != nil {
		t.Fatal(err)
	}
	s.collections["keys"].next = math.MaxInt64
	if _, err := c.Insert(ctx, []vectordata.ModelRecord{{}, {}}); !errors.Is(err, vectordata.ErrInvalidRecord) {
		t.Fatalf("exhausted batch: %v", err)
	}
	if count, err := c.Count(ctx, nil); err != nil || count != 0 || s.collections["keys"].next != math.MaxInt64 {
		t.Fatalf("partial record/sequence update: %d, %v", count, err)
	}
	keys, err := c.Insert(ctx, []vectordata.ModelRecord{{}})
	if err != nil || len(keys) != 1 || keys[0] != int64(math.MaxInt64) {
		t.Fatalf("last valid key: %v, %v", keys, err)
	}
	if _, err := c.Insert(ctx, []vectordata.ModelRecord{{}}); !errors.Is(err, vectordata.ErrInvalidRecord) {
		t.Fatalf("sequence wrapped: %v", err)
	}
}
