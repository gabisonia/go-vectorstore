func TestIntegrationCorruptionReturnsNoPartialPageOrPublication(t *testing.T) {
	s := integrationStore(t, StoreOptions{})
	c := generated(t, s)
	if _, err := c.Insert(t.Context(), append(body("first"), body("second")...)); err != nil {
		t.Fatal(err)
	}
	base, err := s.readRoot(t.Context(), c.name)
	if err != nil {
		t.Fatal(err)
	}
	broken := cloneSnapshot(base)
	broken.Records[token(int64(2))] = json.RawMessage(`{"Key":2,"Data":{}}`)
	// Inject malformed application data through the low-level test boundary.
	// The public writer must not republish it with an otherwise valid mutation.
	if err := s.transition(t.Context(), c.name, base, broken); err != nil {
		t.Fatal(err)
	}
	broken, err = s.readRoot(t.Context(), c.name)
	if err != nil {
		t.Fatal(err)
	}
	if rows, err := c.Query(t.Context(), nil, 2, vectordata.QueryOptions{}); rows != nil || !errors.Is(err, vectordata.ErrInvalidRecord) {
		t.Fatalf("partial page escaped: %v %v", rows, err)
	}
	if keys, err := c.Upsert(t.Context(), []vectordata.ModelRecord{{Key: int64(1), Data: map[string]any{"Body": "valid mutation"}}}); keys != nil || !errors.Is(err, vectordata.ErrInvalidRecord) {
		t.Fatalf("republished corrupt snapshot: %v %v", keys, err)
	}
	after, err := s.readRoot(t.Context(), c.name)
	if err != nil || after.Revision != broken.Revision {
		t.Fatalf("failed mutation advanced revision: %+v %v", after, err)
	}
	if _, err := c.Upsert(t.Context(), []vectordata.ModelRecord{{Key: int64(2), Data: map[string]any{"Body": "explicit repair"}}}); err != nil {
		t.Fatal(err)
	}
}

func TestIntegrationSnapshotDoesNotMixConcurrentPublications(t *testing.T) {
	s := integrationStore(t, StoreOptions{})
	c := generated(t, s)
	rows := func(text string) []vectordata.ModelRecord {
		return []vectordata.ModelRecord{{Key: int64(1), Data: map[string]any{"Body": text}}, {Key: int64(2), Data: map[string]any{"Body": text}}}
	}
	if _, err := c.Upsert(t.Context(), rows("old")); err != nil {
		t.Fatal(err)
	}
	transport := s.http.Transport
	var once sync.Once
	s.http.Transport = roundTripper(func(r *http.Request) (*http.Response, error) {
		response, err := transport.RoundTrip(r)
		if err == nil && r.Method == "POST" && strings.HasSuffix(r.URL.Path, "/points") {
			once.Do(func() {
				other, err := New(StoreOptions{URL: integrationURL, APIKey: s.apiKey, Namespace: s.namespace})
				if err != nil {
					t.Error(err)
					return
				}
				defer other.Close()
				h, err := other.GetModelCollection(c.name, c.definition, vectordata.ModelCollectionOptions{})
				if err != nil {
					t.Error(err)
					return
				}
				if _, err := h.Upsert(t.Context(), rows("new")); err != nil {
					t.Error(err)
				}
			})
		}
		return response, err
	})
	page, err := c.Query(t.Context(), nil, 2, vectordata.QueryOptions{})
	s.http.Transport = transport
	if err != nil || len(page) != 2 || page[0].Data["Body"] != "old" || page[1].Data["Body"] != "old" {
		t.Fatalf("mixed/redirected snapshot: %v %v", page, err)
	}
	page, err = c.Query(t.Context(), nil, 2, vectordata.QueryOptions{})
	if err != nil || len(page) != 2 || !slices.Equal([]any{page[0].Data["Body"], page[1].Data["Body"]}, []any{"new", "new"}) {
		t.Fatalf("missed new snapshot: %v %v", page, err)
	}
}
