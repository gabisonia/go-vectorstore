func TestIntegrationConflictsDoNotRepeatEmbedding(t *testing.T) {
	s := integrationStore(t, StoreOptions{})
	d := vectordata.CollectionDefinition{Key: vectordata.KeyProperty{Name: "ID"}, Data: []vectordata.DataProperty{{Name: "Body", Type: vectordata.TypeString}}, Vectors: []vectordata.VectorProperty{{Name: "V", Dimensions: 2, SourceProperty: "Body"}}}
	var calls atomic.Int32
	c, err := s.EnsureModelCollection(t.Context(), "embedded", d, vectordata.ModelCollectionOptions{Embedder: vectordata.EmbeddingFunc(func(context.Context, []string) ([][]float32, error) {
		calls.Add(1)
		return [][]float32{{1, 0}}, nil
	})})
	if err != nil {
		t.Fatal(err)
	}
	transport := s.http.Transport
	t.Cleanup(func() { s.http.Transport = transport })
	var raced atomic.Bool
	s.http.Transport = roundTripper(func(r *http.Request) (*http.Response, error) {
		if r.Method == "PUT" && strings.HasSuffix(r.URL.Path, "/points") && raced.CompareAndSwap(false, true) {
			other, err := New(StoreOptions{URL: integrationURL, APIKey: s.apiKey, Namespace: s.namespace})
			if err != nil {
				return nil, err
			}
			defer other.Close()
			h, err := other.GetModelCollection("embedded", d, vectordata.ModelCollectionOptions{})
			if err != nil {
				return nil, err
			}
			if _, err := h.Insert(t.Context(), []vectordata.ModelRecord{{Key: "other", Data: map[string]any{"Body": "racing"}, Vectors: map[string][]float32{"V": {0, 1}}}}); err != nil {
				return nil, err
			}
		}
		return transport.RoundTrip(r)
	})
	_, err = c.Insert(t.Context(), []vectordata.ModelRecord{{Key: "embedded", Data: map[string]any{"Body": "prepared once"}}})
	s.http.Transport = transport
	if err != nil || !raced.Load() || calls.Load() != 1 {
		t.Fatalf("embedding repeated across CAS conflict: %d %v", calls.Load(), err)
	}
	if n, err := c.Count(t.Context(), nil); err != nil || n != 2 {
		t.Fatalf("lost racing update: %d %v", n, err)
	}
}

