func TestMain(m *testing.M) {
	integrationURL = os.Getenv("QDRANT_TEST_URL")
	if integrationURL == "" {
		ctx, cancel := context.WithTimeout(context.Background(), 2*time.Minute)
		defer cancel()
		var err error
		ownedContainer, err = testcontainers.GenericContainer(ctx, testcontainers.GenericContainerRequest{ContainerRequest: testcontainers.ContainerRequest{
			Image: "qdrant/qdrant:v1.20.2", ExposedPorts: []string{"6333/tcp"}, Env: map[string]string{"QDRANT__TELEMETRY_DISABLED": "true"},
			WaitingFor: wait.ForHTTP("/readyz").WithPort("6333/tcp").WithStartupTimeout(time.Minute),
		}, Started: true})
		if err != nil {
			fmt.Fprintln(os.Stderr, err)
			os.Exit(1)
		}
		host, err := ownedContainer.Host(ctx)
		if err != nil {
			_ = ownedContainer.Terminate(ctx)
			fmt.Fprintln(os.Stderr, err)
			os.Exit(1)
		}
		port, err := ownedContainer.MappedPort(ctx, "6333/tcp")
		if err != nil {
			_ = ownedContainer.Terminate(ctx)
			fmt.Fprintln(os.Stderr, err)
			os.Exit(1)
		}
		integrationURL = "http://" + net.JoinHostPort(host, port.Port())
	}
	code := m.Run()
	if ownedContainer != nil {
		ctx, cancel := context.WithTimeout(context.Background(), 30*time.Second)
		defer cancel()
		if err := ownedContainer.Terminate(ctx); err != nil {
			fmt.Fprintln(os.Stderr, err)
			code = 1
		}
	}
	os.Exit(code)
}

func integrationStore(t *testing.T, opts StoreOptions) *Store {
	t.Helper()
	opts.URL = integrationURL
	if ownedContainer == nil {
		opts.APIKey = os.Getenv("QDRANT_TEST_API_KEY")
	}
	if opts.Namespace == "" {
		id, err := vectordata.NewUUIDKey()
		if err != nil {
			t.Fatal(err)
		}
		opts.Namespace = "integration:" + id
	}
	s, err := New(opts)
	if err != nil {
		t.Fatal(err)
	}
	t.Cleanup(func() {
		defer s.Close()
		// All clients have finished. Administrative cleanup removes only physical
		// collections whose exact ownership matches this unique test namespace.
		ctx, cancel := context.WithTimeout(context.Background(), 20*time.Second)
		defer cancel()
		var out response[struct{ Collections []struct{ Name string } }]
		if _, err := s.request(ctx, "GET", "/collections", nil, &out); err != nil {
			t.Error(err)
			return
		}
		for _, row := range out.Result.Collections {
			if !strings.HasPrefix(row.Name, "go_vectorstore_v1_") {
				continue
			}
			var info collectionInfo
			if _, err := s.request(ctx, "GET", "/collections/"+row.Name, nil, &info); err != nil {
				t.Error(err)
				continue
			}
			var owner physicalOwner
			if json.Unmarshal(info.Result.Config.Metadata["go_vectorstore"], &owner) == nil && owner.Namespace == s.namespace && s.physical(owner.Name) == row.Name {
				if _, err := s.request(ctx, "DELETE", "/collections/"+row.Name, nil, nil); err != nil {
					t.Error(err)
				}
			}
		}
	})
	return s
}

