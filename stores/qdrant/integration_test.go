func body(value string) []vectordata.ModelRecord {
	return []vectordata.ModelRecord{{Data: map[string]any{"Body": value}}}
}

func TestIntegrationConcurrentClientsAndReopen(t *testing.T) {
	s := integrationStore(t, StoreOptions{})
	c := generated(t, s)
	other, err := New(StoreOptions{URL: integrationURL, APIKey: s.apiKey, Namespace: s.namespace})
	if err != nil {
		t.Fatal(err)
	}
	defer other.Close()
	second, err := other.GetModelCollection(c.name, c.definition, vectordata.ModelCollectionOptions{})
	if err != nil {
		t.Fatal(err)
	}
	var wg sync.WaitGroup
	keys := make(chan any, 16)
	for i := range 16 {
		wg.Add(1)
		go func() {
			defer wg.Done()
			target := vectordata.ModelCollection(c)
			if i%2 == 0 {
				target = second
			}
			out, err := target.Insert(t.Context(), body("concurrent"))
			if err != nil {
				t.Error(err)
				return
			}
			keys <- out[0]
		}()
	}
	wg.Wait()
	close(keys)
	seen := map[any]bool{}
	for key := range keys {
		if seen[key] {
			t.Fatal("duplicate generated key")
		}
		seen[key] = true
	}
	if len(seen) != 16 {
		t.Fatalf("lost writes: %d", len(seen))
	}
	if n, err := second.Count(t.Context(), nil); err != nil || n != 16 {
		t.Fatalf("reopen: %d %v", n, err)
	}
	out, err := second.Insert(t.Context(), body("reopened"))
	if err != nil || out[0] != int64(17) {
		t.Fatalf("sequence: %v %v", out, err)
	}
}

type roundTripper func(*http.Request) (*http.Response, error)

func (f roundTripper) RoundTrip(r *http.Request) (*http.Response, error) { return f(r) }

func TestIntegrationUnknownWriteAndReadOnlyReconciliation(t *testing.T) {
	s := integrationStore(t, StoreOptions{})
	c := generated(t, s)
	transport := s.http.Transport
	t.Cleanup(func() { s.http.Transport = transport })
	var wrote atomic.Bool
	var attempts atomic.Int32
	lost := errors.New("lost acknowledgement and readback")
	s.http.Transport = roundTripper(func(r *http.Request) (*http.Response, error) {
		if r.Method == "PUT" && strings.HasSuffix(r.URL.Path, "/points") {
			attempts.Add(1)
			response, err := transport.RoundTrip(r)
			if err != nil {
				return nil, err
			}
			response.Body.Close()
			wrote.Store(true)
			return nil, lost
		}
		if wrote.Load() {
			return nil, lost
		}
		return transport.RoundTrip(r)
	})
	keys, err := c.Insert(t.Context(), body("uncertain"))
	var outcome *OutcomeUnknownError
	if keys != nil || !errors.Is(err, ErrOutcomeUnknown) || !errors.Is(err, lost) || !errors.As(err, &outcome) || attempts.Load() != 1 {
		t.Fatalf("replay or missing diagnostics: %v %v %d", keys, err, attempts.Load())
	}
	s.http.Transport = transport
	if err := s.ConfirmWrite(t.Context(), c.name, outcome.Token); err != nil {
		t.Fatal(err)
	}
	if keys, err := c.Insert(t.Context(), body("later")); err != nil || keys[0] != int64(2) {
		t.Fatalf("sequence: %v %v", keys, err)
	}
	if err := s.ConfirmWrite(t.Context(), c.name, outcome.Token); err != nil {
		t.Fatal("superseded receipt lost:", err)
	}
}

func TestIntegrationInFlightRequestIsNeverSettledByAbsentReceipt(t *testing.T) {
	for _, superseded := range []bool{false, true} {
		t.Run(fmt.Sprint("superseded=", superseded), func(t *testing.T) {
			s := integrationStore(t, StoreOptions{})
			c := generated(t, s)
			transport := s.http.Transport
			t.Cleanup(func() { s.http.Transport = transport })
			var original *http.Request
			var writes int
			s.http.Transport = roundTripper(func(r *http.Request) (*http.Response, error) {
				if r.Method == "PUT" && strings.HasSuffix(r.URL.Path, "/points") {
					writes++
					raw, err := io.ReadAll(r.Body)
					r.Body.Close()
					if err != nil {
						return nil, err
					}
					original = r.Clone(context.Background())
					original.Body = io.NopCloser(bytes.NewReader(raw))
					return nil, context.DeadlineExceeded
				}
				return transport.RoundTrip(r)
			})
			keys, err := c.Insert(t.Context(), body("original"))
			s.http.Transport = transport
			var outcome *OutcomeUnknownError
			if keys != nil || writes != 1 || !errors.Is(err, context.DeadlineExceeded) || !errors.As(err, &outcome) || original == nil {
				t.Fatalf("request was replayed or misclassified: %v %v", keys, err)
			}
			if err := s.ConfirmWrite(t.Context(), c.name, outcome.Token); !errors.Is(err, ErrOutcomeUnknown) {
				t.Fatalf("absence settled in-flight write: %v", err)
			}
			if superseded {
				if _, err := c.Insert(t.Context(), body("winner")); err != nil {
					t.Fatal(err)
				}
			}
			// Deliver the original guarded request once, after the caller already
			// received unknown. This is not a new logical write or a replay.
			ctx, cancel := context.WithTimeout(t.Context(), 20*time.Second)
			defer cancel()
			original = original.Clone(ctx)
			r, err := transport.RoundTrip(original)
			if err != nil {
				t.Fatal(err)
			}
			io.Copy(io.Discard, r.Body)
			r.Body.Close()
			if r.StatusCode != 200 {
				t.Fatalf("late request: HTTP %d", r.StatusCode)
			}
			confirmed := s.ConfirmWrite(t.Context(), c.name, outcome.Token)
			if superseded && !errors.Is(confirmed, ErrOutcomeUnknown) || !superseded && confirmed != nil {
				t.Fatalf("late completion: %v", confirmed)
			}
			row, err := c.Get(t.Context(), int64(1), vectordata.RetrievalOptions{})
			want := "original"
			if superseded {
				want = "winner"
			}
			if err != nil || row.Data["Body"] != want {
				t.Fatalf("late write overwrote winner: %v %v", row, err)
			}
		})
	}
}

func TestIntegrationRejectsForeignOwnershipTopologyAndLimits(t *testing.T) {
	for _, test := range []string{"foreign", "topology", "limits"} {
		t.Run(test, func(t *testing.T) {
			s := integrationStore(t, StoreOptions{})
			owner := physicalOwner{Format: 1, Namespace: s.namespace, Name: "records", Limits: s.limits}
			shards := 1
			if test == "foreign" {
				owner.Format = 99
			}
			if test == "topology" {
				shards = 2
			}
			if test == "limits" {
				owner.Limits.MaxReceipts++
			}
			_, err := s.request(t.Context(), "PUT", s.path(owner.Name), map[string]any{"vectors": map[string]any{}, "shard_number": shards, "replication_factor": 1, "sharding_method": "auto", "metadata": map[string]any{"go_vectorstore": owner}}, nil)
			if err != nil {
				t.Fatal(err)
			}
			d := vectordata.CollectionDefinition{Key: vectordata.KeyProperty{Name: "ID"}}
			_, err = s.EnsureModelCollection(t.Context(), "records", d, vectordata.ModelCollectionOptions{})
			want := vectordata.ErrSchemaMismatch
			if test == "topology" {
				want = vectordata.ErrUnsupported
			}
			if !errors.Is(err, want) {
				t.Fatalf("adopted incompatible collection: %v", err)
			}
			if _, err := s.readPoint(t.Context(), "records"); !errors.Is(err, errRootAbsent) {
				t.Fatalf("wrote a root before ownership validation: %v", err)
			}
		})
	}
}

func TestIntegrationLimitsAndAtomicValidation(t *testing.T) {
	s := integrationStore(t, StoreOptions{Limits: Limits{MaxRecords: 2, MaxCollectionBytes: 1024, MaxReceipts: 5}})
	c := generated(t, s)
	before, _ := s.readRoot(t.Context(), c.name)
	if _, err := c.Insert(t.Context(), body(strings.Repeat("x", 2048))); !errors.Is(err, ErrLimit) {
		t.Fatal(err)
	}
	after, _ := s.readRoot(t.Context(), c.name)
	if before.Revision != after.Revision {
		t.Fatal("invalid write consumed a receipt")
	}
	if _, err := c.Insert(t.Context(), body("kept")); err != nil {
		t.Fatal(err)
	}
	if _, err := c.Insert(t.Context(), append(body("two"), body("three")...)); !errors.Is(err, ErrLimit) {
		t.Fatal(err)
	}
	keys, err := c.Insert(t.Context(), body("second"))
	if err != nil || keys[0] != int64(2) {
		t.Fatalf("failed batch consumed sequence: %v %v", keys, err)
	}
	if _, err := c.Delete(t.Context(), []any{int64(2)}); err != nil {
		t.Fatal(err)
	}
	if _, err := c.Insert(t.Context(), body("exhausted")); !errors.Is(err, ErrLimit) {
		t.Fatal(err)
	}
	if n, err := c.Count(t.Context(), nil); err != nil || n != 1 {
		t.Fatalf("limit truncated data: %d %v", n, err)
	}
	usage, err := s.Usage(t.Context(), c.name)
	if err != nil || !usage.Active || usage.Records != 1 || usage.CanonicalBytes < 1 || usage.RetainedReceipts != 5 || usage.Limits != s.limits {
		t.Fatalf("capacity diagnostics: %+v %v", usage, err)
	}
	for _, token := range before.Receipts {
		if err := s.ConfirmWrite(t.Context(), c.name, token); err != nil {
			t.Fatal(err)
		}
	}
}

