// These tests may kill only TestMain's owned fixture. Supplied Redis addresses
// are rejected before TestMain starts when recovery mode is requested.
func requireRecovery(t *testing.T) {
	t.Helper()
	if os.Getenv("REDIS_TEST_RECOVERY") != "true" {
		t.Skip("set REDIS_TEST_RECOVERY=true for owned-server persistence tests")
	}
	if ownedRedisContainer == nil {
		t.Fatal("recovery requires an owned container")
	}
}

func redisRecoveryWait() wait.Strategy {
	// Redis can bind its port before restoring the dataset/modules. A real PONG
	// is required before any recovery assertions; never retry failed model reads.
	return wait.ForAll(wait.ForListeningPort("6379/tcp"),
		wait.ForExec([]string{"redis-cli", "-e", "ping"}).WithResponseMatcher(func(body io.Reader) bool {
			data, err := io.ReadAll(body)
			return err == nil && strings.TrimSpace(string(data)) == "PONG"
		})).WithDeadline(time.Minute)
}

func logRecoveryRedis(t *testing.T, container testcontainers.Container) {
	t.Helper()
	if !t.Failed() {
		return
	}
	ctx, cancel := context.WithTimeout(context.Background(), 5*time.Second)
	defer cancel()
	state, err := container.State(ctx)
	t.Logf("recovery server state: %+v (%v)", state, err)
	logs, err := container.Logs(ctx)
	if err != nil {
		t.Logf("recovery server logs unavailable: %v", err)
		return
	}
	defer logs.Close()
	data, err := io.ReadAll(io.LimitReader(logs, 128<<10))
	t.Logf("recovery server logs (at most 128 KiB):\n%s\n%v", data, err)
}

func recoveryLayouts(t *testing.T, test func(*testing.T, StoreOptions)) {
	t.Helper()
	requireRecovery(t)
	for _, opts := range []StoreOptions{
		{StorageMode: StorageSnapshot}, {StorageMode: StorageHash}, {StorageMode: StorageJSON},
		{StorageMode: StorageHash, NativeIndexes: true}, {StorageMode: StorageJSON, NativeIndexes: true},
	} {
		name := string(opts.StorageMode)
		if opts.NativeIndexes {
			name += "-native"
		}
		t.Run(name, func(t *testing.T) {
			t.Cleanup(func() { logRecoveryRedis(t, ownedRedisContainer) })
			if opts.StorageMode == StorageJSON {
				requireRedisJSON(t)
			}
			if opts.NativeIndexes {
				requireNativeSearch(t)
			}
			opts.Addr = integrationAddr
			id, err := vectordata.NewUUIDKey()
			if err != nil {
				t.Fatal(err)
			}
			opts.Namespace = "recovery:" + id
			test(t, opts)
		})
	}
}

func recoveryDefinition(native bool) vectordata.CollectionDefinition {
	p := vectordata.VectorProperty{Name: "Vector", Dimensions: 16, Metric: vectordata.DistanceL2Squared}
	if native {
		p.Index = &vectordata.VectorIndexOptions{Method: vectordata.IndexMethodFlat}
	}
	return vectordata.CollectionDefinition{
		Key: vectordata.KeyProperty{Name: "ID", Type: vectordata.KeyInt64, AutoGenerated: true},
		Data: []vectordata.DataProperty{
			{Name: "Value", Type: vectordata.TypeString, IsIndexed: true, IsFullTextIndexed: native},
			{Name: "Number", Type: vectordata.TypeInt64},
		}, Vectors: []vectordata.VectorProperty{p},
	}
}

func recoveryRow(key int64, value string) vectordata.ModelRecord {
	vector := make([]float32, 16)
	vector[0] = float32(key)
	return vectordata.ModelRecord{Key: key, Data: map[string]any{"Value": value, "Number": int64(9007199254740993)}, Vectors: map[string][]float32{"Vector": vector}}
}

func recoveryStore(t *testing.T, opts StoreOptions) *Store {
	t.Helper()
	s, err := New(opts)
	if err != nil {
		t.Fatal(err)
	}
	t.Cleanup(func() { s.Close() })
	return s
}

func recoveryHandle(t *testing.T, s *Store, create bool) *Collection {
	t.Helper()
	d := recoveryDefinition(s.nativeIndexes)
	var base vectordata.ModelCollection
	var err error
	if create {
		base, err = s.EnsureModelCollection(t.Context(), "records", d, vectordata.ModelCollectionOptions{})
	} else {
		// Recovery must use the persisted registration; do not implicitly Ensure or
		// rebuild anything to hide missing physical storage/index state.
		base, err = s.GetModelCollection("records", d, vectordata.ModelCollectionOptions{})
	}
	if err != nil {
		t.Fatal(err)
	}
	return base.(*Collection)
}

func redisContainerAddr(t *testing.T, container testcontainers.Container) string {
	t.Helper()
	host, err := container.Host(t.Context())
	if err != nil {
		t.Fatal(err)
	}
	port, err := container.MappedPort(t.Context(), "6379/tcp")
	if err != nil {
		t.Fatal(err)
	}
	return net.JoinHostPort(host, port.Port())
}

func restartRedis(t *testing.T) {
	t.Helper()
	ctx, cancel := context.WithTimeout(t.Context(), time.Minute)
	defer cancel()
	client, err := testcontainers.NewDockerClientWithOpts(ctx)
	if err != nil {
		t.Fatal(err)
	}
	defer client.Close()
	if _, err := client.ContainerKill(ctx, ownedRedisContainer.GetContainerID(), dockerclient.ContainerKillOptions{Signal: "SIGKILL"}); err != nil {
		t.Fatal(err)
	}
	waitResult := client.ContainerWait(ctx, ownedRedisContainer.GetContainerID(), dockerclient.ContainerWaitOptions{})
	select {
	case status := <-waitResult.Result:
		if status.StatusCode != 137 {
			t.Fatalf("expected SIGKILL exit 137, got %d", status.StatusCode)
		}
	case err := <-waitResult.Error:
		t.Fatal(err)
	case <-ctx.Done():
		t.Fatal(ctx.Err())
	}
	if err := ownedRedisContainer.Start(ctx); err != nil {
		t.Fatal(err)
	}
	integrationAddr = redisContainerAddr(t, ownedRedisContainer)
}

func restoreRedis(t *testing.T, backup []byte) string {
	t.Helper()
	image := os.Getenv("REDIS_TEST_IMAGE")
	if image == "" {
		image = "redis:8.2"
	}
	ctx, cancel := context.WithTimeout(t.Context(), time.Minute)
	defer cancel()
	c, err := testcontainers.GenericContainer(ctx, testcontainers.GenericContainerRequest{
		ContainerRequest: testcontainers.ContainerRequest{
			Image: image, ExposedPorts: []string{"6379/tcp"},
			// Restore an RDB into a fresh server, without an AOF that could take
			// precedence over it. No active server or application data is replaced.
			Cmd:        []string{"redis-server", "--appendonly", "no", "--save", "", "--maxmemory-policy", "noeviction"},
			Files:      []testcontainers.ContainerFile{{Reader: bytes.NewReader(backup), ContainerFilePath: "/data/dump.rdb", FileMode: 0644}},
			WaitingFor: redisRecoveryWait(),
		}, Started: true,
	})
	if c != nil {
		t.Cleanup(func() {
			logRecoveryRedis(t, c)
			cleanup, stop := context.WithTimeout(context.Background(), 30*time.Second)
			defer stop()
			if err := c.Terminate(cleanup); err != nil {
				t.Error(err)
			}
		})
	}
	if err != nil {
		t.Fatal(err)
	}
	return redisContainerAddr(t, c)
}

func assertRecovered(t *testing.T, c *Collection, firstValue string, hasUnacknowledged bool) {
	t.Helper()
	ctx, cancel := context.WithTimeout(t.Context(), 15*time.Second)
	defer cancel()
	definition := recoveryDefinition(c.store.nativeIndexes)
	definition.Vectors[0].Dimensions++
	incompatible, err := c.store.GetModelCollection(c.name, definition, vectordata.ModelCollectionOptions{})
	if err != nil {
		t.Fatal(err)
	}
	if _, err := incompatible.Count(ctx, nil); !errors.Is(err, vectordata.ErrSchemaMismatch) {
		t.Fatalf("incompatible restored registration: %v", err)
	}
	expected := []vectordata.ModelRecord{recoveryRow(1, firstValue), recoveryRow(3, "original")}
	nextKey := int64(4)
	if hasUnacknowledged {
		expected = append(expected, recoveryRow(4, "unacknowledged"))
		nextKey++
	} else if _, err := c.Get(ctx, int64(4), vectordata.RetrievalOptions{}); !errors.Is(err, vectordata.ErrNotFound) {
		t.Fatalf("post-backup insert in RDB: %v", err)
	}
	checkRows := func(rows []vectordata.ModelRecord) {
		t.Helper()
		if count, err := c.Count(ctx, nil); err != nil || count != int64(len(rows)) {
			t.Fatalf("recovered count: %d want %d: %v", count, len(rows), err)
		}
		for _, want := range rows {
			got, err := c.Get(ctx, want.Key, vectordata.RetrievalOptions{IncludeVectors: true})
			if err != nil || !reflect.DeepEqual(got, want) {
				t.Fatalf("recovered record: got %+v, expected %+v: %v", got, want, err)
			}
		}
	}
	checkRows(expected)
	if _, err := c.Get(ctx, int64(2), vectordata.RetrievalOptions{}); !errors.Is(err, vectordata.ErrNotFound) {
		t.Fatalf("deleted record returned after recovery: %v", err)
	}
	filtered, err := c.Query(ctx, vectordata.Eq(vectordata.Column("Value"), firstValue), 10, vectordata.QueryOptions{})
	if err != nil || len(filtered) != 1 || filtered[0].Key != int64(1) {
		t.Fatalf("recovered filtering: %+v %v", filtered, err)
	}
	if c.store.nativeIndexes {
		if ids := fullTextKeys(t, c, firstValue); len(ids) != 1 {
			t.Fatalf("recovered TEXT index: %v", ids)
		}
	}
	if hits, err := c.Search(ctx, recoveryRow(1, "").Vectors["Vector"], 2, vectordata.ModelSearchOptions{}); err != nil || len(hits) != 2 || hits[0].Record.Key != int64(1) || hits[0].Distance != 0 || hits[1].Record.Key != int64(3) || hits[1].Distance != 4 {
		t.Fatalf("recovered vector ranking: %+v %v", hits, err)
	}
	row := recoveryRow(nextKey, "after recovery")
	row.Key = nil
	if keys, err := c.Insert(ctx, []vectordata.ModelRecord{row}); err != nil || len(keys) != 1 || keys[0] != nextKey {
		t.Fatalf("recovered generated sequence: %v %v", keys, err)
	}
	row.Key = nextKey
	checkRows(append(expected, row))
}

func TestIntegrationRecoveryRestartAndRestore(t *testing.T) {
	recoveryLayouts(t, func(t *testing.T, opts StoreOptions) {
		s := recoveryStore(t, opts)
		ctx, cancel := context.WithTimeout(t.Context(), time.Minute)
		defer cancel()
		// Assert the durability policy rather than relying on an image default.
		for key, value := range map[string]string{"appendonly": "yes", "appendfsync": "always", "maxmemory-policy": "noeviction", "save": ""} {
			got, err := s.client.ConfigGet(ctx, key).Result()
			if err != nil || got[key] != value {
				t.Fatalf("fixture %s: %v %v", key, got, err)
			}
		}
		c := recoveryHandle(t, s, true)
		rows := []vectordata.ModelRecord{recoveryRow(1, "original"), recoveryRow(2, "removed"), recoveryRow(3, "original")}
		for i := range rows {
			rows[i].Key = nil
		}
		if keys, err := c.Insert(ctx, rows); err != nil || !reflect.DeepEqual(keys, []any{int64(1), int64(2), int64(3)}) {
			t.Fatalf("seed: %v %v", keys, err)
		}
		if _, err := c.Upsert(ctx, []vectordata.ModelRecord{recoveryRow(1, "updated")}); err != nil {
			t.Fatal(err)
		}
		if n, err := c.Delete(ctx, []any{int64(2)}); err != nil || n != 1 {
			t.Fatalf("delete: %d %v", n, err)
		}
		invalid := recoveryRow(5, "must not appear")
		invalid.Vectors["Vector"] = []float32{1}
		if _, err := c.Insert(ctx, []vectordata.ModelRecord{recoveryRow(4, "must roll back"), invalid}); err == nil {
			t.Fatal("invalid batch succeeded")
		}
		if err := s.client.Save(ctx).Err(); err != nil {
			t.Fatal(err)
		}
		file, err := ownedRedisContainer.CopyFileFromContainer(ctx, "/data/dump.rdb")
		if err != nil {
			t.Fatal(err)
		}
		backup, readErr := io.ReadAll(file)
		closeErr := file.Close()
		if readErr != nil || closeErr != nil || len(backup) == 0 {
			t.Fatalf("RDB backup: %v %v", readErr, closeErr)
		}
		// This acknowledged update is newer than dump.rdb. Its presence after
		// SIGKILL proves recovery used the AOF, not merely that RDB snapshot.
		if _, err := c.Upsert(ctx, []vectordata.ModelRecord{recoveryRow(1, "postbackup")}); err != nil {
			t.Fatal(err)
		}
		// Drop only the successful publication reply. The caller has no key or
		// success acknowledgement and does not retry this logical insert.
		script := map[StorageMode]string{StorageSnapshot: compareSwap, StorageHash: publishHash, StorageJSON: publishJSON}[opts.StorageMode]
		publications := 0
		s.client.AddHook(processHook{run: func(ctx context.Context, cmd goredis.Cmder, next goredis.ProcessHook) error {
			err := next(ctx, cmd)
			if scriptIs(cmd, script) {
				publications++
				if err == nil {
					return context.DeadlineExceeded
				}
			}
			return err
		}})
		uncertain := recoveryRow(4, "unacknowledged")
		uncertain.Key = nil
		keys, err := c.Insert(ctx, []vectordata.ModelRecord{uncertain})
		if !errors.Is(err, context.DeadlineExceeded) || keys != nil || publications != 1 {
			t.Fatalf("lost publication reply: keys=%v err=%v attempts=%d", keys, err, publications)
		}
		if err := s.Close(); err != nil {
			t.Fatal(err)
		}
		start := time.Now()
		restartRedis(t)
		opts.Addr = integrationAddr
		reopened := recoveryStore(t, opts)
		assertRecovered(t, recoveryHandle(t, reopened, false), "postbackup", true)
		aofElapsed := time.Since(start)
		start = time.Now()
		opts.Addr = restoreRedis(t, backup)
		restored := recoveryStore(t, opts)
		assertRecovered(t, recoveryHandle(t, restored, false), "updated", false)
		rdbElapsed := time.Since(start)
		info, err := restored.client.Info(ctx, "server").Result()
		if err != nil {
			t.Fatal(err)
		}
		for line := range strings.Lines(info) {
			if version, ok := strings.CutPrefix(line, "redis_version:"); ok {
				t.Logf("Redis %s AOF restart %s, RDB restore %s", strings.TrimSpace(version), aofElapsed, rdbElapsed)
				return
			}
		}
		t.Fatal("missing Redis server version")
	})
}

type workloadStats struct {
	mu        sync.Mutex
	count     int
	latencies []time.Duration
	maximum   time.Duration
}

func (s *workloadStats) record(start time.Time) {
	d := time.Since(start)
	s.mu.Lock()
	defer s.mu.Unlock()
	s.count++
	s.maximum = max(s.maximum, d)
	if len(s.latencies) < 4096 {
		s.latencies = append(s.latencies, d)
	}
}

func (s *workloadStats) log(t *testing.T, kind string) {
	sort.Slice(s.latencies, func(i, j int) bool { return s.latencies[i] < s.latencies[j] })
	if s.count == 0 {
		t.Fatalf("no completed %s operations", kind)
	}
	t.Logf("%s operations=%d sampled=%d p50=%s p95=%s max=%s", kind, s.count, len(s.latencies), s.latencies[len(s.latencies)/2], s.latencies[(len(s.latencies)-1)*95/100], s.maximum)
}

func TestIntegrationRecoveryMixedWorkload(t *testing.T) {
	duration := 2 * time.Second
	if configured := os.Getenv("REDIS_SOAK_DURATION"); configured != "" {
		var err error
		duration, err = time.ParseDuration(configured)
		if err != nil || duration < time.Second || duration > 10*time.Minute {
			t.Fatal("REDIS_SOAK_DURATION must be between 1s and 10m")
		}
	}
	recoveryLayouts(t, func(t *testing.T, opts StoreOptions) {
		s := recoveryStore(t, opts)
		c := recoveryHandle(t, s, true)
		var rows []vectordata.ModelRecord
		for key := int64(1); key <= 64; key++ {
			rows = append(rows, recoveryRow(key, "seed"))
		}
		if _, err := c.Insert(t.Context(), rows); err != nil {
			t.Fatal(err)
		}
		var before, after runtime.MemStats
		runtime.ReadMemStats(&before)
		until := time.Now().Add(duration)
		var reads, writes workloadStats
		var workers sync.WaitGroup
		failures := make(chan error, 4)
		ctx, stop := context.WithCancel(t.Context())
		defer stop()
		for worker := range 4 {
			workers.Add(1)
			go func() {
				defer workers.Done()
				for iteration := 0; time.Now().Before(until) && ctx.Err() == nil; iteration++ {
					request, cancel := context.WithTimeout(ctx, 10*time.Second)
					start := time.Now()
					var err error
					if worker < 2 {
						first := int64(worker*2 + 1)
						value := fmt.Sprintf("writer%d-generation%d", worker, iteration)
						_, err = c.Upsert(request, []vectordata.ModelRecord{recoveryRow(first, value), recoveryRow(first+1, value)})
						if err == nil {
							writes.record(start)
						}
					} else {
						err = checkWorkloadRead(request, c)
						if err == nil {
							reads.record(start)
						}
					}
					cancel()
					if err != nil {
						failures <- fmt.Errorf("worker %d: %w", worker, err)
						stop()
						return
					}
				}
			}()
		}
		workers.Wait()
		close(failures)
		for err := range failures {
			t.Error(err)
		}
		if t.Failed() {
			return
		}
		reads.log(t, "query+search")
		writes.log(t, "two-record upsert")
		runtime.ReadMemStats(&after)
		info, err := s.client.Info(t.Context(), "memory").Result()
		if err != nil {
			t.Fatal(err)
		}
		for _, line := range strings.Split(info, "\r\n") {
			if strings.HasPrefix(line, "used_memory:") {
				memory, err := strconv.ParseUint(strings.TrimPrefix(line, "used_memory:"), 10, 64)
				if err != nil {
					t.Fatal(err)
				}
				t.Logf("duration=%s process_heap_before=%d process_heap_after=%d redis_used_memory=%d", duration, before.HeapAlloc, after.HeapAlloc, memory)
			}
		}
		// Cleanup follows completed workers and must preserve the active generation.
		if _, err := s.PruneHashStorage(t.Context(), c.name); err != nil {
			t.Fatal(err)
		}
		if _, err := s.PruneJSONStorage(t.Context(), c.name); err != nil {
			t.Fatal(err)
		}
		if s.nativeIndexes {
			if _, err := s.PruneNativeIndexes(t.Context(), c.name); err != nil {
				t.Fatal(err)
			}
		}
		if err := checkWorkloadRead(t.Context(), c); err != nil {
			t.Fatal("cleanup damaged current data:", err)
		}
		if err := s.DeleteCollection(t.Context(), c.name); err != nil {
			t.Fatal(err)
		}
	})
}

func checkWorkloadRead(ctx context.Context, c *Collection) error {
	rows, err := c.Query(ctx, nil, 64, vectordata.QueryOptions{})
	if err != nil {
		return err
	}
	if len(rows) != 64 {
		return fmt.Errorf("lost records: %d", len(rows))
	}
	values := map[int64]any{}
	for _, row := range rows {
		values[row.Key.(int64)] = row.Data["Value"]
	}
	if values[1] != values[2] || values[3] != values[4] {
		return fmt.Errorf("partial two-record batch observed: %v", values)
	}
	hits, err := c.Search(ctx, recoveryRow(1, "").Vectors["Vector"], 5, vectordata.ModelSearchOptions{})
	if err != nil {
		return err
	}
	if len(hits) != 5 {
		return fmt.Errorf("search returned %d results", len(hits))
	}
	for i, hit := range hits {
		if hit.Record.Key != int64(i+1) || hit.Distance != float64(i*i) {
			return fmt.Errorf("wrong exact ranking: %+v", hits)
		}
	}
	return nil
}
