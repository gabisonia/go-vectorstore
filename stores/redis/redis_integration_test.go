var integrationAddr string
var ownedRedisContainer testcontainers.Container

func TestMain(m *testing.M) {
	integrationAddr = os.Getenv("REDIS_TEST_ADDR")
	if integrationAddr != "" && os.Getenv("REDIS_TEST_RECOVERY") == "true" {
		fmt.Fprintln(os.Stderr, "Redis recovery tests require an owned container; unset REDIS_TEST_ADDR")
		os.Exit(1)
	}
	var container testcontainers.Container
	if integrationAddr == "" {
		ctx, cancel := context.WithTimeout(context.Background(), 2*time.Minute)
		image := os.Getenv("REDIS_TEST_IMAGE")
		if image == "" {
			image = "redis:8.2"
		}
		var err error
		request := testcontainers.ContainerRequest{Image: image, ExposedPorts: []string{"6379/tcp"}, WaitingFor: wait.ForListeningPort("6379/tcp")}
		if os.Getenv("REDIS_TEST_RECOVERY") == "true" {
			request.Cmd = []string{"redis-server", "--appendonly", "yes", "--appendfsync", "always", "--save", "", "--maxmemory-policy", "noeviction"}
			request.WaitingFor = redisRecoveryWait()
		}
		container, err = testcontainers.GenericContainer(ctx, testcontainers.GenericContainerRequest{ContainerRequest: request, Started: true})
		ownedRedisContainer = container
		if err == nil {
			var host string
			host, err = container.Host(ctx)
			if err == nil {
				port, portErr := container.MappedPort(ctx, "6379/tcp")
				err = portErr
				if err == nil {
					integrationAddr = net.JoinHostPort(host, port.Port())
				}
			}
		}
		cancel()
		if err != nil {
			if container != nil {
				container.Terminate(context.Background())
			}
			fmt.Fprintln(os.Stderr, "Redis test container:", err)
			os.Exit(1)
		}
	}
	code := m.Run()
	if container != nil {
		ctx, cancel := context.WithTimeout(context.Background(), 30*time.Second)
		if err := container.Terminate(ctx); err != nil {
			fmt.Fprintln(os.Stderr, err)
			code = 1
		}
		cancel()
	}
	os.Exit(code)
}

func integrationStore(t *testing.T, options StoreOptions) *Store {
	t.Helper()
	options.Addr = integrationAddr
	if options.Namespace == "" {
		id, err := vectordata.NewUUIDKey()
		if err != nil {
			t.Fatal(err)
		}
		options.Namespace = "test:" + id
	}
	s, err := New(options)
	if err != nil {
		t.Fatal(err)
	}
	t.Cleanup(func() {
		ctx, cancel := context.WithTimeout(context.Background(), 5*time.Second)
		defer cancel()
		names, err := s.ListCollectionNames(ctx)
		if err != nil {
			t.Error(err)
		}
		for _, name := range names {
			if err := s.DeleteCollection(ctx, name); err != nil {
				t.Error(err)
			}
		}
		s.Close()
	})
	return s
}
