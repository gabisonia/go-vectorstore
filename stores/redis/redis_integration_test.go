func generatedCollection(t *testing.T, s *Store) *Collection {
	t.Helper()
	base, err := s.EnsureModelCollection(context.Background(), "generated", vectordata.CollectionDefinition{Key: vectordata.KeyProperty{Name: "ID", Type: vectordata.KeyInt64, AutoGenerated: true}, Data: []vectordata.DataProperty{{Name: "Value", Type: vectordata.TypeString}}}, vectordata.ModelCollectionOptions{})
	if err != nil {
		t.Fatal(err)
	}
	return base.(*Collection)
}
func TestIntegrationConcurrentWritesAndReopen(t *testing.T) {
	s := integrationStore(t, StoreOptions{})
	c := generatedCollection(t, s)
	other, err := New(StoreOptions{Addr: integrationAddr, Namespace: s.metadata.Namespace})
	if err != nil {
		t.Fatal(err)
	}
	defer other.Close()
	base, err := other.GetModelCollection(c.name, c.definition, vectordata.ModelCollectionOptions{})
	if err != nil {
		t.Fatal(err)
	}
	var wg sync.WaitGroup
	keys := make(chan int64, 24)
	for i := range 24 {
		wg.Add(1)
		go func() {
			defer wg.Done()
			target := vectordata.ModelCollection(c)
			if i%2 == 0 {
				target = base
			}
			out, err := target.Insert(context.Background(), []vectordata.ModelRecord{{Data: map[string]any{"Value": "kept"}}})
			if err != nil {
				t.Error(err)
				return
			}
			keys <- out[0].(int64)
		}()
	}
	wg.Wait()
	close(keys)
	seen := map[int64]bool{}
	for key := range keys {
		if seen[key] {
			t.Fatal("duplicate generated key")
		}
		seen[key] = true
	}
	if len(seen) != 24 {
		t.Fatalf("lost writes: %d", len(seen))
	}
	if err := other.Close(); err != nil {
		t.Fatal(err)
	}
	reopened, err := New(StoreOptions{Addr: integrationAddr, Namespace: s.metadata.Namespace})
	if err != nil {
		t.Fatal(err)
	}
	defer reopened.Close()
	handle, err := reopened.GetModelCollection(c.name, c.definition, vectordata.ModelCollectionOptions{})
	if err != nil {
		t.Fatal(err)
	}
	if count, err := handle.Count(context.Background(), nil); err != nil || count != 24 {
		t.Fatalf("reopen: %d %v", count, err)
	}
	keys2, err := handle.Insert(context.Background(), []vectordata.ModelRecord{{Data: map[string]any{"Value": "after"}}})
	if err != nil || keys2[0] != int64(25) {
		t.Fatalf("sequence reopen: %v %v", keys2, err)
	}
}

func TestIntegrationFailedBatchesPreserveSequenceAndBytes(t *testing.T) {
	ctx := context.Background()
	s := integrationStore(t, StoreOptions{})
	c := generatedCollection(t, s)
	if _, err := c.Insert(ctx, []vectordata.ModelRecord{{Key: int64(2), Data: map[string]any{"Value": "explicit"}}}); err != nil {
		t.Fatal(err)
	}
	before, err := s.client.Get(ctx, s.key(c.name)).Bytes()
	if err != nil {
		t.Fatal(err)
	}
	if _, err := c.Upsert(ctx, []vectordata.ModelRecord{{Data: map[string]any{"Value": "generated one"}}, {Data: map[string]any{"Value": "collision two"}}}); !errors.Is(err, vectordata.ErrInvalidRecord) {
		t.Fatalf("generated collision: %v", err)
	}
	after, _ := s.client.Get(ctx, s.key(c.name)).Bytes()
	if string(after) != string(before) {
		t.Fatal("failed batch mutated storage")
	}
	keys, err := c.Insert(ctx, []vectordata.ModelRecord{{Data: map[string]any{"Value": "next"}}})
	if err != nil || keys[0] != int64(1) {
		t.Fatalf("sequence advanced: %v %v", keys, err)
	}
	state, _, err := c.load(ctx)
	if err != nil {
		t.Fatal(err)
	}
	state.Next = math.MaxInt64
	raw, err := c.encode(state)
	if err != nil {
		t.Fatal(err)
	}
	if err = s.client.Set(ctx, s.key(c.name), raw, 0).Err(); err != nil {
		t.Fatal(err)
	}
	keys, err = c.Insert(ctx, []vectordata.ModelRecord{{Data: map[string]any{"Value": "max"}}})
	if err != nil || keys[0] != int64(math.MaxInt64) {
		t.Fatalf("sequence precision: %v %v", keys, err)
	}
	if _, err = c.Insert(ctx, []vectordata.ModelRecord{{Data: map[string]any{"Value": "overflow"}}}); !errors.Is(err, vectordata.ErrInvalidRecord) {
		t.Fatalf("exhaustion: %v", err)
	}
}

// Wrap the client after its normal process/retry loop. Simulate losing a reply
// after Redis committed: the provider must return the error without a new CAS.
type processHook struct {
	run func(context.Context, goredis.Cmder, goredis.ProcessHook) error
}

func (h processHook) DialHook(next goredis.DialHook) goredis.DialHook { return next }
func (h processHook) ProcessPipelineHook(next goredis.ProcessPipelineHook) goredis.ProcessPipelineHook {
	return next
}
func (h processHook) ProcessHook(next goredis.ProcessHook) goredis.ProcessHook {
	return func(ctx context.Context, cmd goredis.Cmder) error { return h.run(ctx, cmd, next) }
}
func TestIntegrationUncertainWritesNeverReplay(t *testing.T) {
	s := integrationStore(t, StoreOptions{})
	c := generatedCollection(t, s)
	var evals atomic.Int32
	s.client.AddHook(processHook{run: func(ctx context.Context, cmd goredis.Cmder, next goredis.ProcessHook) error {
		err := next(ctx, cmd)
		if cmd.Name() == "eval" {
			evals.Add(1)
			if err == nil {
				return context.DeadlineExceeded
			}
		}
		return err
	}})
	keys, err := c.Insert(context.Background(), []vectordata.ModelRecord{{Data: map[string]any{"Value": "once"}}})
	if !errors.Is(err, context.DeadlineExceeded) || keys != nil || evals.Load() != 1 {
		t.Fatalf("uncertain result replayed: %v %v %d", keys, err, evals.Load())
	}
	state, _, err := c.load(context.Background())
	if err != nil || len(state.Records) != 1 || state.Next != 2 {
		t.Fatalf("write replay: %+v %v", state, err)
	}
}

func TestIntegrationConflictsDoNotRepeatEmbeddingAndReentry(t *testing.T) {
	ctx, cancel := context.WithTimeout(context.Background(), 5*time.Second)
	defer cancel()
	s := integrationStore(t, StoreOptions{})
	c := generatedCollection(t, s)
	var calls int
	d := vectordata.CollectionDefinition{Key: vectordata.KeyProperty{Name: "ID"}, Data: []vectordata.DataProperty{{Name: "Body", Type: vectordata.TypeString}}, Vectors: []vectordata.VectorProperty{{Name: "Vector", Dimensions: 2, SourceProperty: "Body", Optional: true}}}
	base, err := s.EnsureModelCollection(ctx, "embedded", d, vectordata.ModelCollectionOptions{Embedder: vectordata.EmbeddingFunc(func(ctx context.Context, input []string) ([][]float32, error) {
		calls++
		if _, err := c.Count(ctx, nil); err != nil {
			return nil, err
		}
		return [][]float32{{1, 0}}, nil
	})})
	if err != nil {
		t.Fatal(err)
	}
	var conflicted bool
	s.client.AddHook(processHook{run: func(ctx context.Context, cmd goredis.Cmder, next goredis.ProcessHook) error {
		if cmd.Name() == "eval" && !conflicted {
			conflicted = true
			cmd.(*goredis.Cmd).SetVal(int64(0))
			return nil
		}
		return next(ctx, cmd)
	}})
	if _, err := base.Insert(ctx, []vectordata.ModelRecord{{Key: "a", Data: map[string]any{"Body": "text"}}}); err != nil {
		t.Fatal(err)
	}
	if !conflicted || calls != 1 {
		t.Fatalf("embedding replayed: %t %d", conflicted, calls)
	}
	for _, err := range base.QueryIter(ctx, nil, 1, vectordata.QueryOptions{}) {
		if err != nil {
			t.Fatal(err)
		}
		if _, err := base.Upsert(ctx, []vectordata.ModelRecord{{Key: "b", Data: map[string]any{"Body": "text"}, Vectors: map[string][]float32{"Vector": {0, 1}}}}); err != nil {
			t.Fatal(err)
		}
		break
	}
	if calls != 1 {
		t.Fatal("read invoked embedder")
	}
}

func TestIntegrationNamespaceSchemaLimitsAndCorruption(t *testing.T) {
	ctx := context.Background()
	s := integrationStore(t, StoreOptions{Namespace: "special[*]?" + fmt.Sprint(time.Now().UnixNano())})
	c := generatedCollection(t, s)
	alien := integrationStore(t, StoreOptions{Namespace: s.metadata.Namespace + ":other"})
	generatedCollection(t, alien)
	names, err := s.ListCollectionNames(ctx)
	if err != nil || len(names) != 1 || names[0] != c.name {
		t.Fatalf("namespace escape: %v %v", names, err)
	}
	d := c.definition.Clone()
	d.Data = append(d.Data, vectordata.DataProperty{Name: "New", Type: vectordata.TypeString, Optional: true})
	stale, err := s.GetModelCollection(c.name, d, vectordata.ModelCollectionOptions{})
	if err != nil {
		t.Fatal(err)
	}
	if _, err = stale.Query(ctx, nil, 1, vectordata.QueryOptions{}); !errors.Is(err, vectordata.ErrSchemaMismatch) {
		t.Fatalf("stale handle: %v", err)
	}
	before, _ := s.client.Get(ctx, s.key(c.name)).Bytes()
	s.maxBytes = 1024
	if _, err = c.Insert(ctx, []vectordata.ModelRecord{{Data: map[string]any{"Value": strings.Repeat("x", 2048)}}}); !errors.Is(err, vectordata.ErrInvalidRecord) {
		t.Fatalf("limit: %v", err)
	}
	after, _ := s.client.Get(ctx, s.key(c.name)).Bytes()
	if string(before) != string(after) {
		t.Fatal("size failure mutated collection")
	}
	s.maxBytes = 16 << 20
	state, _, err := c.load(ctx)
	if err != nil {
		t.Fatal(err)
	}
	state.Format = 99
	raw, _ := json.Marshal(state)
	if err = s.client.Set(ctx, s.key(c.name), raw, 0).Err(); err != nil {
		t.Fatal(err)
	}
	if _, err = c.Count(ctx, nil); !errors.Is(err, vectordata.ErrSchemaMismatch) {
		t.Fatalf("future format: %v", err)
	}
	if err = s.client.Set(ctx, s.key(c.name), "broken", 0).Err(); err != nil {
		t.Fatal(err)
	}
	if _, err = c.Query(ctx, nil, 1, vectordata.QueryOptions{}); !errors.Is(err, vectordata.ErrInvalidRecord) {
		t.Fatalf("corruption: %v", err)
	}
	if err = c.EnsureDeleted(ctx); err != nil {
		t.Fatal(err)
	}
}

func TestIntegrationReadSnapshotsAndFailedPages(t *testing.T) {
	ctx := context.Background()
	s := integrationStore(t, StoreOptions{})
	c := generatedCollection(t, s)
	rows := func(value string) []vectordata.ModelRecord {
		return []vectordata.ModelRecord{{Key: int64(1), Data: map[string]any{"Value": value}}, {Key: int64(2), Data: map[string]any{"Value": value}}}
	}
	if _, err := c.Upsert(ctx, rows("0")); err != nil {
		t.Fatal(err)
	}
	done := make(chan error, 1)
	go func() {
		for i := range 30 {
			if _, err := c.Upsert(ctx, rows(fmt.Sprint(i))); err != nil {
				done <- err
				return
			}
		}
		done <- nil
	}()
	for range 30 {
		page, err := c.Query(ctx, nil, 2, vectordata.QueryOptions{})
		if err != nil || len(page) != 2 || page[0].Data["Value"] != page[1].Data["Value"] {
			t.Errorf("mixed batch snapshot: %+v %v", page, err)
			break
		}
	}
	if err := <-done; err != nil {
		t.Fatal(err)
	}
	state, _, err := c.load(ctx)
	if err != nil {
		t.Fatal(err)
	}
	state.Records[token(int64(2))] = json.RawMessage(`{"Key":2,"Data":{}}`)
	raw, err := c.encode(state)
	if err != nil {
		t.Fatal(err)
	}
	if err = s.client.Set(ctx, s.key(c.name), raw, 0).Err(); err != nil {
		t.Fatal(err)
	}
	seen := 0
	for _, err := range c.QueryIter(ctx, nil, 2, vectordata.QueryOptions{}) {
		seen++
		if !errors.Is(err, vectordata.ErrInvalidRecord) {
			t.Fatalf("invalid stored page: %v", err)
		}
	}
	if seen != 1 {
		t.Fatalf("partial rows escaped: %d", seen)
	}
	if _, err := c.Get(ctx, int64(1), vectordata.RetrievalOptions{}); err != nil {
		t.Fatalf("unrelated row decoded on get: %v", err)
	}
	if _, err := c.Upsert(ctx, rows("repaired")); err != nil {
		t.Fatalf("failed read leaked resources: %v", err)
	}
}

func TestIntegrationDeadlinesAndCanceledConflicts(t *testing.T) {
	s := integrationStore(t, StoreOptions{})
	c := generatedCollection(t, s)
	ctx := context.Background()
	if err := s.client.Do(ctx, "CLIENT", "PAUSE", 200, "ALL").Err(); err != nil {
		t.Fatal(err)
	}
	deadline, cancel := context.WithTimeout(ctx, 20*time.Millisecond)
	_, err := c.Count(deadline, nil)
	cancel()
	if !errors.Is(err, context.DeadlineExceeded) {
		t.Fatalf("deadline cause lost: %v", err)
	}
	if _, err = c.Count(ctx, nil); err != nil {
		t.Fatalf("deadline leaked connection: %v", err)
	}
	canceled, cancel := context.WithCancel(ctx)
	defer cancel()
	s.client.AddHook(processHook{run: func(ctx context.Context, cmd goredis.Cmder, next goredis.ProcessHook) error {
		if cmd.Name() == "eval" {
			cancel()
			cmd.(*goredis.Cmd).SetVal(int64(0))
			return nil
		}
		return next(ctx, cmd)
	}})
	if keys, err := c.Insert(canceled, []vectordata.ModelRecord{{Data: map[string]any{"Value": "canceled"}}}); keys != nil || !errors.Is(err, context.Canceled) {
		t.Fatalf("canceled conflict: %v %v", keys, err)
	}
	state, _, err := c.load(ctx)
	if err != nil || state.Next != 1 || len(state.Records) != 0 {
		t.Fatalf("canceled CAS mutated storage: %+v %v", state, err)
	}
}
