func TestHashProjectionPreservesCanonicalValues(t *testing.T) {
	s, err := New(StoreOptions{StorageMode: StorageHash})
	if err != nil {
		t.Fatal(err)
	}
	defer s.Close()
	name := `text."[*]雪`
	d := vectordata.CollectionDefinition{Key: vectordata.KeyProperty{Name: "ID", Type: vectordata.KeyUint64}, Data: []vectordata.DataProperty{{Name: name, Type: vectordata.TypeString}, {Name: "Int", Type: vectordata.TypeInt64}, {Name: "Float", Type: vectordata.TypeFloat64}, {Name: "Bool", Type: vectordata.TypeBool}, {Name: "Null", Type: vectordata.TypeString, Optional: true}, {Name: "JSON", Type: vectordata.TypeJSON}}, Vectors: []vectordata.VectorProperty{{Name: "Vector", Dimensions: 2, Precision: vectordata.VectorFloat16, Optional: true}}}
	base, err := s.GetModelCollection("projection", d, vectordata.ModelCollectionOptions{})
	if err != nil {
		t.Fatal(err)
	}
	c := base.(*Collection)
	rows, err := vectordata.PrepareModelRecords(context.Background(), c.definition, vectordata.ModelCollectionOptions{}, []vectordata.ModelRecord{{Key: uint64(math.MaxUint64), Data: map[string]any{name: "nul\x00雪", "Int": int64(math.MinInt64), "Float": math.SmallestNonzeroFloat64, "Bool": true, "Null": nil, "JSON": vectordata.JSONNull{}}, Vectors: map[string][]float32{"Vector": {0.3333, -0.0}}}, {Key: uint64(0), Data: map[string]any{name: "empty vector", "Int": int64(0), "Float": 0.0, "Bool": false, "JSON": map[string]any{"n": json.Number("18446744073709551615")}}}})
	if err != nil {
		t.Fatal(err)
	}
	state := snapshot{Format: 2, Definition: c.registration, Revision: "a0e70dab-3caf-47a4-8f50-c4c03d2e0d38", Next: 1, Records: map[string]json.RawMessage{}}
	for _, r := range rows {
		raw, err := modelcodec.Encode(r)
		if err != nil {
			t.Fatal(err)
		}
		state.Records[token(r.Key)] = raw
	}
	m, raw, projected, err := c.projectHashes(context.Background(), state)
	if err != nil || len(projected) != 2 {
		t.Fatalf("projection: %+v %v", projected, err)
	}
	if m.Next != 1 || m.Format != 2 || !json.Valid(raw) {
		t.Fatalf("manifest: %s", raw)
	}
	for _, row := range projected {
		fields := map[string]string{}
		for i := 0; i < len(row.fields); i += 2 {
			fields[row.fields[i].(string)] = row.fields[i+1].(string)
		}
		if fields["__vs_token"] == token(uint64(math.MaxUint64)) {
			if fields["d_"+encodeName("Int")] != "-9223372036854775808" || fields["d_"+encodeName(name)] != "nul\x00雪" || fields["d_"+encodeName("Bool")] != "1" {
				t.Fatalf("native scalar precision: %+v", fields)
			}
			blob := []byte(fields["v_"+encodeName("Vector")])
			if len(blob) != 8 || math.Float32frombits(binary.LittleEndian.Uint32(blob)) != rows[0].Vectors["Vector"][0] {
				t.Fatal("float16 projection did not preserve rounded float32 values")
			}
			if _, ok := fields["d_"+encodeName("Null")]; ok {
				t.Fatal("NULL got a scalar projection")
			}
		} else if _, ok := fields["v_"+encodeName("Vector")]; ok {
			t.Fatal("absent vector got a blob")
		}
	}
	s.maxBytes = len(raw)
	if _, _, _, err := c.projectHashes(context.Background(), state); !errors.Is(err, vectordata.ErrInvalidRecord) {
		t.Fatalf("hash byte limit: %v", err)
	}
}

func TestFormatOneFixtureStillDecodes(t *testing.T) {
	if got := sha256.Sum256(fixtureBytes(t)); got != [32]byte{0x27, 0xd7, 0x29, 0x3f, 0x13, 0x64, 0xce, 0x91, 0x64, 0x99, 0x3b, 0x62, 0x5d, 0x59, 0x06, 0xb7, 0xd6, 0x3b, 0xfc, 0x09, 0xc9, 0x21, 0x50, 0xa3, 0x93, 0xc8, 0xd0, 0x1c, 0xe1, 0x5b, 0x0e, 0x69} {
		t.Fatal("immutable format-1 fixture checksum changed")
	}
	s, err := New(StoreOptions{})
	if err != nil {
		t.Fatal(err)
	}
	defer s.Close()
	c := fixtureCollection(t, s)
	var state snapshot
	if err := json.Unmarshal(fixtureBytes(t), &state); err != nil {
		t.Fatal(err)
	}
	if state.Format != 1 || state.Definition != c.registration || state.Next != math.MaxInt64 {
		t.Fatal("immutable fixture registration changed")
	}
	rows, err := c.decode(context.Background(), state, nil)
	if err != nil || len(rows) != 1 || rows[0].Key != int64(math.MinInt64) {
		t.Fatalf("fixture decode: %+v %v", rows, err)
	}
	if !reflect.DeepEqual(rows[0].Data["JSON"].(map[string]any)["number"], json.Number("18446744073709551615")) {
		t.Fatal("fixture JSON precision lost")
	}
}

