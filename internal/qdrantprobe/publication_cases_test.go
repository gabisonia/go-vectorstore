func proofClient(t *testing.T, path string) publicationProof {
	t.Helper()
	transport := http.DefaultTransport.(*http.Transport).Clone()
	t.Cleanup(transport.CloseIdleConnections)
	c := client()
	c.Transport = transport
	return publicationProof{path: path, http: c}
}

func proofCollection(t *testing.T) string {
	t.Helper()
	return collection(t, map[string]any{"vectors": map[string]any{}, "shard_number": 1, "sharding_method": "auto", "replication_factor": 1, "metadata": map[string]any{"publication_proof": 1}})
}

func proofDefinition(t *testing.T) (vectordata.CollectionDefinition, string) {
	t.Helper()
	d, err := (vectordata.CollectionDefinition{
		Key:     vectordata.KeyProperty{Name: "ID", Type: vectordata.KeyInt64, AutoGenerated: true},
		Data:    []vectordata.DataProperty{{Name: "Body", Type: vectordata.TypeString}},
		Vectors: []vectordata.VectorProperty{{Name: "V", Dimensions: 2, Metric: vectordata.DistanceL2}},
	}).Normalize()
	if err != nil {
		t.Fatal(err)
	}
	raw, err := json.Marshal(d)
	if err != nil {
		t.Fatal(err)
	}
	return d, string(raw)
}

func proofFixture(t *testing.T) (publicationProof, manifest, vectordata.CollectionDefinition) {
	t.Helper()
	p := proofClient(t, proofCollection(t))
	if _, err := p.initialize(t.Context()); err != nil {
		t.Fatal(err)
	}
	d, definition := proofDefinition(t)
	m, err := p.create(t.Context(), definition)
	if err != nil {
		t.Fatal(err)
	}
	return p, m, d
}

func proofRows(t *testing.T, d vectordata.CollectionDefinition, label string, count int) []string {
	t.Helper()
	records := make([]vectordata.ModelRecord, count)
	for i := range records {
		records[i] = vectordata.ModelRecord{Key: int64(i + 1), Data: map[string]any{"Body": label}, Vectors: map[string][]float32{"V": {float32(i), 0}}}
	}
	out, err := canonicalProofRecords(t.Context(), d, records)
	if err != nil {
		t.Fatal(err)
	}
	return out
}

func proofRead(t *testing.T, p publicationProof) manifest {
	t.Helper()
	m, err := p.read(t.Context())
	if err != nil {
		t.Fatal(err)
	}
	return m
}

func proofStage(t *testing.T, p publicationProof, records []string, next int64) generation {
	t.Helper()
	g, err := p.reserve(t.Context(), proofRead(t, p), records, next)
	if err != nil {
		t.Fatal(err)
	}
	if err := p.stage(t.Context(), g, records); err != nil {
		t.Fatal(err)
	}
	return g
}

type proofRoundTripper func(*http.Request) (*http.Response, error)

func (f proofRoundTripper) RoundTrip(r *http.Request) (*http.Response, error) { return f(r) }

// Intercept only the client boundary; every forwarded operation is executed by
// the real pinned server. No stand-in backend or fake successful reply is used.
func proofIntercept(p publicationProof, f func(*http.Request, http.RoundTripper) (*http.Response, error)) publicationProof {
	c := *p.http
	transport := p.http.Transport
	c.Transport = proofRoundTripper(func(r *http.Request) (*http.Response, error) { return f(r, transport) })
	p.http = &c
	return p
}

func proofRequestBody(r *http.Request) map[string]json.RawMessage {
	if r.GetBody == nil {
		return nil
	}
	body, err := r.GetBody()
	if err != nil {
		return nil
	}
	defer body.Close()
	var out map[string]json.RawMessage
	if json.NewDecoder(body).Decode(&out) != nil {
		return nil
	}
	return out
}

func proofManifestWrite(r *http.Request) bool {
	if r.Method != "PUT" || !strings.HasSuffix(r.URL.Path, "/points") {
		return false
	}
	body := proofRequestBody(r)
	var points []struct {
		ID int `json:"id"`
	}
	return string(body["update_mode"]) == `"update_only"` && json.Unmarshal(body["points"], &points) == nil && len(points) == 1 && points[0].ID == 0
}

func proofDataWrite(r *http.Request) bool {
	if r.Method != "PUT" || !strings.HasSuffix(r.URL.Path, "/points") {
		return false
	}
	var points []struct {
		ID int `json:"id"`
	}
	return json.Unmarshal(proofRequestBody(r)["points"], &points) == nil && len(points) > 0 && points[0].ID > 0
}

func proofDataRead(r *http.Request) bool {
	if r.Method != "POST" || !strings.HasSuffix(r.URL.Path, "/points") {
		return false
	}
	var ids []int
	return json.Unmarshal(proofRequestBody(r)["ids"], &ids) == nil && len(ids) > 0 && ids[0] > 0
}

func proofConsume(response *http.Response, err error) error {
	if err != nil {
		return err
	}
	defer response.Body.Close()
	_, err = io.Copy(io.Discard, response.Body)
	if err != nil {
		return err
	}
	if response.StatusCode != 200 {
		return fmt.Errorf("real server returned HTTP %d", response.StatusCode)
	}
	return nil
}

func TestPublicationConcurrentInitializationAndReservations(t *testing.T) {
	path := proofCollection(t)
	const contenders = 6
	clients := make([]publicationProof, contenders)
	for i := range clients {
		clients[i] = proofClient(t, path)
	}
	start := make(chan struct{})
	results := make(chan manifest, contenders)
	failures := make(chan error, contenders)
	var wg sync.WaitGroup
	for _, p := range clients {
		wg.Add(1)
		go func() {
			defer wg.Done()
			<-start
			m, err := p.initialize(t.Context())
			if err != nil {
				failures <- err
			} else {
				results <- m
			}
		}()
	}
	close(start)
	wg.Wait()
	close(results)
	close(failures)
	for err := range failures {
		t.Fatal(err)
	}
	var revision string
	for m := range results {
		if revision == "" {
			revision = m.Revision
		}
		if revision != m.Revision || m.Active || len(m.Slots) != 0 {
			t.Fatalf("initialization overwrote root: %+v", m)
		}
	}
	_, definition := proofDefinition(t)
	base, err := clients[0].create(t.Context(), definition)
	if err != nil {
		t.Fatal(err)
	}
	start = make(chan struct{})
	outcomes := make(chan error, contenders)
	for _, p := range clients {
		wg.Add(1)
		go func() { defer wg.Done(); <-start; _, err := p.reserve(t.Context(), base, nil, 1); outcomes <- err }()
	}
	close(start)
	wg.Wait()
	close(outcomes)
	winners := 0
	for err := range outcomes {
		if err == nil {
			winners++
		} else if !errors.Is(err, errProofConflict) {
			t.Fatal(err)
		}
	}
	m := proofRead(t, clients[0])
	if winners != 1 || len(m.Slots) != 1 || len(m.Receipts) != 2 {
		t.Fatalf("reservations: winners=%d root=%+v", winners, m)
	}
	t.Log("six independent clients adopted one root; one reservation won from the same revision")
}

func TestPublicationConcurrentWritersDoNotLoseUpdates(t *testing.T) {
	p, initial, d := proofFixture(t)
	other := proofClient(t, p.path)
	left := proofStage(t, p, proofRows(t, d, "left", 1), 2)
	right := proofStage(t, other, proofRows(t, d, "right", 1), 2)
	start := make(chan struct{})
	outcomes := make(chan error, 2)
	var wg sync.WaitGroup
	for i, g := range []generation{left, right} {
		q := []publicationProof{p, other}[i]
		wg.Add(1)
		go func() { defer wg.Done(); <-start; outcomes <- q.publish(t.Context(), g) }()
	}
	close(start)
	wg.Wait()
	close(outcomes)
	winners := 0
	for err := range outcomes {
		if err == nil {
			winners++
		} else if !errors.Is(err, errProofConflict) {
			t.Fatal(err)
		}
	}
	m, rows, err := p.snapshot(t.Context(), initial.Epoch)
	if err != nil || winners != 1 || len(rows) != 1 || m.Next != 2 || len(m.Slots) != 2 || m.Head != left.Token && m.Head != right.Token {
		t.Fatalf("publication: winners=%d root=%+v rows=%d err=%v", winners, m, len(rows), err)
	}
	loser := left
	if m.Head == left.Token {
		loser = right
	}
	if _, err := p.readGeneration(t.Context(), loser); err != nil {
		t.Fatal("losing staging was reclaimed:", err)
	}
	if !errors.Is(p.prune(t.Context()), vectordata.ErrUnsupported) {
		t.Fatal("online cleanup must stay disabled")
	}
}

func TestPublicationLostReplyConfirmedAfterSupersedingWrite(t *testing.T) {
	p, initial, d := proofFixture(t)
	aRows, bRows := proofRows(t, d, "A", 1), proofRows(t, d, "B", 2)
	a := proofStage(t, p, aRows, 2)
	dropped := errors.New("lost publication reply")
	var writes atomic.Int32
	fault := proofIntercept(p, func(r *http.Request, transport http.RoundTripper) (*http.Response, error) {
		if !proofManifestWrite(r) {
			return transport.RoundTrip(r)
		}
		writes.Add(1)
		if err := proofConsume(transport.RoundTrip(r)); err != nil {
			return nil, err
		}
		// Before A's confirmation read, a distinct client completes B. A must
		// confirm its retained receipt rather than inspect only the new head.
		base, err := p.read(t.Context())
		if err != nil {
			return nil, err
		}
		b, err := p.reserve(t.Context(), base, bRows, 3)
		if err != nil {
			return nil, err
		}
		if err := p.stage(t.Context(), b, bRows); err != nil {
			return nil, err
		}
		if err := p.publish(t.Context(), b); err != nil {
			return nil, err
		}
		return nil, dropped
	})
	if err := fault.publish(t.Context(), a); err != nil {
		t.Fatal("superseded committed A misclassified:", err)
	}
	m, rows, err := p.snapshot(t.Context(), initial.Epoch)
	if err != nil || !slices.Equal(rows, bRows) || m.Next != 3 || writes.Load() != 1 || len(m.Receipts) != 5 {
		t.Fatalf("superseding publication: root=%+v writes=%d err=%v", m, writes.Load(), err)
	}
	if err := proofClient(t, p.path).confirm(t.Context(), a); err != nil {
		t.Fatal("new client could not reconcile superseded A:", err)
	}
	t.Log("lost A reply recovered from retained receipt after B had already published; no write replay")
}

func TestPublicationUnknownOutcomeRetainsGeneration(t *testing.T) {
	p, initial, d := proofFixture(t)
	rows := proofRows(t, d, "committed with lost acknowledgement", 1)
	g := proofStage(t, p, rows, 2)
	lost := errors.New("connection lost after write; confirmation unavailable")
	var wrote atomic.Bool
	var attempts atomic.Int32
	fault := proofIntercept(p, func(r *http.Request, transport http.RoundTripper) (*http.Response, error) {
		if proofManifestWrite(r) {
			attempts.Add(1)
			if err := proofConsume(transport.RoundTrip(r)); err != nil {
				return nil, err
			}
			wrote.Store(true)
			return nil, lost
		}
		if wrote.Load() {
			r.Body.Close()
			return nil, lost
		}
		return transport.RoundTrip(r)
	})
	err := fault.publish(t.Context(), g)
	if !errors.Is(err, errProofUnknown) || !errors.Is(err, lost) || attempts.Load() != 1 {
		t.Fatalf("unknown outcome: attempts=%d err=%v", attempts.Load(), err)
	}
	if !errors.Is(p.prune(t.Context()), vectordata.ErrUnsupported) {
		t.Fatal("unsafe cleanup")
	}
	m, actual, err := p.snapshot(t.Context(), initial.Epoch)
	if err != nil || m.Head != g.Token || !slices.Equal(actual, rows) {
		t.Fatalf("unknown published generation was lost: %+v, %v", m, err)
	}
	if err := proofClient(t, p.path).confirm(t.Context(), g); err != nil {
		t.Fatal("read-only recovery failed:", err)
	}
}

func TestPublicationInFlightCannotBeClassifiedByAbsentReceipt(t *testing.T) {
	for _, competing := range []bool{false, true} {
		t.Run(fmt.Sprintf("competing_%t", competing), func(t *testing.T) {
			p, initial, d := proofFixture(t)
			aRows, bRows := proofRows(t, d, "late A", 1), proofRows(t, d, "winning B", 2)
			a := proofStage(t, p, aRows, 2)
			var pending *http.Request
			var attempts int
			ctx, cancel := context.WithTimeout(context.Background(), 20*time.Second)
			defer cancel()
			lost := errors.New("publication still in flight")
			fault := proofIntercept(p, func(r *http.Request, transport http.RoundTripper) (*http.Response, error) {
				if !proofManifestWrite(r) {
					return transport.RoundTrip(r)
				}
				attempts++
				pending = r.Clone(ctx)
				var err error
				pending.Body, err = r.GetBody()
				r.Body.Close()
				if err != nil {
					return nil, err
				}
				return nil, lost
			})
			if err := fault.publish(t.Context(), a); !errors.Is(err, errProofUnknown) || !errors.Is(err, lost) || attempts != 1 {
				t.Fatalf("pending request: %v (%d attempts)", err, attempts)
			}
			if pending == nil {
				t.Fatal("no captured in-flight request")
			}
			defer pending.Body.Close()
			if proofRead(t, p).Head != "" {
				t.Fatal("capture unexpectedly delivered request")
			}
			if err := p.confirm(t.Context(), a); !errors.Is(err, errProofUnknown) {
				t.Fatal("absent receipt settled pending write:", err)
			}
			var b generation
			if competing {
				b = proofStage(t, p, bRows, 3)
				if err := p.publish(t.Context(), b); err != nil {
					t.Fatal(err)
				}
			}
			// Deliver the original captured request exactly once, after the caller
			// returned unknown. This is delayed delivery, not a retry.
			if err := proofConsume(p.http.Transport.RoundTrip(pending)); err != nil {
				t.Fatal(err)
			}
			m, actual, err := p.snapshot(t.Context(), initial.Epoch)
			want, head := aRows, a.Token
			if competing {
				want, head = bRows, b.Token
			}
			if err != nil || m.Head != head || !slices.Equal(actual, want) {
				t.Fatalf("late delivery: %+v, %v", m, err)
			}
			if _, err := p.readGeneration(t.Context(), a); err != nil {
				t.Fatal("unknown staging was reclaimed:", err)
			}
			confirmation := proofClient(t, p.path).confirm(t.Context(), a)
			if competing && !errors.Is(confirmation, errProofUnknown) || !competing && confirmation != nil {
				t.Fatalf("late publication recovery: %v", confirmation)
			}
		})
	}
}

func TestPublicationUnknownReservationCannotWriteAnotherOwnersSlot(t *testing.T) {
	p, initial, d := proofFixture(t)
	aRows, bRows := proofRows(t, d, "delayed reservation A", 1), proofRows(t, d, "reserved B", 1)
	var pending *http.Request
	ctx, cancel := context.WithTimeout(context.Background(), 20*time.Second)
	defer cancel()
	lost := errors.New("reservation in flight")
	fault := proofIntercept(p, func(r *http.Request, transport http.RoundTripper) (*http.Response, error) {
		if !proofManifestWrite(r) {
			return transport.RoundTrip(r)
		}
		pending = r.Clone(ctx)
		var err error
		pending.Body, err = r.GetBody()
		r.Body.Close()
		if err != nil {
			return nil, err
		}
		return nil, lost
	})
	a, err := fault.reserve(t.Context(), initial, aRows, 2)
	if !errors.Is(err, errProofUnknown) || !errors.Is(err, lost) || pending == nil {
		t.Fatalf("reservation outcome: %v", err)
	}
	defer pending.Body.Close()
	b := proofStage(t, p, bRows, 2)
	if a.Index != b.Index || a.Token == b.Token {
		t.Fatal("invalid competing slot fixture")
	}
	if err := p.publish(t.Context(), b); err != nil {
		t.Fatal(err)
	}
	if err := proofConsume(p.http.Transport.RoundTrip(pending)); err != nil {
		t.Fatal(err)
	}
	if err := p.stage(t.Context(), a, aRows); !errors.Is(err, errProofCorrupt) {
		t.Fatal("unconfirmed reservation wrote B's slot:", err)
	}
	m, actual, err := p.snapshot(t.Context(), initial.Epoch)
	if err != nil || len(m.Slots) != 1 || m.Head != b.Token || !slices.Equal(actual, bRows) {
		t.Fatalf("slot ownership lost: %+v, %v", m, err)
	}
}

