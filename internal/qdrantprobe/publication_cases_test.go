func TestPublicationPreparationFailureDoesNotAllocateKeysOrSlots(t *testing.T) {
	p, initial, d := proofFixture(t)
	bad := []vectordata.ModelRecord{
		{Key: int64(1), Data: map[string]any{"Body": "new"}, Vectors: map[string][]float32{"V": {1, 0}}},
		{Key: int64(1), Data: map[string]any{"Body": "duplicate"}, Vectors: map[string][]float32{"V": {1, 0}}},
	}
	if _, err := canonicalProofRecords(t.Context(), d, bad); !errors.Is(err, vectordata.ErrInvalidRecord) {
		t.Fatal("duplicate accepted:", err)
	}
	rawA, err := modelcodec.Encode(bad[0])
	if err != nil {
		t.Fatal(err)
	}
	rawB, err := modelcodec.Encode(bad[1])
	if err != nil {
		t.Fatal(err)
	}
	if _, err := p.reserve(t.Context(), initial, []string{string(rawA), string(rawB)}, 2); !errors.Is(err, vectordata.ErrInvalidRecord) {
		t.Fatal("reservation accepted duplicate snapshot:", err)
	}
	bad[1].Key = int64(2)
	bad[1].Vectors["V"] = []float32{1}
	if _, err := canonicalProofRecords(t.Context(), d, bad); err == nil {
		t.Fatal("invalid vector accepted")
	}
	rawB, err = modelcodec.Encode(bad[1])
	if err != nil {
		t.Fatal(err)
	}
	if _, err := p.reserve(t.Context(), initial, []string{string(rawA), string(rawB)}, 3); err == nil {
		t.Fatal("reservation accepted invalid-vector snapshot")
	}
	m := proofRead(t, p)
	if m.Next != initial.Next || m.Revision != initial.Revision || len(m.Slots) != 0 {
		t.Fatal("preparation failure consumed sequence or slot")
	}
}

