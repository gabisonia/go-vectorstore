const header = "// Code generated by vectordata-gen; DO NOT EDIT.\n"
const vectorPackage = "github.com/gabisonia/go-vectorstore/vectordata"

type Options struct {
	Dir, Model, Output, Name string
	Check                    bool
}

func Run(ctx context.Context, opts Options) error {
	if !token.IsIdentifier(opts.Model) || opts.Model == "_" {
		return fmt.Errorf("-type must name one local model type")
	}
	if opts.Dir == "" {
		opts.Dir = "."
	}
	dir, err := filepath.Abs(opts.Dir)
	if err != nil {
		return err
	}
	if resolved, err := filepath.EvalSymlinks(dir); err == nil {
		dir = resolved
	}
	if opts.Name == "" {
		opts.Name = opts.Model + "Fields"
	}
	if !token.IsIdentifier(opts.Name) || opts.Name == "_" || types.Universe.Lookup(opts.Name) != nil {
		return fmt.Errorf("invalid -name identifier")
	}
	if opts.Output == "" {
		opts.Output = strings.ToLower(opts.Model) + "_fields.gen.go"
	}
	if filepath.Base(opts.Output) != opts.Output || !strings.HasSuffix(opts.Output, ".go") || strings.HasPrefix(opts.Output, ".") || strings.HasPrefix(opts.Output, "_") || strings.HasSuffix(opts.Output, "_test.go") {
		return fmt.Errorf("-output must be a non-test .go basename in the current package")
	}
	path := filepath.Join(dir, opts.Output)
	previous, err := os.ReadFile(path)
	if err != nil && !os.IsNotExist(err) {
		return err
	}
	marker := header + "// Model: " + opts.Model + "\n"
	if err == nil && !bytes.HasPrefix(previous, []byte(marker)) {
		return fmt.Errorf("refusing to replace %s: not generated for %s", opts.Output, opts.Model)
	}
	pkg, err := load(ctx, dir, opts.Output)
	if err != nil {
		return err
	}
	if pkg.Path() == vectorPackage {
		return fmt.Errorf("generate references in the application model package, outside vectordata")
	}
	obj, ok := pkg.Scope().Lookup(opts.Model).(*types.TypeName)
	if !ok {
		return fmt.Errorf("model type %s not found", opts.Model)
	}
	model := types.Unalias(obj.Type())
	if named, ok := model.(*types.Named); ok && named.TypeParams().Len() != 0 && named.TypeArgs().Len() == 0 {
		return fmt.Errorf("generic models require an instantiated local alias")
	}
	if _, ok := model.Underlying().(*types.Struct); !ok {
		return fmt.Errorf("model %s must be a struct", opts.Model)
	}
	// TypeString uses predeclared spellings, as do emitted operands/conversions.
	// Reject shadowing instead of producing code with a different meaning.
	for _, name := range types.Universe.Names() {
		if pkg.Scope().Lookup(name) != nil {
			return fmt.Errorf("package shadows predeclared identifier %s; typed reference generation requires unshadowed builtins", name)
		}
	}
	if pkg.Scope().Lookup(opts.Name) != nil {
		return fmt.Errorf("generated variable %s already declared outside the output file", opts.Name)
	}
	fields, err := discover(model)
	if err != nil {
		return err
	}
	code, err := emit(pkg, opts, fields)
	if err != nil {
		return err
	}
	if opts.Check {
		if !bytes.Equal(previous, code) {
			return fmt.Errorf("%s is stale; run go generate", opts.Output)
		}
		return nil
	}
	if bytes.Equal(previous, code) {
		return nil
	}
	f, err := os.CreateTemp(dir, ".vectordata-gen-*.go")
	if err != nil {
		return err
	}
	defer os.Remove(f.Name())
	if _, err := f.Write(code); err != nil {
		f.Close()
		return err
	}
	if err := f.Chmod(0644); err != nil {
		f.Close()
		return err
	}
	if err := f.Close(); err != nil {
		return err
	}
	return os.Rename(f.Name(), path)
}

// Module-aware export data loading uses the active Go build configuration.
// -e allows initial generation and regeneration when application code refers to
// missing/stale output. Requested model types still must resolve completely.
// go list compiles dependencies but does not execute application init functions.
func load(ctx context.Context, dir, output string) (*types.Package, error) {
	command := exec.CommandContext(ctx, "go", "list", "-e", "-deps", "-export", "-json", ".")
	command.Dir = dir
	var stdout, stderr bytes.Buffer
	command.Stdout, command.Stderr = &stdout, &stderr
	if err := command.Run(); err != nil {
		return nil, fmt.Errorf("load package: %w: %s", err, strings.TrimSpace(stderr.String()))
	}
	type listed struct {
		Dir, ImportPath, Name, Export string
		GoFiles                       []string
	}
	exports := map[string]string{}
	var target listed
	decoder := json.NewDecoder(&stdout)
	for {
		var item listed
		if err := decoder.Decode(&item); err == io.EOF {
			break
		} else if err != nil {
			return nil, err
		}
		if item.Export != "" {
			exports[item.ImportPath] = item.Export
		}
		itemDir, err := filepath.EvalSymlinks(item.Dir)
		if err == nil && itemDir == dir {
			target = item
		}
	}
	if target.ImportPath == "" || target.Name == "" {
		return nil, fmt.Errorf("no Go package in %s", dir)
	}
	fset := token.NewFileSet()
	var files []*ast.File
	for _, name := range target.GoFiles {
		if name == output {
			continue
		}
		file, err := parser.ParseFile(fset, filepath.Join(dir, name), nil, 0)
		if err != nil {
			return nil, err
		}
		files = append(files, file)
	}
	imports := importer.ForCompiler(fset, "gc", func(path string) (io.ReadCloser, error) {
		file := exports[path]
		if file == "" {
			return nil, fmt.Errorf("missing export data for %s", path)
		}
		return os.Open(file)
	})
	var problems []error
	config := types.Config{Importer: imports, Error: func(err error) { problems = append(problems, err) }}
	pkg, _ := config.Check(target.ImportPath, fset, files, nil)
	if pkg == nil {
		return nil, fmt.Errorf("cannot resolve package: %v", problems)
	}
	return pkg, nil
}

type property struct {
	name, role, kind, tag    string
	original, value, element types.Type
}

func deref(t types.Type) types.Type {
	seen := map[types.Type]bool{}
	for {
		if seen[t] {
			return t
		}
		seen[t] = true
		pointer, ok := t.Underlying().(*types.Pointer)
		if !ok {
			return t
		}
		t = pointer.Elem()
	}
}

func infer(t types.Type) string {
	t = types.Unalias(deref(t))
	if named, ok := t.(*types.Named); ok && named.Obj().Pkg() != nil && named.Obj().Pkg().Path() == "time" && named.Obj().Name() == "Time" {
		return "time"
	}
	switch value := t.Underlying().(type) {
	case *types.Basic:
		switch value.Kind() {
		case types.String:
			return "string"
		case types.Bool:
			return "bool"
		case types.Int, types.Int8, types.Int16, types.Int32, types.Int64:
			return "int64"
		case types.Float32, types.Float64:
			return "float64"
		}
	case *types.Slice:
		if b, ok := value.Elem().Underlying().(*types.Basic); ok && b.Kind() == types.String {
			return "string_array"
		}
	}
	return "json"
}

func discover(model types.Type) ([]property, error) {
	var result []property
	keys := 0
	visiting := map[types.Type]bool{}
	var walk func(types.Type) error
	walk = func(t types.Type) error {
		t = deref(t)
		if visiting[t] {
			return nil
		}
		structure, ok := t.Underlying().(*types.Struct)
		if !ok {
			return nil
		}
		visiting[t] = true
		defer delete(visiting, t)
		for i := 0; i < structure.NumFields(); i++ {
			field := structure.Field(i)
			visible, _, _ := types.LookupFieldOrMethod(model, true, field.Pkg(), field.Name())
			tag, tagged := reflect.StructTag(structure.Tag(i)).Lookup("vectordata")
			if visible == field && tagged && tag != "-" {
				parts := strings.Split(tag, ",")
				role := parts[0]
				if role != "key" && role != "data" && role != "vector" {
					return fmt.Errorf("field %s has invalid vectordata role", field.Name())
				}
				if !field.Exported() {
					return fmt.Errorf("tagged field %s must be exported", field.Name())
				}
				if role != "vector" {
					p := property{name: field.Name(), role: role, tag: tag, original: field.Type(), value: deref(field.Type())}
					if len(p.name) > 63 {
						return fmt.Errorf("property %s exceeds model name limit", p.name)
					}
					for _, option := range parts[1:] {
						if value, found := strings.CutPrefix(option, "type="); found {
							p.kind = value
						}
					}
					if p.kind == "" {
						p.kind = infer(p.value)
					}
					if role == "key" {
						keys++
						p.kind = "key"
					} else {
						switch p.kind {
						case "string", "int64", "float64", "bool", "json", "time", "uuid", "bytes", "date_only", "time_only", "decimal":
						case "string_array", "int64_array", "float64_array", "bool_array", "uuid_array", "time_array", "date_only_array", "time_only_array", "decimal_array":
							slice, ok := p.value.Underlying().(*types.Slice)
							if !ok {
								return fmt.Errorf("array property %s requires a slice", p.name)
							}
							p.element = slice.Elem()
							if p.kind == "string_array" {
								b, ok := p.element.Underlying().(*types.Basic)
								if !ok || b.Kind() != types.String {
									return fmt.Errorf("string array %s requires string elements", p.name)
								}
							}
						default:
							return fmt.Errorf("unsupported data type %q for %s", p.kind, p.name)
						}
					}
					if invalid(p.original, map[types.Type]bool{}) {
						return fmt.Errorf("cannot resolve Go type of %s", p.name)
					}
					result = append(result, p)
				}
			}
			if field.Embedded() {
				if err := walk(field.Type()); err != nil {
					return err
				}
			}
		}
		return nil
	}
	if err := walk(model); err != nil {
		return nil, err
	}
	if keys != 1 {
		return nil, fmt.Errorf("model must have exactly one visible tagged key, found %d", keys)
	}
	return result, nil
}

func invalid(t types.Type, seen map[types.Type]bool) bool {
	if seen[t] {
		return false
	}
	seen[t] = true
	switch t := types.Unalias(t).(type) {
	case *types.Basic:
		return t.Kind() == types.Invalid
	case *types.Pointer:
		return invalid(t.Elem(), seen)
	case *types.Slice:
		return invalid(t.Elem(), seen)
	case *types.Array:
		return invalid(t.Elem(), seen)
	case *types.Map:
		return invalid(t.Key(), seen) || invalid(t.Elem(), seen)
	case *types.Named:
		return invalid(t.Underlying(), seen)
	case *types.Struct:
		for i := 0; i < t.NumFields(); i++ {
			if invalid(t.Field(i).Type(), seen) {
				return true
			}
		}
	case *types.TypeParam:
		return true
	}
	return false
}

func emit(pkg *types.Package, opts Options, fields []property) ([]byte, error) {
	aliases := map[string]string{}
	used := map[string]bool{"value": true, "values": true, "operands": true, "i": true, "model": true, opts.Name: true}
	for _, name := range pkg.Scope().Names() {
		used[name] = true
	}
	for _, p := range fields {
		used["_"+opts.Name+"_"+p.name] = true
	}
	qualify := func(p *types.Package) string {
		if p.Path() == pkg.Path() {
			return ""
		}
		if name := aliases[p.Path()]; name != "" {
			return name
		}
		base := p.Name()
		if p.Path() == vectorPackage {
			base = "vsdata"
		}
		name := base
		for n := 2; used[name]; n++ {
			name = base + strconv.Itoa(n)
		}
		used[name], aliases[p.Path()] = true, name
		return name
	}
	base := qualify(types.NewPackage(vectorPackage, "vectordata"))
	var body bytes.Buffer
	fmt.Fprintf(&body, "var %s = struct {\n", opts.Name)
	for _, p := range fields {
		fmt.Fprintf(&body, "%s _%s_%s\n", p.name, opts.Name, p.name)
	}
	body.WriteString("}{}\n\n")
	for _, p := range fields {
		ref := "_" + opts.Name + "_" + p.name
		if pkg.Scope().Lookup(ref) != nil {
			return nil, fmt.Errorf("generated type %s already declared", ref)
		}
		fmt.Fprintf(&body, "// %s %s: %s. Regenerate after changing tags.\n", p.role, p.name, p.kind)
		fmt.Fprintf(&body, "// Tag: %s\n", strconv.Quote(p.tag))
		fmt.Fprintf(&body, "type %s struct{}\n", ref)
		// Selector/type anchors make renamed/removed fields and changed Go types
		// fail compilation until regeneration. These functions are never invoked.
		original := types.TypeString(p.original, qualify)
		fmt.Fprintf(&body, "var _ func(%s) %s = func(model %s) %s { return model.%s }\n", opts.Model, original, opts.Model, original, p.name)
		value := types.TypeString(p.value, qualify)
		column := base + ".Column(" + strconv.Quote(p.name) + ")"
		fmt.Fprintf(&body, "func (%s) Name() string { return %q }\n", ref, p.name)
		for _, op := range []string{"Eq", "Ne"} {
			fmt.Fprintf(&body, "func (%s) %s(value %s) %s.Filter { return %s.%s(%s, value) }\n", ref, op, value, base, base, op, column)
		}
		fmt.Fprintf(&body, "func (%s) In(values ...%s) %s.Filter { operands := make([]any, len(values)); for i := range values { operands[i] = values[i] }; return %s.In(%s, operands...) }\n", ref, value, base, base, column)
		fmt.Fprintf(&body, "func (%s) IsNull() %s.Filter { return %s.Eq(%s, nil) }\n", ref, base, base, column)
		fmt.Fprintf(&body, "func (%s) IsNotNull() %s.Filter { return %s.Ne(%s, nil) }\n", ref, base, base, column)
		if p.kind != "json" && p.element == nil {
			for _, descending := range []bool{false, true} {
				method := "Asc"
				if descending {
					method = "Desc"
				}
				fmt.Fprintf(&body, "func (%s) %s() %s.SortField { return %s.SortField{Property: %q, Descending: %t} }\n", ref, method, base, base, p.name, descending)
			}
			if p.kind != "bool" {
				for _, op := range []string{"Gt", "Gte", "Lt", "Lte"} {
					fmt.Fprintf(&body, "func (%s) %s(value %s) %s.Filter { return %s.%s(%s, value) }\n", ref, op, value, base, base, op, column)
				}
			}
		}
		if p.element != nil {
			element := types.TypeString(p.element, qualify)
			operand := "value"
			if p.kind == "string_array" {
				operand = "string(value)"
			}
			fmt.Fprintf(&body, "func (%s) Contains(value %s) %s.Filter { return %s.Contains(%s, %s) }\n", ref, element, base, base, column, operand)
			for _, op := range []string{"ContainsAny", "ContainsAll"} {
				item := "values[i]"
				if p.kind == "string_array" {
					item = "string(values[i])"
				}
				fmt.Fprintf(&body, "func (%s) %s(values ...%s) %s.Filter { operands := make([]any,len(values)); for i := range values { operands[i] = %s }; return %s.%s(%s, operands...) }\n", ref, op, element, base, item, base, op, column)
			}
		}
		if p.kind == "json" {
			fmt.Fprintf(&body, "func (%s) Path(path ...string) %s.FieldRef { return %s.DataPath(%q, path...) }\n", ref, base, base, p.name)
			fmt.Fprintf(&body, "func (%s) IsJSONNull() %s.Filter { return %s.Eq(%s, %s.JSONNull{}) }\n", ref, base, base, column, base)
		}
		body.WriteString("\n")
	}
	var out bytes.Buffer
	fmt.Fprintf(&out, "%s// Model: %s\n\npackage %s\n\nimport (\n", header, opts.Model, pkg.Name())
	paths := make([]string, 0, len(aliases))
	for path := range aliases {
		paths = append(paths, path)
	}
	sort.Strings(paths)
	for _, path := range paths {
		fmt.Fprintf(&out, "%s %q\n", aliases[path], path)
	}
	out.WriteString(")\n\n")
	out.Write(body.Bytes())
	formatted, err := format.Source(out.Bytes())
	if err != nil {
		return nil, fmt.Errorf("format generated code: %w", err)
	}
	return formatted, nil
}
