#nullable enable
using CommunityToolkit.VectorData.Milvus;
using Microsoft.Extensions.VectorData;
using Milvus.Client;

using var store = new MilvusVectorStore(new MilvusClient("localhost", 19530), ownsClient: true);
var collection = store.GetCollection<string, Article>(args[1]);
switch (args[0])
{
    case "probe":
        break;
    case "seed":
        await collection.EnsureCollectionExistsAsync();
        await collection.UpsertAsync(new Article { Id = "seed", Body = "keep", Direction = new float[] { 0, 1 } });
        await collection.UpsertAsync(new Article { Id = "excluded", Body = "omit", Direction = new float[] { 1, 0 } });
        break;
    case "verify":
        var doc = await collection.GetAsync("go", new() { IncludeVectors = true });
        if (doc?.Body != "keep" || !doc.Direction.ToArray().SequenceEqual(new float[] { 1, 0 }))
            throw new InvalidOperationException("Go update did not round-trip");
        var nullable = await collection.GetAsync("null-text", new() { IncludeVectors = true });
        if (nullable == null || nullable.Body != null || !nullable.Direction.ToArray().SequenceEqual(new float[] { -1, 0 }))
            throw new InvalidOperationException($"NULL text read: id={nullable?.Id}, text=<{nullable?.Body ?? "(null)"}>, vector={string.Join(",", nullable?.Direction.ToArray() ?? Array.Empty<float>())}");
        var ids = new List<string>();
        await foreach (var hit in collection.SearchAsync(new ReadOnlyMemory<float>(new float[] { 1, 0 }), 3,
            new() { Filter = a => a.Body == "keep" }))
            ids.Add(hit.Record.Id);
        if (!ids.SequenceEqual(new[] { "go", "seed" })) throw new InvalidOperationException("Unexpected filtered ranking");
        doc.Body = "edited";
        await collection.UpsertAsync(doc);
        await collection.DeleteAsync("seed");
        break;
    case "verify-delete":
        if (await collection.GetAsync("go") != null) throw new InvalidOperationException("Go delete was not visible");
        break;
    default: throw new ArgumentException("Unknown phase");
}

public sealed class Article
{
    [VectorStoreKey(StorageName = "id", IsAutoGenerated = false)] public string Id { get; set; } = "";
    [VectorStoreData(StorageName = "body")] public string? Body { get; set; }
    [VectorStoreVector(2, StorageName = "direction", IndexKind = IndexKind.Flat, DistanceFunction = DistanceFunction.CosineSimilarity)]
    public ReadOnlyMemory<float> Direction { get; set; }
}
