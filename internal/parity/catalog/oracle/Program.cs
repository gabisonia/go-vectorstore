using Microsoft.Extensions.VectorData;
using Oracle.VectorData;

using var store = new OracleVectorStore(Environment.GetEnvironmentVariable("REFERENCE_ORACLE_DSN")!);
var collection = store.GetCollection<long, Article>(args[1]);
switch (args[0])
{
    case "create":
        await collection.EnsureCollectionExistsAsync();
        break;
    case "seed":
        await collection.UpsertAsync(new Article { ID = 7, CATEGORY = 1, DIRECTION = new float[] { 0, 1 } });
        await collection.UpsertAsync(new Article { ID = 8, CATEGORY = 2, DIRECTION = new float[] { 1, 0 } });
        break;
    case "verify":
        var p = await collection.GetAsync(42, new() { IncludeVectors = true });
        if (p?.CATEGORY != 1 || !p.DIRECTION.ToArray().SequenceEqual(new float[] { 0.8f, 0.6f }))
            throw new InvalidOperationException("Go update did not round-trip");
        var ids = new List<long>();
        await foreach (var hit in collection.SearchAsync(new ReadOnlyMemory<float>(new float[] { 1, 0 }), 3,
            new() { Filter = a => a.CATEGORY == 1 }))
            ids.Add(hit.Record.ID);
        if (!ids.SequenceEqual(new long[] { 42, 7 })) throw new InvalidOperationException("Filtered ranking: " + string.Join(",", ids));
        p.CATEGORY = 3;
        await collection.UpsertAsync(p);
        await collection.DeleteAsync(7);
        break;
    case "verify-delete":
        if (await collection.GetAsync(42) != null) throw new InvalidOperationException("Go delete was not visible");
        break;
    default: throw new ArgumentException("Unknown phase");
}

public sealed class Article
{
    [VectorStoreKey(IsAutoGenerated = false)] public long ID { get; set; }
    [VectorStoreData] public int? CATEGORY { get; set; }
    [VectorStoreVector(2, DistanceFunction = DistanceFunction.CosineDistance)] public ReadOnlyMemory<float> DIRECTION { get; set; }
}
