//go:build ignore

// The storage upgrade script builds this consumer twice, once per library version.
package main

import (
	"context"
	"errors"
	"fmt"
	"log"
	"os"
	"slices"
	"strings"
	"time"

	"github.com/gabisonia/go-vectorstore/stores/postgres"
	"github.com/gabisonia/go-vectorstore/stores/qdrant"
	"github.com/gabisonia/go-vectorstore/stores/redis"
	"github.com/gabisonia/go-vectorstore/stores/sqlite"
	"github.com/gabisonia/go-vectorstore/stores/sqlitevec"
	vd "github.com/gabisonia/go-vectorstore/vectordata"
	"github.com/jackc/pgx/v5/pgxpool"
)

func main() {
	if len(os.Args) != 4 {
		log.Fatal("expected write|verify layout endpoint")
	}
	ctx, cancel := context.WithTimeout(context.Background(), time.Minute)
	defer cancel()
	if err := run(ctx, os.Args[1], os.Args[2], os.Args[3]); err != nil {
		log.Fatal(err)
	}
}

func open(ctx context.Context, layout, endpoint string) (vd.ModelStore, func(), error) {
	switch {
	case strings.HasPrefix(layout, "sqlite"):
		opts := sqlite.StoreOptions{NativeIndexes: layout != "sqlite", VectorProjections: layout != "sqlite"}
		opener := sqlite.Open
		if layout == "sqlitevec" {
			opener = sqlitevec.Open
		}
		s, err := opener(ctx, endpoint, opts)
		return s, func() { s.Close() }, err
	case layout == "postgres":
		pool, err := pgxpool.New(ctx, endpoint)
		if err != nil {
			return nil, nil, err
		}
		s, err := postgres.NewVectorStore(pool, postgres.DefaultStoreOptions())
		return s, pool.Close, err
	case layout == "qdrant":
		s, err := qdrant.New(qdrant.StoreOptions{URL: endpoint, Namespace: "upgrade"})
		return s, func() { s.Close() }, err
	default:
		mode, native, _ := strings.Cut(layout, "-")
		s, err := redis.New(redis.StoreOptions{Addr: endpoint, Namespace: "upgrade" + strings.ReplaceAll(layout, "-", ""), StorageMode: redis.StorageMode(mode), NativeIndexes: native != ""})
		return s, func() { s.Close() }, err
	}
}

func run(ctx context.Context, phase, layout, endpoint string) error {
	s, closeStore, err := open(ctx, layout, endpoint)
	if err != nil {
		return err
	}
	defer closeStore()
	const precise = int64(9007199254740993)
	d := vd.CollectionDefinition{
		Key: vd.KeyProperty{Name: "ID", Type: vd.KeyInt64, AutoGenerated: true},
		Data: []vd.DataProperty{
			{Name: "Number", Type: vd.TypeInt64, IsIndexed: layout == "sqlite-projected" || layout == "sqlitevec"},
			{Name: "Body", Type: vd.TypeString, IsFullTextIndexed: layout == "json-text"},
		},
		Vectors: []vd.VectorProperty{{Name: "V", Dimensions: 2, Metric: vd.DistanceCosine, Optional: true}},
	}
	if strings.HasSuffix(layout, "-native") || layout == "json-text" {
		d.Vectors[0].Index = &vd.VectorIndexOptions{Method: vd.IndexMethodFlat, Metric: vd.DistanceCosine}
	}
	row := vd.ModelRecord{Data: map[string]any{"Number": precise, "Body": "fixture"}}
	if phase == "write" {
		c, err := s.EnsureModelCollection(ctx, "items", d, vd.ModelCollectionOptions{})
		if err != nil {
			return err
		}
		withVector := row
		withVector.Vectors = map[string][]float32{"V": {1, 0}}
		keys, err := c.Insert(ctx, []vd.ModelRecord{withVector, row})
		if err != nil {
			return err
		}
		if len(keys) != 2 || keys[0] != int64(1) || keys[1] != int64(2) {
			return fmt.Errorf("unexpected producer keys %v", keys)
		}
		return nil
	}
	if phase != "verify" {
		return fmt.Errorf("unknown phase %s", phase)
	}
	incompatible := d
	incompatible.Vectors = slices.Clone(d.Vectors)
	incompatible.Vectors[0].Dimensions++
	if _, err := s.EnsureModelCollection(ctx, "items", incompatible, vd.ModelCollectionOptions{}); !errors.Is(err, vd.ErrSchemaMismatch) {
		return fmt.Errorf("expected registered schema mismatch, got %v", err)
	}
	c, err := s.GetModelCollection("items", d, vd.ModelCollectionOptions{})
	if err != nil {
		return err
	}
	// A requested downgrade from JSON to hash must leave the source readable.
	if layout == "json" {
		if err := c.(*redis.Collection).MigrateToHashStorage(ctx); !errors.Is(err, vd.ErrUnsupported) {
			return fmt.Errorf("unexpected JSON to hash migration result: %v", err)
		}
	}
	for _, key := range []int64{1, 2} {
		got, err := c.Get(ctx, key, vd.RetrievalOptions{IncludeVectors: true})
		if err != nil {
			return err
		}
		expected := []float32(nil)
		if key == 1 {
			expected = []float32{1, 0}
		}
		if got.Key != key || got.Data["Number"] != precise || got.Data["Body"] != "fixture" || !slices.Equal(got.Vectors["V"], expected) {
			return fmt.Errorf("changed record %v", got)
		}
	}
	hits, err := c.Search(ctx, []float32{1, 0}, 2, vd.ModelSearchOptions{})
	if err != nil {
		return err
	}
	if len(hits) != 1 || hits[0].Record.Key != int64(1) || hits[0].Distance != 0 {
		return fmt.Errorf("unexpected search result %v", hits)
	}
	keys, err := c.Insert(ctx, []vd.ModelRecord{row})
	if err != nil {
		return err
	}
	if len(keys) != 1 || keys[0] != int64(3) {
		return fmt.Errorf("lost generated sequence: %v", keys)
	}
	return nil
}
